///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CModule1::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	HRESULT hr = S_OK;

	(void)ipTask;
	(void)ipCaller;
	(void)context;

	const bool resetEdge = (m_Inputs.resetReq != false) && !m_prevResetReq;
	m_prevResetReq = (m_Inputs.resetReq != false);
	if (resetEdge)
	{
		ResetRuntimeState();
	}

	m_Outputs.positionRel = m_Inputs.positionAct;
	m_Outputs.error = m_Inputs.refValue - m_Inputs.positionAct;

	const double u = StepController(
		m_Inputs.refValue,
		m_Inputs.ffValue,
		m_Inputs.positionAct);

	m_Outputs.controlInput = u;

	return hr;
}
