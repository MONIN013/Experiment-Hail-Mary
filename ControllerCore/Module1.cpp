void CModule1::ResetRuntimeState()
{
	m_PidS1 = 0.0;
	m_PidS2 = 0.0;
	m_LeadS1 = 0.0;
	m_LeadS2 = 0.0;
	m_NotchS1 = 0.0;
	m_NotchS2 = 0.0;
	m_ResoS1 = 0.0;
	m_ResoS2 = 0.0;
}

double CModule1::StepController(double refValue, double ffValue, double positionRel)
{
	if (!std::isfinite(refValue) || !std::isfinite(ffValue) || !std::isfinite(positionRel))
	{
		return 0.0;
	}

	const double error = refValue - positionRel;
	double y = error;

	if (m_EnableParams.enablePid)
	{
		y = ApplyPid(y);
	}

	if (m_EnableParams.enableLead)
	{
		y = ApplyBiquad(y,
			m_LeadParams.leadB0,
			m_LeadParams.leadB1,
			m_LeadParams.leadB2,
			m_LeadParams.leadA1,
			m_LeadParams.leadA2,
			m_LeadS1, m_LeadS2);
	}

	if (m_EnableParams.enableNotch)
	{
		y = ApplyBiquad(y,
			m_NotchParams.notchB0, m_NotchParams.notchB1, m_NotchParams.notchB2,
			m_NotchParams.notchA1, m_NotchParams.notchA2,
			m_NotchS1, m_NotchS2);
	}

	if (m_EnableParams.enableReso)
	{
		y = ApplyBiquad(y,
			m_ResoParams.resoB0, m_ResoParams.resoB1, m_ResoParams.resoB2,
			m_ResoParams.resoA1, m_ResoParams.resoA2,
			m_ResoS1, m_ResoS2);
	}

	return y + ffValue;
}

double CModule1::ApplyPid(double error)
{
	return ApplyBiquad(error,
		m_PIDParams.pidB0,
		m_PIDParams.pidB1,
		m_PIDParams.pidB2,
		m_PIDParams.pidA1,
		m_PIDParams.pidA2,
		m_PidS1, m_PidS2);
}

double CModule1::ApplyBiquad(double x, double b0, double b1, double b2, double a1, double a2, double& s1, double& s2)
{
	if (!std::isfinite(x))
	{
		return 0.0;
	}
	const double y = b0 * x + s1;
	const double s1next = b1 * x - a1 * y + s2;
	const double s2next = b2 * x - a2 * y;
	s1 = s1next;
	s2 = s2next;
	if (!std::isfinite(y))
	{
		return 0.0;
	}
	return y;
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CModule1::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID; 
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CModule1::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if ( m_spCyclicCaller )
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller	= NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}

