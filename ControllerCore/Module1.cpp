void CModule1::ResetRuntimeStates()
{
	m_pidS1 = 0.0;
	m_pidS2 = 0.0;
	m_leadS1 = 0.0;
	m_leadS2 = 0.0;
	m_notchS1 = 0.0;
	m_notchS2 = 0.0;
	m_resoS1 = 0.0;
	m_resoS2 = 0.0;
}

double CModule1::StepController(double refValue, double ffValue, double positionAct)
{
	if (!std::isfinite(refValue) || !std::isfinite(ffValue) || !std::isfinite(positionAct))
	{
		return 0.0;
	}

	const double error = refValue - positionAct;
	double y = error;

	if (m_EnableParams.enable_pid)
	{
		y = ApplyPid(y);
	}

	if (m_EnableParams.enable_lead)
	{
		y = ApplyBiquad(y,
			m_LeadParams.notch_b0,
			m_LeadParams.notch_b1,
			m_LeadParams.notch_b2,
			m_LeadParams.notch_a1,
			m_LeadParams.notch_a2,
			m_leadS1, m_leadS2);
	}

	if (m_EnableParams.enable_notch)
	{
		y = ApplyBiquad(y,
			m_NotchParams.notch_b0, m_NotchParams.notch_b1, m_NotchParams.notch_b2,
			m_NotchParams.notch_a1, m_NotchParams.notch_a2,
			m_notchS1, m_notchS2);
	}

	if (m_EnableParams.enable_reso)
	{
		y = ApplyBiquad(y,
			m_ResoParams.notch_b0, m_ResoParams.notch_b1, m_ResoParams.notch_b2,
			m_ResoParams.notch_a1, m_ResoParams.notch_a2,
			m_resoS1, m_resoS2);
	}

	return y + ffValue;
}

double CModule1::ApplyPid(double error)
{
	return ApplyBiquad(error,
		m_PIDParams.notch_b0,
		m_PIDParams.notch_b1,
		m_PIDParams.notch_b2,
		m_PIDParams.notch_a1,
		m_PIDParams.notch_a2,
		m_pidS1, m_pidS2);
}

double CModule1::ApplyBiquad(double x, double b0, double b1, double b2, double a1, double a2, double& s1, double& s2)
{
	if (!std::isfinite(x))
	{
		return 0.0;
	}
	const double y = b0 * x + s1;
	const double s1next = b1 * x - a1 * y + s2;
	const double s2next = b2 * x - a2 * y;
	s1 = s1next;
	s2 = s2next;
	if (!std::isfinite(y))
	{
		return 0.0;
	}
	return y;
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CModule1::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID; 
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CModule1::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if ( m_spCyclicCaller )
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller	= NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}

