///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CModule1::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	HRESULT hr = S_OK;

	(void)ipTask;
	(void)ipCaller;
	(void)context;

	const bool resetEdge = (m_Inputs.resetReq != false) && !m_prevResetReq;
	m_prevResetReq = (m_Inputs.resetReq != false);
	if (resetEdge)
	{
		ResetRuntimeState();
	}

	if (m_SosApplyRevision != m_controllerAlgorithm.LastSeenRevision())
	{
		m_controllerAlgorithm.ApplyParameters(
			m_SosCoefficients,
			m_SosSectionCount,
			m_SosApplyRevision,
			{ m_HigsEnabled, m_HigsGain, m_HigsOmegaTs, m_HigsPreSectionCount });
	}

	m_Outputs.error = controllercore::ControllerAlgorithm::ComputeError(
		m_Inputs.refValue,
		m_Inputs.positionAct);

	const double u = m_controllerAlgorithm.Step(
		m_Inputs.refValue,
		m_Inputs.ffValue,
		m_Inputs.positionAct);

	m_Outputs.controlInput = u;
	m_Outputs.appliedRevision = m_controllerAlgorithm.AppliedRevision();
	m_Outputs.processedRevision = m_controllerAlgorithm.ProcessedRevision();
	m_Outputs.parameterErrorCode = m_controllerAlgorithm.ParameterErrorCode();
	m_Outputs.higsInput = m_controllerAlgorithm.HigsInput();
	m_Outputs.higsOutput = m_controllerAlgorithm.HigsOutput();
	m_Outputs.higsMode = m_controllerAlgorithm.HigsMode();

	return hr;
}
///</AutoGeneratedContent>

void CModule1::ResetRuntimeState()
{
	m_controllerAlgorithm.Reset();
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CModule1::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID; 
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CModule1::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if ( m_spCyclicCaller )
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller	= NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}

