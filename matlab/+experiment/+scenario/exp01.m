function out = exp01(varargin)
% exp01  Pure configuration for the system-identification experiment.
p = inputParser;
p.addParameter("cfg", experiment.ExperimentConfig.defaults(), ...
  @(x) isa(x, "experiment.ExperimentConfig"));
p.addParameter("Tend", 100, @is_positive_scalar);
p.addParameter("Tcycle", 10, @is_positive_scalar);
p.addParameter("initial_phase", 0, @is_finite_scalar);
p.addParameter("f0", 0.5, @is_positive_scalar);
p.addParameter("f1", 4000, @is_positive_scalar);
p.addParameter("amplitude_A", 0.25, @is_nonnegative_scalar);
p.addParameter("transient_cycles", 2, @is_nonnegative_integer);
p.addParameter("Jn", 7.1e-5, @is_positive_scalar);
p.addParameter("Dn", 5.325e-4, @is_nonnegative_scalar);
p.addParameter("sample_delay", 4, @is_nonnegative_integer);
p.addParameter("hold_margin_s", 1.0, @is_nonnegative_scalar);
p.addParameter("save_results", true, @is_logical_scalar);
p.addParameter("require_logger_records", true, @is_logical_scalar);
p.addParameter("result_dir", experiment.scenario.default_result_dir(), @is_text_scalar);
p.parse(varargin{:});
o = p.Results;

cfg = o.cfg;
Ts = 1 / double(cfg.env.task_rate_hz);
chirp = experiment.waveform.periodic_chirp( ...
  "Ts", Ts, "Tend", o.Tend, "Tcycle", o.Tcycle, ...
  "f0", o.f0, "f1", o.f1, "A", o.amplitude_A, ...
  "initial_phase", o.initial_phase);
cycle_n = round(double(o.Tcycle) / Ts);
repeat_count = round(double(o.Tend) / double(o.Tcycle));
if abs(cycle_n * Ts - double(o.Tcycle)) > 16 * eps(double(o.Tcycle)) || ...
    abs(repeat_count * double(o.Tcycle) - double(o.Tend)) > 16 * eps(double(o.Tend))
  error("experiment:scenario:invalidExp01Duration", ...
    "Tcycle must align to Ts and Tend must contain an integer number of cycles.");
end
if cycle_n > double(cfg.env.table_max_n)
  error("experiment:scenario:exp01CycleTooLong", ...
    "One chirp cycle has %d samples but table_max_n is %d.", ...
    cycle_n, double(cfg.env.table_max_n));
end

raw_cycle = double(chirp.signal(1:cycle_n));
cycle_mean_before_centering_A = mean(raw_cycle);
cycle_signal = raw_cycle - cycle_mean_before_centering_A;
cycle_peak = max(abs(cycle_signal));
if double(o.amplitude_A) > 0
  if cycle_peak == 0
    error("experiment:scenario:degenerateExp01Excitation", ...
      "The requested chirp cycle has no nonzero zero-mean excitation.");
  end
  cycle_signal = cycle_signal * (double(o.amplitude_A) / cycle_peak);
end
chirp.signal = repmat(cycle_signal, repeat_count, 1);
chirp.cycle_mean_before_centering_A = cycle_mean_before_centering_A;
chirp.applied_mean_A = mean(cycle_signal);
chirp.applied_peak_A = max(abs(cycle_signal));

result_dir = string(o.result_dir);
paths = struct( ...
  "result_dir", result_dir, ...
  "chirp_result", fullfile(result_dir, "chirp_result.mat"), ...
  "plant", fullfile(result_dir, "plant.mat"), ...
  "runner", fullfile(result_dir, "exp01_runner.mat"));
save_path = "";
if logical(o.save_results)
  save_path = paths.runner;
end
cfg = experiment.scenario.configure_run( ...
  cfg, zeros(cycle_n, 1), cycle_signal, zeros(cycle_n, 1), ...
  experiment.ControllerConfig.p_only(0), ...
  "repeat_count", repeat_count, "hold_margin_s", o.hold_margin_s, ...
  "save_path", save_path);

out = struct( ...
  "name", "exp01", ...
  "cfg", cfg, ...
  "chirp", chirp, ...
  "Ts", Ts, ...
  "Tend", double(o.Tend), ...
  "Tcycle", double(o.Tcycle), ...
  "transient_cycles", double(o.transient_cycles), ...
  "nominal", struct("Jn", double(o.Jn), "Dn", double(o.Dn), ...
    "Ndelay", double(o.sample_delay)), ...
  "save_results", logical(o.save_results), ...
  "require_logger_records", logical(o.require_logger_records), ...
  "expected_sample_count", double(chirp.sample_count), ...
  "paths", paths);
end

function tf = is_positive_scalar(x), tf = isnumeric(x) && isscalar(x) && isfinite(x) && x > 0; end
function tf = is_nonnegative_scalar(x), tf = isnumeric(x) && isscalar(x) && isfinite(x) && x >= 0; end
function tf = is_finite_scalar(x), tf = isnumeric(x) && isscalar(x) && isfinite(x); end
function tf = is_nonnegative_integer(x), tf = is_nonnegative_scalar(x) && fix(x) == x; end
function tf = is_logical_scalar(x), tf = islogical(x) && isscalar(x); end
function tf = is_text_scalar(x), tf = ischar(x) || (isstring(x) && isscalar(x)); end
