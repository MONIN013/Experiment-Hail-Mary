classdef PlantConfig
  properties
    motor = struct( ...
      "inertia", 0.02, ...
      "damping", 0.2, ...
      "ratedTorque", 1.2, ...
      "tauLimit", 2.4, ...
      "velLimit", 2*pi*60, ...
      "maxPermille", 0.0, ...
      "encoderResolution", uint32(8388608))
    load = struct( ...
      "inertia", 0.02, ...
      "damping", 0.2, ...
      "ratedTorque", 1.2, ...
      "tauLimit", 2.4, ...
      "velLimit", 2*pi*60, ...
      "encoderResolution", uint32(8388608))
    coupling = struct( ...
      "stiffness", 50.0, ...
      "damping", 0.5)
  end

  methods (Static)
    function out = from_struct(s)
      out = experiment.PlantConfig();
      if nargin < 1 || isempty(s)
        out = out.normalize();
        return;
      end
      if isa(s, "experiment.PlantConfig")
        out = s.normalize();
        return;
      end
      if ~isstruct(s)
        error("experiment:plant:invalid", ...
          "PlantConfig.from_struct accepts only struct or PlantConfig.");
      end

      required_fields = ["motor", "load", "coupling"];
      actual_fields = string(fieldnames(s));
      if ~isempty(setdiff(actual_fields, required_fields))
        error("experiment:plant:invalid", ...
          "PlantConfig accepts only motor/load/coupling fields.");
      end

      for k = 1:numel(required_fields)
        key = char(required_fields(k));
        if ~isfield(s, key)
          error("experiment:plant:invalid", ...
            "PlantConfig requires '%s'.", key);
        end
      end

      out.motor = normalize_axis_struct(s.motor, "motor");
      out.load = normalize_axis_struct(s.load, "load");
      out.coupling = normalize_coupling_struct(s.coupling);
      out = out.normalize();
    end
  end

  methods
    function out = normalize(obj)
      out = obj;
      out.motor = normalize_axis_struct(out.motor, "motor");
      out.load = normalize_axis_struct(out.load, "load");
      out.coupling = normalize_coupling_struct(out.coupling);
    end

    function s = to_struct(obj)
      out = obj.normalize();
      s = struct( ...
        "motor", out.motor, ...
        "load", out.load, ...
        "coupling", out.coupling);
    end
  end
end

function axis = normalize_axis_struct(axis, label)
if nargin < 2
  label = "axis";
end
if strcmp(label, "motor")
  defaults = struct( ...
    "inertia", 0.02, ...
    "damping", 0.2, ...
    "ratedTorque", 1.2, ...
    "tauLimit", 2.4, ...
    "velLimit", 2*pi*60, ...
    "maxPermille", 0.0, ...
    "encoderResolution", uint32(8388608));
else
  defaults = struct( ...
    "inertia", 0.02, ...
    "damping", 0.2, ...
    "ratedTorque", 1.2, ...
    "tauLimit", 2.4, ...
    "velLimit", 2*pi*60, ...
    "encoderResolution", uint32(8388608));
end
if ~isstruct(axis)
  error("experiment:plant:invalid", ...
    "%s must be a struct.", label);
end
actual_fields = string(fieldnames(axis));
expected_fields = string(fieldnames(defaults));
unknown = setdiff(actual_fields, expected_fields);
if ~isempty(unknown)
  error("experiment:plant:invalid", ...
    "%s accepts only %s.", label, strjoin(expected_fields, ", "));
end
missing = setdiff(expected_fields, actual_fields);
if ~isempty(missing)
  error("experiment:plant:invalid", ...
    "%s is missing %s.", label, strjoin(missing, ", "));
end
if strcmp(label, "motor")
  axis = struct( ...
    "inertia", double(axis.inertia), ...
    "damping", double(axis.damping), ...
    "ratedTorque", double(axis.ratedTorque), ...
    "tauLimit", double(axis.tauLimit), ...
    "velLimit", double(axis.velLimit), ...
    "maxPermille", double(axis.maxPermille), ...
    "encoderResolution", uint32(axis.encoderResolution));
else
  axis = struct( ...
    "inertia", double(axis.inertia), ...
    "damping", double(axis.damping), ...
    "ratedTorque", double(axis.ratedTorque), ...
    "tauLimit", double(axis.tauLimit), ...
    "velLimit", double(axis.velLimit), ...
    "encoderResolution", uint32(axis.encoderResolution));
end
end

function coupling = normalize_coupling_struct(coupling)
if ~isstruct(coupling)
  error("experiment:plant:invalid", ...
    "coupling must be a struct.");
end
expected_fields = ["stiffness", "damping"];
actual_fields = string(fieldnames(coupling));
unknown = setdiff(actual_fields, expected_fields);
if ~isempty(unknown)
  error("experiment:plant:invalid", ...
    "coupling accepts only stiffness and damping.");
end
missing = setdiff(expected_fields, actual_fields);
if ~isempty(missing)
  error("experiment:plant:invalid", ...
    "coupling is missing %s.", strjoin(missing, ", "));
end
coupling = struct( ...
  "stiffness", double(coupling.stiffness), ...
  "damping", double(coupling.damping));
end
