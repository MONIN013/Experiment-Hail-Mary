function result = run_exp04(scenario, varargin)
% run_exp04  Execute a complete ILC campaign with numeric checkpoints.

p = inputParser;
p.addParameter("collector", @experiment.exp0n.run_and_collect, ...
  @(x) isa(x, "function_handle"));
p.addParameter("dashboard_visibility", "auto", ...
  @(x) islogical(x) || ischar(x) || (isstring(x) && isscalar(x)));
p.addParameter("logger_archiver", @experiment.exp04.archive_trial_logger, ...
  @(x) isa(x, "function_handle"));
p.parse(varargin{:});
validate_scenario(scenario);

trial_count = double(scenario.trial_count);
reference = double(scenario.trajectory.p(:));
t = double(scenario.trajectory.t(:));
sample_count = numel(reference);
history = initialize_history(scenario, t, reference);
completed_trials = 0;
dashboard = [];
runs = cell(1, trial_count);
loggers = cell(1, trial_count);
[paths, artifacts] = prepare_artifacts(scenario, trial_count);

try
  for trial = 1:trial_count
    cfg = scenario.cfg;
    cfg.ff_profile = history.f(:, trial);
    if scenario.save_results
      cfg.save_path = paths.trial_runner(trial);
    end
    cfg = cfg.normalize();
    cfg.validate();

    collected = p.Results.collector(cfg);
    experiment.exp0n.assert_run_contract(collected.run);
    [signals, trial_metrics] = experiment.exp02.signals_from_logger_bin( ...
      collected.logger_bin, "expected_sample_count", sample_count);
    runs{trial} = collected.run;
    loggers{trial} = collected.logger_bin;

    history.y(:, trial) = signals.position_act;
    history.e(:, trial) = signals.error;
    history.eNorm(trial) = norm(signals.error);
    history.f(:, trial) = cfg.ff_profile;
    history.ffApplied(:, trial) = signals.applied_feedforward;
    history.u(:, trial) = signals.control_input;
    history.maxAbsInput(trial) = max(abs(signals.control_input));
    history.maxAbsFeedforward(trial) = max(abs(cfg.ff_profile));
    history.maxAbsTotalInput(trial) = max(abs(signals.current_cmd));
    history.maxAbsError(trial) = trial_metrics.max_abs_error;
    completed_trials = trial;
    if scenario.save_results
      archived_logger = p.Results.logger_archiver( ...
        collected.logger_bin, paths.trial_logger(trial));
      validate_archived_logger(archived_logger, trial);
      history.trialLoggerPaths(trial) = string(archived_logger.path);
      history.trialLoggerRecordCount(trial) = ...
        double(archived_logger.record_count);
    end

    dashboard = experiment.exp04.update_trial_dashboard( ...
      dashboard, t, reference, signals.position_act, signals.error, ...
      signals.applied_feedforward, signals.feedback_input, ...
      trial, trial_count, ...
      "total_input", signals.current_cmd, ...
      "visible", p.Results.dashboard_visibility);

    if trial > 1 && experiment.exp04.error_norm_increased( ...
        history.eNorm(trial - 1), history.eNorm(trial))
      history.errorIncreased(trial) = true;
      history.stopReason = "error_increased";
      error("experiment:exp04:errorNormIncreased", ...
        "Trial %d error norm increased from %.6g to %.6g.", ...
        trial, history.eNorm(trial - 1), history.eNorm(trial));
    end

    if trial < trial_count
      learning_count = double(scenario.learning_sample_count);
      [next_active_ff, limit] = experiment.exp04.learning_update( ...
        cfg.ff_profile(1:learning_count), signals.error(1:learning_count), ...
        scenario.learning_filters, ...
        "alpha", scenario.alpha, "Npad", scenario.Npad, ...
        "transient_samples", scenario.transient_samples, ...
        "max_input", scenario.max_input_A);
      if ~limit.ok
        history.stopReason = "input_limit";
        error("experiment:exp04:inputLimitExceeded", ...
          "Next feedforward %.6g A exceeds the %.6g A limit.", ...
          limit.max_abs_input, limit.limit);
      end
      next_ff = [next_active_ff; ...
        zeros(sample_count - learning_count, 1)];
      history.f(:, trial + 1) = next_ff;
    end
  end
catch cause
  history = finalize_history(history, completed_trials);
  if history.stopReason == "completed"
    history.stopReason = string(cause.identifier);
  end
  if scenario.save_results
    experiment.exp04.checkpoint_partial_history( ...
      paths.result, history, completed_trials, history.stopReason);
  end
  close_batch_dashboard(dashboard);
  rethrow(cause);
end

history = finalize_history(history, completed_trials);
metrics = campaign_metrics(history);
if scenario.save_results
  Kd = scenario.Kd;
  stability = scenario.stability;
  learning_filters = scenario.learning_filters;
  save(paths.result, "t", "history", "Kd", "stability", "learning_filters");
  artifacts.saved = true;
end
close_batch_dashboard(dashboard);

signals = struct( ...
  "time_s", t, "reference", history.r, "position", history.y, ...
  "error", history.e, "feedforward", history.f, ...
  "applied_feedforward", history.ffApplied, ...
  "control_input", history.u);
result = struct( ...
  "scenario", scenario, "run", {runs}, "logger", {loggers}, ...
  "signals", signals, "metrics", metrics, "artifacts", artifacts, ...
  "history", history);
end

function history = initialize_history(scenario, t, reference)
trial_count = double(scenario.trial_count);
sample_count = numel(reference);
history = struct( ...
  "t", t, "r", repmat(reference, 1, trial_count), ...
  "y", zeros(sample_count, trial_count), ...
  "e", zeros(sample_count, trial_count), ...
  "eNorm", zeros(1, trial_count), ...
  "f", zeros(sample_count, trial_count), ...
  "ffApplied", zeros(sample_count, trial_count), ...
  "u", zeros(sample_count, trial_count), ...
  "maxAbsInput", zeros(1, trial_count), ...
  "maxAbsFeedforward", zeros(1, trial_count), ...
  "maxAbsTotalInput", zeros(1, trial_count), ...
  "maxAbsError", zeros(1, trial_count), ...
  "errorIncreased", false(1, trial_count), ...
  "convergencePeak", repmat( ...
    scenario.learning_filters.max_convergence_gain, 1, trial_count), ...
  "trialLoggerPaths", strings(1, trial_count), ...
  "trialLoggerRecordCount", zeros(1, trial_count), ...
  "maxSensitivity", scenario.stability.max_sensitivity, ...
  "sensitivityLimitExceeded", scenario.stability.limit_exceeded, ...
  "completedTrials", 0, "stopReason", "completed");
end

function history = finalize_history(history, completed_trials)
matrix_fields = ["r", "y", "e", "f", "ffApplied", "u"];
vector_fields = ["eNorm", "maxAbsInput", "maxAbsFeedforward", ...
  "maxAbsTotalInput", "maxAbsError", "errorIncreased", "convergencePeak", ...
  "trialLoggerRecordCount"];
for name = matrix_fields
  history.(name) = history.(name)(:, 1:completed_trials);
end
for name = vector_fields
  history.(name) = history.(name)(1:completed_trials);
end
history.trialLoggerPaths = history.trialLoggerPaths(1:completed_trials);
history.completedTrials = completed_trials;
if completed_trials > 0
  [history.bestErrorNorm, history.bestTrial] = min(history.eNorm);
else
  history.bestErrorNorm = NaN;
  history.bestTrial = NaN;
end
history.trialSummary = table( ...
  (1:completed_trials)', history.eNorm(:), history.maxAbsError(:), ...
  history.maxAbsInput(:), history.maxAbsFeedforward(:), ...
  history.maxAbsTotalInput(:), history.errorIncreased(:), ...
  history.convergencePeak(:), history.convergencePeak(:) < 1, ...
  VariableNames=["trial", "errorNorm", "maxAbsError", ...
    "maxAbsInputA", "maxAbsFeedforwardA", "maxAbsTotalInputA", ...
    "errorIncreased", "convergencePeak", "convergenceSatisfied"]);
end

function metrics = campaign_metrics(history)
metrics = struct( ...
  "completed_trials", history.completedTrials, ...
  "error_norm", history.eNorm, ...
  "best_trial", history.bestTrial, ...
  "best_error_norm", history.bestErrorNorm, ...
  "monotonic_decrease", all(diff(history.eNorm) < 0), ...
  "max_abs_feedforward_A", max(history.maxAbsFeedforward), ...
  "max_abs_total_input_A", max(history.maxAbsTotalInput), ...
  "convergence_peak", max(history.convergencePeak));
end

function [paths, artifacts] = prepare_artifacts(scenario, trial_count)
paths = struct("result", "", "trial_runner", strings(1, trial_count), ...
  "trial_logger", strings(1, trial_count));
artifacts = struct("saved", false, "run_directory", "", ...
  "result", "", "trial_runner", strings(1, trial_count), ...
  "trial_logger", strings(1, trial_count), ...
  "image_files", strings(0, 1));
if ~scenario.save_results
  return;
end
base = fullfile(scenario.result_dir, "exp04_runs");
if ~isfolder(base), mkdir(base); end
stamp = string(datetime("now", "Format", "yyyyMMdd_HHmmss_SSS"));
run_directory = fullfile(base, stamp);
mkdir(run_directory);
paths.result = fullfile(run_directory, "ilc_result.mat");
for trial = 1:trial_count
  paths.trial_runner(trial) = fullfile( ...
    run_directory, sprintf("trial%02d.mat", trial));
  paths.trial_logger(trial) = fullfile( ...
    run_directory, sprintf("trial%02d_logger.bin", trial));
end
artifacts.run_directory = string(run_directory);
artifacts.result = string(paths.result);
artifacts.trial_runner = paths.trial_runner;
artifacts.trial_logger = paths.trial_logger;
end

function validate_archived_logger(capture, trial)
if ~isstruct(capture) || ~isscalar(capture) || ...
    ~all(isfield(capture, ["path", "record_count"])) || ...
    strlength(string(capture.path)) == 0 || ...
    ~(isnumeric(capture.record_count) && isscalar(capture.record_count) && ...
      isfinite(double(capture.record_count)) && capture.record_count >= 0)
  error("experiment:exp04:invalidArchivedLogger", ...
    "Trial %d logger archiver returned an invalid capture.", trial);
end
end

function validate_scenario(scenario)
if ~isstruct(scenario) || ~isfield(scenario, "name") || ...
    string(scenario.name) ~= "exp04" || ...
    ~isfield(scenario, "learning_error_quantum_rad")
  error("experiment:workflow:invalidScenario", "Expected an exp04 scenario.");
end
end

function close_batch_dashboard(dashboard)
if ~usejava("desktop") && isstruct(dashboard) && ...
    isfield(dashboard, "figure") && isgraphics(dashboard.figure, "figure")
  close(dashboard.figure);
end
end
