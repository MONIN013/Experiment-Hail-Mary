classdef VirtualMotorService < handle
  properties (Access = private)
    plc_transport
    vm_transport
    control_transport
  end

  methods
    function obj = VirtualMotorService(plc_transport, vm_transport, control_transport)
      if ~isa(plc_transport, "twincat_ads.IAdsTransport")
        error("experiment:service:invalidDependency", ...
          "plc_transport must implement twincat_ads.IAdsTransport.");
      end
      if ~isa(vm_transport, "twincat_ads.IAdsTransport")
        error("experiment:service:invalidDependency", ...
          "vm_transport must implement twincat_ads.IAdsTransport.");
      end
      if nargin < 3 || isempty(control_transport)
        control_transport = plc_transport;
      end
      if ~isa(control_transport, "twincat_ads.IAdsTransport")
        error("experiment:service:invalidDependency", ...
          "control_transport must implement twincat_ads.IAdsTransport.");
      end
      obj.plc_transport = plc_transport;
      obj.vm_transport = vm_transport;
      obj.control_transport = control_transport;
    end

    function out = run(obj, cfg)
      if ~isa(cfg, "experiment.RunConfig")
        cfg = experiment.RunConfig.from_struct(cfg);
      end
      obj.ensure_folder(fileparts(cfg.save_path));

      plc_symbols = experiment.VirtualMotorSymbols.from_defaults();
      vm_symbols = experiment.VirtualMotorSymbols.from_vm_prefix(cfg.vm_param_symbol_prefix);
      controller_symbols = experiment.VirtualMotorSymbols.from_controller_prefix(cfg.controller_param_symbol_prefix);
      twincat_ads.SymbolBrowser.validate_symbols(obj.plc_transport, plc_symbols.plcRequiredProbes);
      twincat_ads.SymbolBrowser.validate_symbols(obj.vm_transport, vm_symbols.vmRequiredProbes);
      twincat_ads.SymbolBrowser.validate_symbols(obj.vm_transport, controller_symbols.controllerRequiredProbes);

      ctrl = experiment.ModeManagerControl.resolve_symbols( ...
        obj.control_transport, plc_symbols, "experiment:service:invalidConfig");
      heartbeat_state = experiment.ModeManagerControl.init_heartbeat( ...
        obj.control_transport, ctrl, cfg.host_heartbeat_enable, cfg.host_heartbeat_period_s);

      vm_params = struct( ...
        "m", cfg.m, ...
        "d", cfg.d, ...
        "rated_current", cfg.rated_current, ...
        "max_permille", cfg.max_permille, ...
        "tau_limit", cfg.tau_limit, ...
        "vel_limit", cfg.vel_limit);
      controller_params = struct( ...
        "pid_b0", cfg.pid_b0, "pid_b1", cfg.pid_b1, "pid_b2", cfg.pid_b2, ...
        "pid_a1", cfg.pid_a1, "pid_a2", cfg.pid_a2, ...
        "lead_b0", cfg.lead_b0, "lead_b1", cfg.lead_b1, "lead_b2", cfg.lead_b2, ...
        "lead_a1", cfg.lead_a1, "lead_a2", cfg.lead_a2, ...
        "notch_b0", cfg.notch_b0, "notch_b1", cfg.notch_b1, "notch_b2", cfg.notch_b2, ...
        "notch_a1", cfg.notch_a1, "notch_a2", cfg.notch_a2, ...
        "reso_b0", cfg.reso_b0, "reso_b1", cfg.reso_b1, "reso_b2", cfg.reso_b2, ...
        "reso_a1", cfg.reso_a1, "reso_a2", cfg.reso_a2, ...
        "enable_pid", cfg.enable_pid, "enable_lead", cfg.enable_lead, ...
        "enable_notch", cfg.enable_notch, "enable_reso", cfg.enable_reso);
      experiment.write_vm_params(obj.vm_transport, cfg.vm_param_symbol_prefix, vm_params, cfg.task_dt_ns);
      experiment.write_controller_params(obj.vm_transport, cfg.controller_param_symbol_prefix, controller_params);

      ref_profile = cfg.ref_profile(:);
      ff_profile = cfg.ff_profile(:);
      dist_profile = cfg.dist_profile(:);
      table_n = numel(ref_profile);
      if table_n > double(cfg.table_max_n)
        error("experiment:service:invalidProfile", ...
          "ref_profile length (%d) exceeds table_max_n (%d).", table_n, cfg.table_max_n);
      end

      t_run = tic;
      experiment.ModeManagerControl.write_mode_flags(obj.control_transport, ctrl, uint32(0));
      obj.plc_transport.write_scalar(plc_symbols.tableLen, uint32(0), plc_symbols.types.u32);

      [reset_acked, reset_diag, heartbeat_state] = experiment.ModeManagerControl.request_reset_and_wait_ack( ...
        obj.control_transport, ctrl, cfg.reset_timeout_s, heartbeat_state);
      if ~reset_acked
        error("experiment:service:resetAckTimeout", ...
          "Timed out waiting reset acknowledgement (resetAckCounter before=%g after=%g).", ...
          reset_diag.counter_before, reset_diag.counter_after);
      end

      [idle_ready, ~, heartbeat_state] = experiment.ModeManagerControl.wait_for_reset_idle( ...
        obj.plc_transport, obj.control_transport, plc_symbols, ctrl, cfg.reset_timeout_s, heartbeat_state);
      if ~idle_ready
        error("experiment:service:resetSyncTimeout", ...
          "Timed out waiting reset idle state (idx==0, experimentActive==FALSE).");
      end

      experiment.write_ref_table(obj.plc_transport, ref_profile, double(cfg.table_max_n));
      experiment.write_ff_table(obj.plc_transport, ff_profile, table_n);
      experiment.write_dist_table(obj.plc_transport, dist_profile, table_n);
      experiment.ModeManagerControl.write_mode_flags(obj.control_transport, ctrl, uint32(ctrl.MODEF_SERVO_ENABLE));
      experiment.ModeManagerControl.write_mode_flags(obj.control_transport, ctrl, uint32(bitor(ctrl.MODEF_SERVO_ENABLE, ctrl.MODEF_EXPERIMENT_START_REQ)));

      if cfg.wait_for_done
        [done, heartbeat_state] = experiment.ModeManagerControl.wait_until_done( ...
          obj.control_transport, obj.plc_transport, plc_symbols, ctrl, cfg.done_timeout_s, heartbeat_state);
        if ~done
          warning("experiment:service:timeout", "Timed out waiting for experiment completion.");
        end
      else
        done = false;
        while toc(t_run) < cfg.hold_seconds
          heartbeat_state = experiment.ModeManagerControl.tick_heartbeat( ...
            obj.control_transport, ctrl, heartbeat_state, false);
          pause(min(0.05, cfg.hold_seconds / 10 + eps));
        end
      end

      experiment.ModeManagerControl.write_mode_flags(obj.control_transport, ctrl, uint32(0));
      elapsed_s = toc(t_run);

      position_last = double(obj.plc_transport.read_scalar(plc_symbols.positionActLog, plc_symbols.types.double));
      control_input_last = double(obj.plc_transport.read_scalar(plc_symbols.controlInput, plc_symbols.types.double));
      log_data = obj.read_logger_bin_payload();

      raw = struct( ...
        "position_last", position_last, ...
        "controlInput_last", control_input_last, ...
        "logSeq", log_data.logSeq, ...
        "logRefValue", log_data.logRefValue, ...
        "logFfValue", log_data.logFfValue, ...
        "logDistValue", log_data.logDistValue, ...
        "logControlInput", log_data.logControlInput, ...
        "logTargetCurrent", log_data.logTargetCurrent, ...
        "logPositionAct", log_data.logPositionAct, ...
        "logT", log_data.logT, ...
        "logIdx", log_data.logIdx, ...
        "log_wrIdx", log_data.wrIdx, ...
        "log_overflow", logical(log_data.overflow));

      cmd = struct( ...
        "ref_profile", ref_profile, ...
        "ff_profile", ff_profile, ...
        "dist_profile", dist_profile, ...
        "tableLen", table_n, ...
        "use_profile", true, ...
        "hold_seconds", cfg.hold_seconds);

      host = struct( ...
        "elapsed_s", elapsed_s, ...
        "log_read_time_s", 0, ...
        "log_read_time_s_total", 0, ...
        "host_heartbeat_enable", logical(cfg.host_heartbeat_enable), ...
        "host_heartbeat_period_s", double(cfg.host_heartbeat_period_s), ...
        "control_mode_flags_symbol", char(string(ctrl.modeFlagsSymbol)), ...
        "control_experiment_state_symbol", char(string(ctrl.experimentStateSymbol)));

      cfg_struct = cfg.to_struct();
      metrics = experiment.preload_eval(raw, cmd, cfg_struct);
      config = cfg_struct;
      save(cfg.save_path, "raw", "cmd", "host", "metrics", "config");

      out = struct( ...
        "raw", raw, ...
        "cmd", cmd, ...
        "host", host, ...
        "metrics", metrics, ...
        "config", config, ...
        "save_path", cfg.save_path);
    end
  end

  methods (Access = private)
    function ensure_folder(~, path_value)
      if strlength(string(path_value)) == 0
        return;
      end
      if ~exist(path_value, "dir")
        mkdir(path_value);
      end
    end

    function log_data = read_logger_bin_payload(~)
      logger_path = "C:\ExperimentData\experiment_logger.bin";
      log_data = struct( ...
        "logSeq", zeros(0, 1), ...
        "logRefValue", zeros(0, 1), ...
        "logFfValue", zeros(0, 1), ...
        "logDistValue", zeros(0, 1), ...
        "logControlInput", zeros(0, 1), ...
        "logTargetCurrent", zeros(0, 1), ...
        "logPositionAct", zeros(0, 1), ...
        "logT", zeros(0, 1), ...
        "logIdx", zeros(0, 1), ...
        "wrIdx", 0, ...
        "overflow", false);
      if ~isfile(logger_path)
        return;
      end
      out = experiment.read_logger_bin(logger_path);
      n = numel(out.time_s);
      log_data.logSeq = double((1:n)');
      log_data.logRefValue = double(out.ref_value(:));
      log_data.logFfValue = double(out.ff_value(:));
      log_data.logDistValue = double(out.dist_value(:));
      log_data.logControlInput = double(out.control_input(:));
      log_data.logTargetCurrent = double(out.target_current(:));
      log_data.logPositionAct = double(out.load_position(:));
      log_data.logT = double(round(out.time_s(:) * 1e9));
      log_data.logIdx = double((0:max(n - 1, 0))');
      log_data.wrIdx = double(n);
    end
  end
end
