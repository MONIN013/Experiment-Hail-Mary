classdef ExperimentRunner
  methods (Static)
    function out = run(conn, cfg)
      cfg = experiment.ExperimentConfig.from_varargin(cfg);
      experiment.ExperimentRunner.validate_connection(conn);

      seq_transport = conn.seq;
      ctrl_transport = conn.ctrl;
      module_transport = [];
      if isfield(conn, "module")
        module_transport = conn.module;
      end

      plc_symbols = experiment.VirtualMotorSymbols.from_defaults();
      vm_symbols = experiment.VirtualMotorSymbols.from_vm_prefix(experiment.SystemConfig.VM_PREFIX);
      controller_symbols = experiment.VirtualMotorSymbols.from_controller_prefix(experiment.SystemConfig.CTRL_PREFIX);

      if (cfg.write_plant_params || cfg.write_controller_params) && isempty(module_transport)
        error("experiment:runner:invalidConfig", ...
          "module transport is required when module parameter writes are enabled.");
      end

      if cfg.validate_symbols
        twincat_ads.SymbolBrowser.validate_symbols(seq_transport, plc_symbols.plcRequiredProbes);
        if cfg.write_plant_params
          twincat_ads.SymbolBrowser.validate_symbols(module_transport, vm_symbols.vmRequiredProbes);
        end
        if cfg.write_controller_params
          twincat_ads.SymbolBrowser.validate_symbols(module_transport, controller_symbols.controllerRequiredProbes);
        end
      end

      ctrl = experiment.ModeManagerControl.resolve_symbols( ...
        ctrl_transport, plc_symbols, "experiment:runner:invalidConfig");
      heartbeat_state = experiment.ModeManagerControl.init_heartbeat( ...
        ctrl_transport, ctrl, cfg.host_heartbeat_enable, cfg.host_heartbeat_period_s);

      if cfg.write_plant_params
        if isempty(module_transport)
          error("experiment:runner:invalidConfig", "module transport is required when write_plant_params=true.");
        end
        experiment.write_vm_params( ...
          module_transport, experiment.SystemConfig.VM_PREFIX, ...
          cfg.plant.to_struct(), uint64(round(1e9 / cfg.task_rate_hz)));
      end
      if cfg.write_controller_params
        if isempty(module_transport)
          error("experiment:runner:invalidConfig", "module transport is required when write_controller_params=true.");
        end
        experiment.write_controller_params( ...
          module_transport, experiment.SystemConfig.CTRL_PREFIX, ...
          cfg.controller.to_flat_struct());
      end

      table_n = numel(cfg.ref_profile);
      logger_path = string(experiment.SystemConfig.LOGGER_DEFAULT_FILE_PATH);
      t_run = tic;
      experiment.ModeManagerControl.write_mode_flags(ctrl_transport, ctrl, uint32(0));
      seq_transport.write_scalar(plc_symbols.tableLen, uint32(0), plc_symbols.types.u32);

      [reset_acked, reset_diag, heartbeat_state] = experiment.ModeManagerControl.request_reset_and_wait_ack( ...
        ctrl_transport, ctrl, cfg.reset_timeout_s, heartbeat_state);
      if ~reset_acked
        error("experiment:runner:resetAckTimeout", ...
          "Timed out waiting reset acknowledgement (resetAckCounter before=%g after=%g).", ...
          reset_diag.counter_before, reset_diag.counter_after);
      end

      [idle_ready, idle_diag, heartbeat_state] = experiment.ModeManagerControl.wait_for_reset_idle( ...
        seq_transport, ctrl_transport, plc_symbols, ctrl, cfg.reset_timeout_s, heartbeat_state);
      if ~idle_ready
        error("experiment:runner:resetSyncTimeout", ...
          "Timed out waiting reset idle state (idx==0, experimentActive==FALSE). Observed idx=%g experimentActive=%d.", ...
          idle_diag.idx, logical(idle_diag.experiment_active));
      end
      logger_before = experiment.ModeManagerControl.read_logger_status(ctrl_transport, ctrl);

      experiment.write_ref_table(seq_transport, cfg.ref_profile(:), double(cfg.table_max_n));
      experiment.write_ff_table(seq_transport, cfg.ff_profile(:), table_n);
      experiment.write_dist_table(seq_transport, cfg.dist_profile(:), table_n);
      seq_transport.write_scalar(plc_symbols.repeatCount, uint32(cfg.repeat_count), plc_symbols.types.u32);
      seq_transport.write_scalar(plc_symbols.tableLen, uint32(table_n), plc_symbols.types.u32);

      experiment.ModeManagerControl.write_mode_flags(ctrl_transport, ctrl, uint32(ctrl.MODEF_SERVO_ENABLE));
      experiment.ModeManagerControl.write_mode_flags(ctrl_transport, ctrl, ...
        uint32(bitor(ctrl.MODEF_SERVO_ENABLE, ctrl.MODEF_EXPERIMENT_START_REQ)));

      if cfg.wait_for_done
        [done, heartbeat_state] = experiment.ModeManagerControl.wait_until_done( ...
          ctrl_transport, seq_transport, plc_symbols, ctrl, cfg.done_timeout_s, heartbeat_state);
        timed_out = ~done;
      else
        done = false;
        timed_out = false;
        while toc(t_run) < cfg.hold_seconds
          heartbeat_state = experiment.ModeManagerControl.tick_heartbeat( ...
            ctrl_transport, ctrl, heartbeat_state, false);
          pause(min(0.05, cfg.hold_seconds / 10 + eps));
        end
      end

      experiment.ModeManagerControl.write_mode_flags(ctrl_transport, ctrl, uint32(0));
      [file_released, logger_diag, heartbeat_state] = experiment.ModeManagerControl.wait_for_logger_release( ...
        ctrl_transport, ctrl, cfg.logger_release_timeout_s, heartbeat_state);
      elapsed_s = toc(t_run);
      logger_after = experiment.ModeManagerControl.read_logger_status(ctrl_transport, ctrl);

      if logger_diag.error_code ~= 0
        error("experiment:runner:loggerError", ...
          "Logger reported error after experiment stop (0x%08X).", uint32(logger_diag.error_code));
      end
      if ~file_released
        error("experiment:runner:loggerReleaseTimeout", ...
          "Logger file was not released after experiment stop (%s).", string(logger_diag.detail));
      end

      raw = experiment.ExperimentRunner.read_log_payload(cfg.read_logs, logger_path);
      cmd = struct( ...
        "ref_profile", cfg.ref_profile(:), ...
        "ff_profile", cfg.ff_profile(:), ...
        "dist_profile", cfg.dist_profile(:), ...
        "table_len", table_n, ...
        "repeat_count", double(cfg.repeat_count), ...
        "task_rate_hz", cfg.task_rate_hz);
      host = struct( ...
        "elapsed_s", elapsed_s, ...
        "wait_for_done", logical(cfg.wait_for_done), ...
        "done", logical(done), ...
        "timed_out", logical(timed_out), ...
        "control_ams_port", double(cfg.control_port), ...
        "host_heartbeat_enable", logical(cfg.host_heartbeat_enable), ...
        "host_heartbeat_period_s", double(cfg.host_heartbeat_period_s), ...
        "logger_release_timeout_s", double(cfg.logger_release_timeout_s), ...
        "control_mode_flags_symbol", char(string(ctrl.modeFlagsSymbol)), ...
        "control_experiment_state_symbol", char(string(ctrl.experimentStateSymbol)));
      logger = struct( ...
        "ready_before", false, ...
        "ready_after", false, ...
        "error_before", uint32(logger_before.error_code), ...
        "error_after", uint32(logger_after.error_code), ...
        "records_before", uint32(0), ...
        "records_after", uint32(0), ...
        "file_released", logical(logger_after.file_released), ...
        "file_probe_detail", string(logger_diag.detail), ...
        "file_path", char(logger_path));

      metrics = experiment.preload_eval(to_legacy_raw(raw), cmd, cfg.to_struct());
      config = cfg.to_struct();

      if strlength(string(cfg.save_path)) > 0
        experiment.ExperimentRunner.ensure_folder(fileparts(cfg.save_path));
        save(cfg.save_path, "raw", "cmd", "host", "metrics", "config");
      end

      out = struct( ...
        "raw", raw, ...
        "cmd", cmd, ...
        "host", host, ...
        "metrics", metrics, ...
        "eval", to_legacy_eval(metrics), ...
        "config", config, ...
        "logger", logger, ...
        "save_path", char(string(cfg.save_path)));
    end
  end

  methods (Static, Access = private)
    function validate_connection(conn)
      required = {"seq", "ctrl"};
      for k = 1:numel(required)
        key = required{k};
        if ~isfield(conn, key) || ~isa(conn.(key), "twincat_ads.IAdsTransport")
          error("experiment:runner:invalidConfig", "Connection is missing '%s' transport.", key);
        end
      end
      if isfield(conn, "module") && ~isempty(conn.module) && ~isa(conn.module, "twincat_ads.IAdsTransport")
        error("experiment:runner:invalidConfig", "Connection 'module' must implement twincat_ads.IAdsTransport.");
      end
    end

    function raw = read_log_payload(read_logs, logger_path)
      raw = struct( ...
        "seq", zeros(0, 1), ...
        "ref_value", zeros(0, 1), ...
        "ff_value", zeros(0, 1), ...
        "dist_value", zeros(0, 1), ...
        "control_input", zeros(0, 1), ...
        "target_current", zeros(0, 1), ...
        "position_act", zeros(0, 1));
      if ~logical(read_logs)
        return;
      end
      if ~isfile(logger_path)
        error("experiment:runner:loggerFileMissing", ...
          "Logger file was released but not found at %s.", string(logger_path));
      end
      out = experiment.read_logger_bin(logger_path);
      sample_n = double(out.record_count);
      raw.seq = double((1:sample_n)');
      raw.ref_value = double(out.raw.ref_value(:));
      raw.ff_value = double(out.raw.ff_value(:));
      raw.dist_value = double(out.raw.ff_value(:) * 0);
      raw.control_input = double(out.raw.control_input(:));
      raw.target_current = double(out.raw.current_cmd(:));
      raw.position_act = double(out.raw.load_position(:));
    end

    function ensure_folder(path_value)
      if strlength(string(path_value)) == 0
        return;
      end
      if ~exist(path_value, "dir")
        mkdir(path_value);
      end
    end
  end
end

function raw = to_legacy_raw(new_raw)
raw = struct( ...
  "logSeq", new_raw.seq, ...
  "logRefValue", new_raw.ref_value, ...
  "logFfValue", new_raw.ff_value, ...
  "logDistValue", new_raw.dist_value, ...
  "logControlInput", new_raw.control_input, ...
  "logTargetCurrent", new_raw.target_current, ...
  "logPositionAct", new_raw.position_act);
end

function ev = to_legacy_eval(metrics)
sampling = metrics.sampling;
ev = struct( ...
  "input_count", double(sampling.command_count), ...
  "log_seq_count", double(metrics.sample_count), ...
  "log_ref_count", double(sampling.ref_log_count), ...
  "log_ff_count", double(sampling.ff_log_count), ...
  "log_dist_count", double(sampling.dist_log_count), ...
  "log_control_input_count", double(sampling.controlInput_log_count), ...
  "log_target_current_count", double(sampling.target_torque_log_count), ...
  "log_position_count", double(sampling.position_log_count), ...
  "log_component_counts_match", logical(sampling.all_sample_counts_match), ...
  "input_count_matches_log_ref", double(sampling.command_count) == double(sampling.ref_log_count), ...
  "input_count_matches_log_position", double(sampling.command_count) == double(sampling.position_log_count), ...
  "input_and_all_log_counts_match", ...
    logical(sampling.all_sample_counts_match) && ...
    (double(sampling.command_count) == double(sampling.ref_log_count)) && ...
    (double(sampling.command_count) == double(sampling.position_log_count)));
end
