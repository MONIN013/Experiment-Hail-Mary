classdef TestRunPositionCommandDemoConfig < matlab.unittest.TestCase
  methods (Test)
    function demoUsesSharedRuntimeAndConfirmedLogger(testCase)
      source = read_tool_source("run_position_command_demo.m");
      required = ["experiment.ExperimentConfig.defaults()", ...
        "experiment.exp0n.run_and_collect(cfg)", ...
        "logger_bin = collect_out.logger_bin", ...
        "experiment.exp0n.assert_run_contract(out)", ...
        "experiment.exp02.signals_from_logger_bin(logger_bin)", ...
        "experiment.plot.feedback_result("];
      for value = required
        testCase.verifyTrue(contains(source, value));
      end
      verify_normal_tool_has_no_vm_oracle(testCase, source);
      testCase.verifyFalse(contains(source, "read_latest_logger_bin"));
      testCase.verifyFalse(contains(source, "logger_share_dir ="));
      testCase.verifyFalse(contains(source, "experiment.send_position_command("));
      testCase.verifyFalse(contains(source, "restoredefaultpath;"));
      testCase.verifyFalse(contains(source, "addpath(genpath("));
    end

    function demoPinsExpectedPositionExperiment(testCase)
      source = read_tool_source("run_position_command_demo.m");
      required = ["target_position_rad = 0.75;", ...
        "step_duration_s     = 2.0;", "pre_step_s          = 2.0;", ...
        "N_REPEAT            = 1;", ...
        "controller_bandwidth_rad_s = 20;", ...
        "Jn = 7.1e-5;", "Dn = 5.325e-4;", ...
        "experiment.exp02.designpid(", ...
        'c2d(Kpid, sample_time_s, "tustin")', ...
        "experiment.controller.from_discrete_tf(Kd)", ...
        "cfg.repeat_count = N_REPEAT;", ...
        "cfg.host_heartbeat_enable = false;", ...
        "cfg.external_host_heartbeat_enable = true;"];
      for value = required
        testCase.verifyTrue(contains(source, value));
      end
      testCase.verifyFalse(contains(source, "Kp = 0.02;"));
      testCase.verifyFalse(contains(source, "cfg.plant ="));
    end

    function loggerDirectoryDerivesFromEnvironmentConfig(testCase)
      env = config.EnvironmentConfig.defaults();
      logger_path = string(env.logger_host_file_path);
      testCase.verifyEqual( ...
        string(fileparts(char(logger_path))), ...
        string(fileparts(char(config.EnvironmentConfig.DEFAULT_LOGGER_HOST_FILE_PATH))));
    end
  end
end

function source = read_tool_source(file_name)
root = fileparts(fileparts(fileparts(mfilename("fullpath"))));
source = string(fileread(fullfile(root, "tools", file_name)));
end

function verify_normal_tool_has_no_vm_oracle(testCase, source)
for forbidden = [ ...
    "virtualMotor.predict_logger(", "virtualMotor.compare_prediction(", ...
    "virtualMotor.assert_prediction(", "virtualMotor.restart_runtime(", ...
    "virtualMotor.configure(", "virtualMotor.writeParams("]
  testCase.verifyFalse(contains(source, forbidden), ...
    "Normal demos must leave VM prediction and reconfiguration to tests.");
end
end
