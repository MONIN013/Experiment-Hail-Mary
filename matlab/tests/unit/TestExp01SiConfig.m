classdef TestExp01SiConfig < matlab.unittest.TestCase
  methods (Test)
    function scriptUsesCurrentExperimentApis(testCase)
      script_path = fullfile( ...
        fileparts(fileparts(fileparts(mfilename("fullpath")))), ...
        "experiment", ...
        "exp01_SI.m");
      source = string(fileread(script_path));

      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] # 概要"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] ## 前提確認"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] ## セットアップ"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] ## 例示パラメータ"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] ## chirp 生成"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] ## 実験実行"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] ## FRF 解析"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] ## 可視化"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("%[text] ## 次の調整指針"));

      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "run('matlab/setup_matlab_environment.m')"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg = experiment.ExperimentConfig.defaults();"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        'logger_dir = string(fileparts(char(sys.LOGGER_DEFAULT_FILE_PATH)));'));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "conn = experiment.ConnectionManager.create(cfg);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "run_out = experiment.ExperimentRunner.run(conn, cfg);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "latest_bin = experiment.read_latest_logger_bin(logger_dir, logger_file_glob);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "frf_out = experiment.analyze_si_frf(logger_bin, ..."));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "compute_nominal_two_inertia_frf("));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        'si_out = struct( ...'));
      testCase.verifyFalse(contains(source, "resolve_matlab_root()"));
      testCase.verifyFalse(contains(source, "restoredefaultpath;"));
      testCase.verifyFalse(contains(source, "addpath(genpath("));
      testCase.verifyFalse(contains(source, "addpath(char(utils_dir));"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "experiment.wrap_phase_at_180("));
      testCase.verifyFalse(contains(source, "fprintf("));
    end

    function scriptPinsRealMotorDefaults(testCase)
      script_path = fullfile( ...
        fileparts(fileparts(fileparts(mfilename("fullpath")))), ...
        "experiment", ...
        "exp01_SI.m");
      source = string(fileread(script_path));

      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("Tend = 10;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("Tcycle = 10;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("repeat_count = 10;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("f0 = 0.5;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("f1 = 4000;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("A = 0.1;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("transient_cycles = 3;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("initial_phase = 0;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("hold_margin_s = 1.0;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring("Kp = 0;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.ref_profile = zeros(sample_n, 1);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.ff_profile = chirp_cfg.signal(:);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.dist_profile = zeros(sample_n, 1);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.repeat_count = repeat_count;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.hold_seconds = Tend + hold_margin_s;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.done_timeout_s = repeat_count * Tend + hold_margin_s + 5.0;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.logger_release_timeout_s = max(5.0, repeat_count * Tend / 10);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.controller = experiment.ControllerConfig.p_only(Kp);"));
    end

    function scriptUsesNominalOverlayWithoutVirtualMotorWrite(testCase)
      script_path = fullfile( ...
        fileparts(fileparts(fileparts(mfilename("fullpath")))), ...
        "experiment", ...
        "exp01_SI.m");
      source = string(fileread(script_path));

      testCase.verifyFalse(contains(source, "virtualMotor.writeParams("));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "virtualMotor.PlantConfig.from_struct(struct("));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "frf_nominal = compute_nominal_two_inertia_frf("));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        '"DisplayName", "Nominal"'));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "% Analysis-only nominal plant for FRF overlay; do not write this to ADS."));
    end
  end
end
