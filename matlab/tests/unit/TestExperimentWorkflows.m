classdef TestExperimentWorkflows < matlab.unittest.TestCase
  methods (Test)
    function runsShortSystemIdentificationWithSyntheticLogger(testCase)
      temporary_folder = testCase.applyFixture( ...
        matlab.unittest.fixtures.TemporaryFolderFixture);
      scenario = experiment.scenario.exp01( ...
        "Tend", 0.06, "Tcycle", 0.02, "transient_cycles", 1, ...
        "f0", 20, "f1", 1000, "save_results", false, ...
        "result_dir", temporary_folder.Folder);

      result = experiment.workflow.run_exp01(scenario, ...
        "collector", @TestExperimentWorkflows.fakeExp01Collector);

      required_fields = ["scenario", "run", "logger", "signals", ...
        "metrics", "artifacts", "plant", "startup_timing"];
      testCase.verifyTrue(all(isfield(result, required_fields)));
      testCase.verifyEqual(result.metrics.sample_count, 480);
      testCase.verifyTrue(result.metrics.nonzero_motion);
      testCase.verifySize(result.signals.input, [480 1]);
      testCase.verifyEqual(result.signals.input, result.logger.raw.ff_value);
      testCase.verifyNotEqual(result.signals.input, ...
        result.logger.raw.control_input);
      testCase.verifyClass(result.plant.Pd, "frd");
      testCase.verifyEqual(result.plant.Ts, 1 / 8000, "AbsTol", eps);
      z = tf("z", result.plant.Ts);
      integrator = result.plant.Ts*z/(z-1);
      frequency_rad_s = 2*pi*result.plant.Pd_vel_load.Frequency;
      expected_position = squeeze(result.plant.Pd_vel_load.ResponseData) .* ...
        squeeze(freqresp(integrator, frequency_rad_s));
      testCase.verifyEqual( ...
        squeeze(result.plant.Pd_load.ResponseData), expected_position, ...
        "AbsTol", 1e-12);
      testCase.verifyFalse(result.artifacts.saved);
      testCase.verifyEmpty(dir(fullfile(temporary_folder.Folder, "*.mat")));
    end

    function runsFeedbackAndFeedforwardWithSyntheticLogger(testCase)
      [plant, trajectory, controller] = testCase.syntheticInputs();
      feedback_scenario = experiment.scenario.exp02(plant, trajectory, ...
        "Kd", controller, "save_results", false);
      feedforward_scenario = experiment.scenario.exp03(plant, trajectory, ...
        "Kd", controller, "save_results", false);

      feedback_state = testCase.newCollectorState();
      feedback = experiment.workflow.run_exp02(feedback_scenario, ...
        "collector", @(cfg) TestExperimentWorkflows.fakeTrackingCollector( ...
          cfg, feedback_state, 0.2));
      feedforward_state = testCase.newCollectorState();
      feedforward = experiment.workflow.run_exp03(feedforward_scenario, ...
        "collector", @(cfg) TestExperimentWorkflows.fakeTrackingCollector( ...
          cfg, feedforward_state, 0.05));

      required_fields = ["scenario", "run", "logger", "signals", ...
        "metrics", "artifacts", "startup_timing"];
      testCase.verifyTrue(all(isfield(feedback, required_fields)));
      testCase.verifyTrue(all(isfield(feedforward, required_fields)));
      testCase.verifyNumElements(feedback.signals.error, numel(trajectory.p));
      testCase.verifyGreaterThan(feedback.metrics.tracking_error_rms, 0);
      testCase.verifyGreaterThan(feedback.metrics.integral_absolute_error, 0);
      testCase.verifyFalse(feedback.artifacts.saved);

      testCase.verifyEqual(feedforward.signals.feedforward, ...
        feedforward_scenario.feedforward, "AbsTol", 1e-12);
      testCase.verifyEqual(feedforward.signals.feedback_input, ...
        0.05 * feedforward.signals.error, "AbsTol", 1e-12);
      testCase.verifyEqual(feedforward.metrics.max_abs_feedforward, ...
        max(abs(feedforward_scenario.feedforward)), "AbsTol", 1e-12);
      testCase.verifyFalse(feedforward.artifacts.saved);
    end

    function completesMonotonicallyDecreasingIlcCampaign(testCase)
      [plant, trajectory, controller] = testCase.syntheticInputs();
      scenario = experiment.scenario.exp04(plant, trajectory, ...
        "Kd", controller, "trial_count", 3, "alpha", 0.6, ...
        "noQ", true, "Npad", 0, "transient_samples", 0, ...
        "settling_tail_s", 0, ...
        "max_input_A", 1000, "save_results", false);
      collector_state = testCase.newCollectorState();
      original_figures = findall(0, "Type", "figure");
      testCase.addTeardown(@() TestExperimentWorkflows.closeNewFigures( ...
        original_figures));

      result = experiment.workflow.run_exp04(scenario, ...
        "collector", @(cfg) TestExperimentWorkflows.fakeTrackingCollector( ...
          cfg, collector_state, [0.5, 0.25, 0.1]), ...
        "dashboard_visibility", "off");

      testCase.verifyEqual(result.history.completedTrials, 3);
      testCase.verifyEqual(result.history.stopReason, "completed");
      testCase.verifyTrue(all(diff(result.history.eNorm) < 0));
      testCase.verifyEqual(result.history.bestTrial, 3);
      testCase.verifyEqual(height(result.history.trialSummary), 3);
      testCase.verifyEqual(string(result.history.trialSummary.Properties.VariableNames), ...
        ["trial", "errorNorm", "maxAbsError", "maxAbsInputA", ...
         "maxAbsFeedforwardA", "maxAbsTotalInputA", "errorIncreased", ...
         "convergencePeak", "convergenceSatisfied"]);
      testCase.verifyTrue(result.metrics.monotonic_decrease);
      testCase.verifyEqual(result.metrics.completed_trials, 3);
      testCase.verifyEqual(result.metrics.best_trial, 3);
      testCase.verifyFalse(result.artifacts.saved);
      testCase.verifyEmpty(result.artifacts.image_files);
    end

