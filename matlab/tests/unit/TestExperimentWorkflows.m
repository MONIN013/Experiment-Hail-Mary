  methods (Static, Access = private)
    function collected = fakeExp01Collector(cfg)
      Ts = 1 / double(cfg.env.task_rate_hz);
      input = repmat(double(cfg.ff_profile(:)), double(cfg.repeat_count), 1);
      control_input = [0; input(1:end - 1)];
      velocity = filter(1, [1, -0.92], input);
      load_position = cumsum(velocity) * Ts;
      motor_position = cumsum(1.08 * velocity) * Ts;
      raw = struct( ...
        "ff_value", input, ...
        "control_input", control_input, ...
        "load_position", load_position, ...
        "motor_position", motor_position, ...
        "load_velocity", velocity, ...
        "motor_velocity", 1.08 * velocity);
      logger_bin = struct("record_count", numel(input), "raw", raw);
      collected = TestExperimentWorkflows.collectedPayload(logger_bin);
    end

    function collected = fakeTrackingCollector(cfg, state, scales)
      index = state("index") + 1;
      state("index") = index; %#ok<NASGU> % containers.Map preserves trial state across calls.
      if index > numel(scales)
        error("test:collectorExhausted", "No synthetic trial remains.");
      end
      scale = double(scales(index));
      repeat_count = double(cfg.repeat_count);
      reference = repmat(double(cfg.ref_profile(:)), repeat_count, 1);
      feedforward = repmat(double(cfg.ff_profile(:)), repeat_count, 1);
      error_signal = scale * reference;
      position = reference - error_signal;
      ff_value = [0; feedforward(1:end - 1)];
      applied_feedforward = [0; ff_value(1:end - 1)];
      control_input = applied_feedforward + 0.05 * error_signal;
      Ts = 1 / double(cfg.env.task_rate_hz);
      raw = struct( ...
        "t_s", (0:numel(reference) - 1)' * Ts, ...
        "ref_value", reference, ...
        "ff_value", ff_value, ...
        "dist_value", zeros(size(reference)), ...
        "load_position", position, ...
        "error", error_signal, ...
        "control_input", control_input, ...
        "current_cmd", control_input);
      logger_bin = struct("record_count", numel(reference), "raw", raw);
      collected = TestExperimentWorkflows.collectedPayload(logger_bin);
    end

    function collected = collectedPayload(logger_bin)
      acceptance = struct( ...
        "input_waveform_exact_match", true, ...
        "ff_waveform_exact_match", true, ...
        "dist_waveform_exact_match", true, ...
        "torque_sum_exact_match", true, ...
        "seq_no_gap", true, ...
        "total_sample_count_exact_match", true);
      run = struct("metrics", struct("acceptance", acceptance));
      collected = struct( ...
        "run", run, "logger_bin", logger_bin, ...
        "startup_timing", struct("total_s", 0));
    end

    function capture = fakeLoggerArchiver(logger_bin, destination)
      capture = struct("path", string(destination), ...
        "record_count", double(logger_bin.record_count));
    end

    function capture = failingLoggerArchiver(varargin)
      capture = struct("path", "", "record_count", 0);
      if ~isempty(varargin)
        error("test:loggerArchiveFailed", "Injected archive failure.");
      end
    end

    function state = newCollectorState()
      state = containers.Map("KeyType", "char", "ValueType", "double");
      state("index") = 0;
    end

    function [plant, trajectory, controller] = syntheticInputs()
      Ts = 1 / 8000;
      sample_count = 64;
      t = (0:sample_count - 1)' * Ts;
      frequency_hz = 125;
      p = 0.2 * sin(2*pi*frequency_hz*t);
      v = 0.2 * 2*pi*frequency_hz * cos(2*pi*frequency_hz*t);
      a = -0.2 * (2*pi*frequency_hz)^2 * sin(2*pi*frequency_hz*t);
      trajectory = struct("t", t, "p", p, "v", v, "a", a);
      plant = struct( ...
        "Pd", tf(1, 1, Ts), "Pdn", tf(1, 1, Ts), ...
        "Jn", 7.1e-5, "Dn", 5.325e-4, "Ndelay", 4, "Ts", Ts);
      controller = tf(0, 1, Ts);
    end

    function closeNewFigures(original_figures)
      new_figures = setdiff(findall(0, "Type", "figure"), original_figures);
      if ~isempty(new_figures)
        close(new_figures);
      end
    end
  end
