    function checkpointsCompletedHistoryBeforeErrorIncreaseException(testCase)
      temporary_folder = testCase.applyFixture( ...
        matlab.unittest.fixtures.TemporaryFolderFixture);
      [plant, trajectory, controller] = testCase.syntheticInputs();
      scenario = experiment.scenario.exp04(plant, trajectory, ...
        "Kd", controller, "trial_count", 3, "alpha", 0.6, ...
        "noQ", true, "Npad", 0, "transient_samples", 0, ...
        "settling_tail_s", 0, ...
        "max_input_A", 1000, "save_results", true, ...
        "result_dir", temporary_folder.Folder);
      collector_state = testCase.newCollectorState();
      original_figures = findall(0, "Type", "figure");
      testCase.addTeardown(@() TestExperimentWorkflows.closeNewFigures( ...
        original_figures));

      testCase.verifyError(@() experiment.workflow.run_exp04(scenario, ...
        "collector", @(cfg) TestExperimentWorkflows.fakeTrackingCollector( ...
          cfg, collector_state, [0.5, 0.8]), ...
        "logger_archiver", @TestExperimentWorkflows.fakeLoggerArchiver, ...
        "dashboard_visibility", "off"), ...
        "experiment:exp04:errorNormIncreased");

      checkpoints = dir(fullfile(temporary_folder.Folder, ...
        "exp04_runs", "*", "ilc_result.mat"));
      testCase.verifyNumElements(checkpoints, 1);
      checkpoint = load(fullfile(checkpoints(1).folder, checkpoints(1).name), ...
        "history");
      history = checkpoint.history;
      testCase.verifyEqual(history.completedTrials, 2);
      testCase.verifyEqual(history.stopReason, "error_increased");
      testCase.verifySize(history.y, [numel(trajectory.p), 2]);
      testCase.verifySize(history.e, [numel(trajectory.p), 2]);
      testCase.verifySize(history.f, [numel(trajectory.p), 2]);
      testCase.verifyEqual(height(history.trialSummary), 2);
      testCase.verifyTrue(history.errorIncreased(2));
      testCase.verifyGreaterThan(history.eNorm(2), history.eNorm(1));
      testCase.verifyNumElements(history.trialLoggerPaths, 2);
      testCase.verifyEqual(history.trialLoggerRecordCount, ...
        repmat(numel(trajectory.p), 1, 2));

      image_files = [ ...
        dir(fullfile(temporary_folder.Folder, "**", "*.png")); ...
        dir(fullfile(temporary_folder.Folder, "**", "*.jpg")); ...
        dir(fullfile(temporary_folder.Folder, "**", "*.jpeg"))];
      testCase.verifyEmpty(image_files);
    end

