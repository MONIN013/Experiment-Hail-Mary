    function boundedChildProcessTimesOutAndRegistryFreezesLimits(testCase)
      registry = testoracle.entry_registry();
      testCase.verifyTrue(all([registry.timeout_s] > 0));
      testCase.verifyGreaterThan( ...
        registry(string({registry.name}) == "experiment.exp04").timeout_s, ...
        registry(string({registry.name}) == "experiment.exp02").timeout_s);
      directory = string(tempname);
      mkdir(directory);
      cleanup = onCleanup(@() remove_directory(directory));
      sentinel = fullfile(directory, "descendant-survived.txt");
      child_path = fullfile(directory, "descendant.ps1");
      parent_path = fullfile(directory, "parent.ps1");
      escaped_sentinel = replace(string(sentinel), "'", "''");
      escaped_child = replace(string(child_path), "'", "''");
      writelines([ ...
        "Start-Sleep -Milliseconds 1200"
        "[IO.File]::WriteAllText('" + escaped_sentinel + "','survived')"], ...
        child_path);
      writelines([ ...
        "$null = Start-Process -FilePath 'powershell.exe' " + ...
          "-ArgumentList @('-NoProfile','-NonInteractive','-File','" + ...
          escaped_child + "') -WindowStyle Hidden -PassThru"
        "Start-Sleep -Seconds 10"], parent_path);
      arguments = '-NoProfile -NonInteractive -File "' + parent_path + '"';
      started = tic;
      testCase.verifyError(@() testoracle.run_bounded_process( ...
        "powershell.exe", arguments, 0.2, "label", "timeout regression"), ...
        "testoracle:process:timeout");
      pause(2);
      testCase.verifyLessThan(toc(started), 4);
      testCase.verifyFalse(isfile(sentinel), ...
        "A timed-out descendant survived the process-tree kill.");
    end

    function restartCountRequiresAuthenticatedLifecycleProof(testCase)
