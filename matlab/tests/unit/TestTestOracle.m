    function lsimLagUsesPositionDifferencesInsteadOfOffsetBiasedLevels(testCase)
      expected_position = (0:999)'.^2;
      actual_position = expected_position + 999;
      level_zero_rms = norm(actual_position-expected_position) / ...
        sqrt(numel(expected_position));
      level_lag_one_rms = norm( ...
        actual_position(1:end-1)-expected_position(2:end)) / ...
        sqrt(numel(expected_position)-1);
      testCase.verifyLessThan(level_lag_one_rms, level_zero_rms, ...
        "Position levels intentionally prefer the wrong one-sample lag.");
      independent = struct("load_position", expected_position);
      report = testoracle.compare_lsim(actual_position, independent, ...
        "nrmse_limit", 0.01, "required_lag_samples", 0);
      testCase.verifyTrue(report.pass);
      testCase.verifyEqual(report.comparison_lag_samples, 0);
      testCase.verifyEqual(report.diagnostic_best_lag_samples, 0);
      testCase.verifyEqual(report.diagnostic_alignment_signal, ...
        "diff(load_position)");
    end

