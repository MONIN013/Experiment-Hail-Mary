    function canonicalDigestIgnoresStructFieldInsertionOrder(testCase)
      first = struct("b", uint32(2), "a", [1, 2, 3]);
      second = struct("a", [1, 2, 3], "b", uint32(2));
      testCase.verifyEqual(testoracle.canonical_digest(first), ...
        testoracle.canonical_digest(second));
      second.a(3) = 4;
      testCase.verifyNotEqual(testoracle.canonical_digest(first), ...
        testoracle.canonical_digest(second));
      testCase.verifyError(@() testoracle.canonical_digest(@sin), ...
        "testoracle:manifest:nonCanonicalValue");
    end

    function liveFreshnessRequiresFileAndOutputDigestChanges(testCase)
      directory = string(tempname);
      mkdir(directory);
      cleanup = onCleanup(@() remove_directory(directory));
      fixture = fullfile(directory, "rich-live-fixture.m");
      writelines("before", fixture);
      before_sha256 = testoracle.file_sha256(fixture);
      writelines(["before"; "after"], fixture);
      after_sha256 = testoracle.file_sha256(fixture);
      testCase.verifyNotEqual(before_sha256, after_sha256);

      before_report = struct("output_json", "{""value"":1}");
      after_report = struct("output_json", "{""value"":2}");
      evidence = testoracle.live_freshness_evidence( ...
        before_sha256, before_report, after_sha256, after_report, ...
        "before_datenum", 2, "after_datenum", 1);
      testCase.verifyTrue(evidence.pass);
      testCase.verifyTrue(evidence.file_sha256_changed);
      testCase.verifyTrue(evidence.output_json_digest_changed);
      testCase.verifyFalse(evidence.source_timestamp_not_older, ...
        "mtime is auxiliary evidence and must not decide freshness.");

      evidence = testoracle.live_freshness_evidence( ...
        before_sha256, before_report, before_sha256, after_report);
      testCase.verifyFalse(evidence.pass);
      evidence = testoracle.live_freshness_evidence( ...
        before_sha256, before_report, after_sha256, before_report);
      testCase.verifyFalse(evidence.pass);
    end

    function artifactContractCanonicalizesValuesInsideTolerance(testCase)
      expected = struct("x", [1; 2], "label", "frozen");
      units = struct("path", "root.x", "unit", "1");
      contract = testoracle.artifact_contract(expected, ...
        "required_fields", ["x", "label"], ...
        "absolute_tolerance", struct("x", 1e-3), "units", units);
      actual = expected;
      actual.x(2) = actual.x(2) + 5e-4;
      report = testoracle.verify_artifact(actual, contract, "units", units);
      testCase.verifyTrue(report.pass);
      testCase.verifyTrue(report.digest_match);

      wrong_units = units;
      wrong_units.unit = "rad";
      report = testoracle.verify_artifact( ...
        actual, contract, "units", wrong_units);
      testCase.verifyFalse(report.pass);
      testCase.verifyFalse(report.units_match);

      actual.x(2) = actual.x(2) + 1e-2;
      report = testoracle.verify_artifact(actual, contract, "units", units);
      testCase.verifyFalse(report.pass);
      testCase.verifyFalse(report.value_match);
    end

