    function rawLoggerContractUsesSpecifiedQuantizationGates(testCase)
      cfg = short_config(128, 0.02);
      prediction = virtualMotor.predict_logger(cfg, virtualMotor.PlantConfig());
      actual = struct("raw", prediction.raw);
      tables = command_tables(cfg);
      report = testoracle.compare_raw_logger(actual, prediction, ...
