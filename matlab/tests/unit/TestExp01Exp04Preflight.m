classdef TestExp01Exp04Preflight < matlab.unittest.TestCase
  methods (Test)
    function preflightIsReadOnlyAndChecksRuntimePrerequisites(testCase)
      script_path = fullfile( ...
        fileparts(fileparts(fileparts(mfilename("fullpath")))), ...
        "tools", ...
        "run_exp01_exp04_preflight.m");
      source = string(fileread(script_path));

      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "run_verify_xar.m"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "plant.mat"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "experiment.exp0n.load_plant_data("));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "experiment.exp0n.load_trajectory("));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        '"tf2sos", "Signal Processing Toolbox"'));
      testCase.verifyFalse(contains(source, "use_virtual_motor"));
      testCase.verifyFalse(contains(source, "run_verify_virtual_motor.m"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "run('matlab/experiment/exp01_SysId.m')"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "run('matlab/experiment/exp02_FeedBack.m')"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "run('matlab/experiment/exp03_FeedForward.m')"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "run('matlab/experiment/exp04_ILC.m')"));
      testCase.verifyFalse(contains(source, "ExperimentRunner.run"));
      testCase.verifyFalse(contains(source, "write_scalar"));
      testCase.verifyFalse(contains(source, "modeFlags"));
      testCase.verifyFalse(contains(source, "plant_out"));
      testCase.verifyFalse(contains(source, "frf_out"));
    end
  end
end
