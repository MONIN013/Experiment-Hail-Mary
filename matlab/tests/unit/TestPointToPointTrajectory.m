classdef TestPointToPointTrajectory < matlab.unittest.TestCase
  methods (Test)
    function backAndForthTrajectoryHasExpectedShape(testCase)
      Ts = 0.001;
      traj = experiment.waveform.point_to_point_trajectory( ...
        "Ts", Ts, ...
        "target_position_rad", 2.0, ...
        "vmax", 20.0, ...
        "amax", 200.0, ...
        "jmax", 4000.0, ...
        "smax", 1e5, ...
        "motion_start_s", 0.1, ...
        "dwell_s", 0.1, ...
        "back_and_forth", true, ...
        "total_time_s", 1.0);

      testCase.verifyEqual(fieldnames(traj), {'t'; 'p'; 'v'; 'a'});
      testCase.verifySize(traj.t, [1000, 1]);
      testCase.verifySize(traj.p, [1000, 1]);
      testCase.verifySize(traj.v, [1000, 1]);
      testCase.verifySize(traj.a, [1000, 1]);
      testCase.verifyEqual(traj.p(traj.t < 0.1), zeros(nnz(traj.t < 0.1), 1), "AbsTol", 1e-12);
      testCase.verifyLessThan(abs(traj.p(end)), 1e-10);
      testCase.verifyGreaterThan(max(traj.p), 1.99);
      testCase.verifyLessThanOrEqual(max(abs(traj.v)), 20.0 + 1e-10);
      testCase.verifyLessThanOrEqual(max(abs(traj.a)), 200.0 + 1e-10);
    end

    function derivativesAreConsistentWithPosition(testCase)
      Ts = 0.002;
      traj = experiment.waveform.point_to_point_trajectory( ...
        "Ts", Ts, ...
        "target_position_rad", 1.0, ...
        "vmax", 10.0, ...
        "amax", 100.0, ...
        "jmax", 2000.0, ...
        "smax", 5e4, ...
        "motion_start_s", 0.05, ...
        "dwell_s", 0.1, ...
        "back_and_forth", true, ...
        "total_time_s", 1.0);

      v_fd = gradient(traj.p, Ts);
      a_fd = gradient(traj.v, Ts);

      testCase.verifyLessThan(max(abs(v_fd - traj.v)), 0.02);
      testCase.verifyLessThan(max(abs(a_fd - traj.a)), 1.0);
    end

    function oneWayTrajectoryHoldsTargetAfterMove(testCase)
      traj = experiment.waveform.point_to_point_trajectory( ...
        "Ts", 0.01, ...
        "target_position_rad", -0.75, ...
        "vmax", 20.0, ...
        "amax", 200.0, ...
        "jmax", 4000.0, ...
        "smax", 1e5, ...
        "motion_start_s", 0.1, ...
        "dwell_s", 0.2, ...
        "back_and_forth", false, ...
        "total_time_s", 1.0);

      testCase.verifyEqual(traj.p(end), -0.75, "AbsTol", 1e-12);
      testCase.verifyEqual(traj.v(end), 0.0, "AbsTol", 1e-12);
      testCase.verifyEqual(traj.a(end), 0.0, "AbsTol", 1e-12);
    end

    function rejectsImpossibleLimits(testCase)
      testCase.verifyError(@() experiment.waveform.point_to_point_trajectory( ...
        "Ts", 0.001, ...
        "target_position_rad", 10.0, ...
        "vmax", 0.1, ...
        "amax", 1.0, ...
        "jmax", 10.0, ...
        "smax", 100.0, ...
        "motion_start_s", 0.1, ...
        "dwell_s", 0.1, ...
        "back_and_forth", true, ...
        "total_time_s", 1.0), ...
        "experiment:waveform:invalidTrajectory");
    end
  end
end
