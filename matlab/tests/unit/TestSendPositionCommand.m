classdef TestSendPositionCommand < matlab.unittest.TestCase
  methods (Test)
    function basicFlowWritesExpectedSymbols(testCase)
      plc = MockAdsTransport();
      seed_plc_state(plc);
      plc.set_scalar_read_sequence("GVL_SEQ.experimentActive", [false; false; true; true; false]);

      out = experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ref_profile", [0.1; 0.2; 0.3], ...
        "plc_transport", plc, ...
        "validate_symbols", false, ...
        "read_logs", false, ...
        "done_timeout_s", 0.05, ...
        "reset_timeout_s", 0.05);

      joined = strjoin(plc.operations, "|");
      testCase.verifyThat(joined, matlab.unittest.constraints.ContainsSubstring("write_array:GVL_SEQ.refTable"));
      testCase.verifyThat(joined, matlab.unittest.constraints.ContainsSubstring("write_array:GVL_SEQ.ffTable"));
      testCase.verifyThat(joined, matlab.unittest.constraints.ContainsSubstring("write_array:GVL_SEQ.distTable"));
      testCase.verifyThat(joined, matlab.unittest.constraints.ContainsSubstring("write_scalar:GVL_SEQ.tableLen"));
      testCase.verifyThat(joined, matlab.unittest.constraints.ContainsSubstring("write_scalar:GVL_MODE.modeFlags"));
      testCase.verifyEqual(string(out.host.mode_flags_symbol), "GVL_MODE.modeFlags");
      testCase.verifyFalse(out.host.servo_ready_check_supported);
      testCase.verifyEqual(double(out.host.control_ams_port), 851);
      testCase.verifyTrue(out.host.done);
      testCase.verifyFalse(out.host.timed_out);
    end

    function defaultsFillFfAndDistProfiles(testCase)
      plc = MockAdsTransport();
      seed_plc_state(plc);

      out = experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ref_profile", [0.5; 0.6], ...
        "plc_transport", plc, ...
        "validate_symbols", false, ...
        "wait_for_done", false, ...
        "hold_seconds", 0.0, ...
        "read_logs", false);

      testCase.verifyEqual(out.cmd.ff_profile, [0; 0]);
      testCase.verifyEqual(out.cmd.dist_profile, [0; 0]);
      testCase.verifyEqual(double(plc.arrayMap("GVL_SEQ.ffTable")), [0; 0]);
      testCase.verifyEqual(double(plc.arrayMap("GVL_SEQ.distTable")), [0; 0]);
    end

    function mismatchedProfileLengthsRaise(testCase)
      plc = MockAdsTransport();
      seed_plc_state(plc);

      testCase.verifyError(@() experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ref_profile", [1; 2; 3], ...
        "ff_profile", [0; 0], ...
        "plc_transport", plc, ...
        "validate_symbols", false), ...
        "experiment:position_command:invalidConfig");
    end

    function timeoutSetsTimedOutFlagAndCleansUp(testCase)
      plc = MockAdsTransport();
      seed_plc_state(plc);
      plc.set_scalar_read_sequence("GVL_SEQ.experimentActive", [false; true; true; true; true]);

      lastwarn("");
      out = experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ref_profile", [0.1; 0.1], ...
        "plc_transport", plc, ...
        "validate_symbols", false, ...
        "read_logs", false, ...
        "done_timeout_s", 0.01, ...
        "reset_timeout_s", 0.05);
      [~, warn_id] = lastwarn;

      testCase.verifyTrue(out.host.timed_out);
      testCase.verifyEqual(string(warn_id), "experiment:position_command:timeout");
      testCase.verifyEqual(uint32(plc.scalarMap("GVL_MODE.modeFlags")), uint32(0));
    end

    function readsUpperLogsOnSuccess(testCase)
      plc = MockAdsTransport();
      seed_plc_state(plc);
      seed_log_arrays(plc);
      plc.scalarMap("GVL_SEQ_LOG.wrIdx") = uint32(3);
      plc.scalarMap("GVL_SEQ_LOG.overflow") = false;
      plc.set_scalar_read_sequence("GVL_SEQ.experimentActive", [false; false; true; true; false]);

      out = experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ref_profile", [0.1; 0.2; 0.3], ...
        "plc_transport", plc, ...
        "validate_symbols", false, ...
        "read_logs", true, ...
        "done_timeout_s", 0.05, ...
        "reset_timeout_s", 0.05);

      testCase.verifyEqual(out.raw.logRefValue(:), [0.1; 0.2; 0.3]);
      testCase.verifyEqual(out.raw.logPositionAct(:), [0.0; 0.01; 0.02]);
      testCase.verifyEqual(out.raw.log_wrIdx, 3);
      testCase.verifyFalse(out.raw.log_overflow);
    end

    function logReadFailureWarnsAndReturnsEmptyLogs(testCase)
      plc = MockAdsTransport();
      seed_plc_state(plc);
      seed_log_arrays(plc);
      plc.scalarMap("GVL_SEQ_LOG.wrIdx") = uint32(2);
      plc.set_scalar_read_sequence("GVL_SEQ.experimentActive", [false; false; true; true; false]);
      remove(plc.arrayMap, "GVL_SEQ_LOG.logControlInput");

      lastwarn("");
      out = experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ref_profile", [0.1; 0.2], ...
        "plc_transport", plc, ...
        "validate_symbols", false, ...
        "read_logs", true, ...
        "done_timeout_s", 0.05, ...
        "reset_timeout_s", 0.05);
      [~, warn_id] = lastwarn;

      testCase.verifyEqual(string(warn_id), "experiment:position_command:logUnavailable");
      testCase.verifyEmpty(out.raw.logRefValue);
      testCase.verifyEmpty(out.raw.logPositionAct);
    end

    function fallsBackToGvlSeqModeFlagsWhenGvlModeMissing(testCase)
      plc = MockAdsTransport();
      seed_plc_state(plc);
      remove(plc.scalarMap, "GVL_MODE.modeFlags");
      plc.set_scalar_read_sequence("GVL_SEQ.experimentActive", [false; false; true; true; false]);

      out = experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ref_profile", [0.1; 0.2], ...
        "plc_transport", plc, ...
        "validate_symbols", false, ...
        "read_logs", false, ...
        "done_timeout_s", 0.05, ...
        "reset_timeout_s", 0.05);

      joined = strjoin(plc.operations, "|");
      testCase.verifyEqual(string(out.host.mode_flags_symbol), "GVL_SEQ.modeFlags");
      testCase.verifyThat(joined, matlab.unittest.constraints.ContainsSubstring("write_scalar:GVL_SEQ.modeFlags"));
      testCase.verifyTrue(out.host.done);
    end

    function noServoReadyTimeoutWhenExperimentStateUnavailable(testCase)
      plc = MockAdsTransport();
      seed_plc_state(plc);
      if isKey(plc.scalarMap, "GVL_MODE.experimentState")
        remove(plc.scalarMap, "GVL_MODE.experimentState");
      end
      plc.set_scalar_read_sequence("GVL_SEQ.experimentActive", [false; false; true; true; false]);

      lastwarn("");
      out = experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ams_port", 853, ...
        "ref_profile", [0.1; 0.2], ...
        "plc_transport", plc, ...
        "validate_symbols", false, ...
        "read_logs", false, ...
        "done_timeout_s", 0.05, ...
        "reset_timeout_s", 0.05);
      [~, warn_id] = lastwarn;

      testCase.verifyFalse(out.host.servo_ready_check_supported);
      testCase.verifyFalse(out.host.servo_ready);
      testCase.verifyNotEqual(string(warn_id), "experiment:position_command:servoReadyTimeout");
      testCase.verifyTrue(out.host.done);
      testCase.verifyEqual(double(out.host.control_ams_port), 852);
    end

    function usesSeparateControlTransportWhenProvided(testCase)
      plc = MockAdsTransport();
      ctrl = MockAdsTransport();
      seed_plc_state(plc);
      seed_control_state(ctrl);

      testCase.verifyError(@() experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ams_port", 853, ...
        "control_ams_port", 852, ...
        "ref_profile", [0.1; 0.2], ...
        "plc_transport", plc, ...
        "control_transport", ctrl, ...
        "validate_symbols", false, ...
        "read_logs", false, ...
        "done_timeout_s", 0.05, ...
        "reset_timeout_s", 0.05), ...
        "experiment:position_command:invalidConfig");
    end

    function splitPortsExplicitModeFlagsUsesDataTransport(testCase)
      plc = MockAdsTransport();
      ctrl = MockAdsTransport();
      seed_plc_state(plc);
      seed_control_state(ctrl);
      ctrl.set_scalar_read_sequence("GVL_MODE.experimentState", uint32([0; 1; 2; 3]));

      out = experiment.send_position_command( ...
        "ams_net_id", "192.168.10.3.1.1", ...
        "ams_port", 853, ...
        "control_ams_port", 852, ...
        "ref_profile", [0.1; 0.2], ...
        "plc_transport", plc, ...
        "control_transport", ctrl, ...
        "mode_flags_transport", plc, ...
        "mode_flags_symbol", "GVL_SEQ.modeFlags", ...
        "validate_symbols", false, ...
        "read_logs", false, ...
        "done_timeout_s", 0.05, ...
        "reset_timeout_s", 0.05);

      plc_ops = strjoin(plc.operations, "|");
      ctrl_ops = strjoin(ctrl.operations, "|");
      testCase.verifyThat(plc_ops, matlab.unittest.constraints.ContainsSubstring("write_scalar:GVL_SEQ.modeFlags"));
      testCase.verifyThat(ctrl_ops, matlab.unittest.constraints.ContainsSubstring("read_scalar:GVL_MODE.experimentState"));
      testCase.verifyEqual(string(out.host.mode_flags_symbol), "GVL_SEQ.modeFlags");
      testCase.verifyTrue(out.host.servo_ready_check_supported);
      testCase.verifyEqual(double(out.host.control_ams_port), 852);
      testCase.verifyTrue(out.host.done);
    end

    function defaultsControlPortTo852WhenDataPortIs853(testCase)
      plc = MockAdsTransport();
