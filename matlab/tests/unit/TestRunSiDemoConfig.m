classdef TestRunSiDemoConfig < matlab.unittest.TestCase
  methods (Test)
    function demoUsesExperimentRunnerAndAnalysisHelpers(testCase)
      script_path = fullfile(fileparts(fileparts(fileparts(mfilename("fullpath")))), "tools", "run_si_demo.m");
      source = string(fileread(script_path));

      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg = experiment.ExperimentConfig.defaults();"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "chirp_cfg = experiment.waveform.periodic_chirp("));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.write_virtual_motor_params = true;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.restart_virtual_motor_runtime = false;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.host_heartbeat_enable = false;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.external_host_heartbeat_enable = true;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "experiment.exp0n.assert_run_contract(run_out);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "collect_out = experiment.exp0n.run_and_collect(cfg);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "frf_out = experiment.analyze_si_frf(logger_bin, ..."));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "logger_bin = collect_out.logger_bin;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "experiment.plot.si_frf("));
      testCase.verifyFalse(contains(source, "read_latest_logger_bin"));
      testCase.verifyFalse(contains(source, "restoredefaultpath;"));
      testCase.verifyFalse(contains(source, "addpath(genpath("));
    end

    function demoPinsSiSpecificProfiles(testCase)
      script_path = fullfile(fileparts(fileparts(fileparts(mfilename("fullpath")))), "tools", "run_si_demo.m");
      source = string(fileread(script_path));

      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "Tend = 10;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.ref_profile = zeros(sample_n, 1);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.ff_profile = chirp_cfg.signal(:);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.dist_profile = zeros(sample_n, 1);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.repeat_count = repeat_count;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "repeat_count = 10;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "A = 0.25;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "remove_chirp_mean = true;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "if remove_chirp_mean"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "chirp_cfg.signal = chirp_cfg.signal - chirp_dc_A;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        'warning("experiment:run_si_demo:chirpMeanRetained", ...'));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "positive_frequency = freq_hz > 0;"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "position_frf = velocity_frf(positive_frequency) ./ (1i * 2 * pi * position_freq_hz);"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        '"output_signal_name", "load_position"'));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "vm_cfg = experiment.exp01.nominal_overlay_plant();"));
      testCase.verifyThat(source, matlab.unittest.constraints.ContainsSubstring( ...
        "cfg.controller = experiment.ControllerConfig.p_only(Kp);"));
      testCase.verifyFalse(contains(source, "sweep_type"));
      testCase.verifyFalse(contains(source, "virtualMotor.predict_logger("));
      testCase.verifyFalse(contains(source, "virtualMotor.compare_prediction("));
      testCase.verifyFalse(contains(source, "virtualMotor.assert_prediction("));
      testCase.verifyFalse(contains(source, "virtualMotor.discrete_velocity_frf("));
    end
  end
end
