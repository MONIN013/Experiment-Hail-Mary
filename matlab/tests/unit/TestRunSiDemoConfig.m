classdef TestRunSiDemoConfig < matlab.unittest.TestCase
  methods (Test)
    function demoUsesSharedRuntimeAndAnalysisHelpers(testCase)
      source = read_tool_source("run_si_demo.m");
      required = ["experiment.ExperimentConfig.defaults()", ...
        "experiment.waveform.periodic_chirp(", ...
        "experiment.exp0n.run_and_collect(cfg)", ...
        "logger_bin = collect_out.logger_bin", ...
        "experiment.exp0n.assert_run_contract(run_out)", ...
        "experiment.analyze_si_frf(logger_bin", ...
        "experiment.plot.si_frf("];
      for value = required
        testCase.verifyTrue(contains(source, value));
      end
      verify_normal_tool_has_no_vm_oracle(testCase, source);
      testCase.verifyFalse(contains(source, "read_latest_logger_bin"));
      testCase.verifyFalse(contains(source, "restoredefaultpath;"));
      testCase.verifyFalse(contains(source, "addpath(genpath("));
    end

    function demoPinsSiSpecificProfiles(testCase)
      source = read_tool_source("run_si_demo.m");
      required = ["Tend = 10;", "Tcycle = 10;", ...
        "repeat_count = 10;", "f0 = 0.1;", "f1 = 4000;", ...
        "A = 0.25;", "transient_cycles = 2;", ...
        "remove_chirp_mean = true;", ...
        "driver_current_quantum_A = 1.6 / 1000;", ...
        "[balanced, balance_report] = experiment.waveform.balance_quantized_cycle(", ...
        "chirp_cfg.balance = balance_report;", ...
        "cfg.ref_profile = zeros(sample_n, 1);", ...
        "cfg.ff_profile = balanced;", ...
        "cfg.dist_profile = zeros(sample_n, 1);", ...
        "cfg.repeat_count = repeat_count;", ...
        "cfg.controller = experiment.ControllerConfig.p_only(Kp);", ...
        "frf_out.position_freq_hz", ...
        "frf_out.position_frf", ...
        '"derived_from", frf_out.output_signal_name + " via Ts/(1-z^-1)"', ...
        '"output_signal_name", "load_position"'];
      for value = required
        testCase.verifyTrue(contains(source, value));
      end
      testCase.verifyFalse(contains(source, "sweep_type"));
      testCase.verifyFalse(contains(source, "1i * 2 * pi * position_freq_hz"));
      testCase.verifyFalse(contains(source, "virtualMotor.discrete_velocity_frf("));
    end
  end
end

function source = read_tool_source(file_name)
root = fileparts(fileparts(fileparts(mfilename("fullpath"))));
source = string(fileread(fullfile(root, "tools", file_name)));
end

function verify_normal_tool_has_no_vm_oracle(testCase, source)
for forbidden = [ ...
    "virtualMotor.predict_logger(", "virtualMotor.compare_prediction(", ...
    "virtualMotor.assert_prediction(", "virtualMotor.restart_runtime(", ...
    "virtualMotor.configure(", "virtualMotor.writeParams("]
  testCase.verifyFalse(contains(source, forbidden), ...
    "Normal demos must leave VM prediction and reconfiguration to tests.");
end
end
