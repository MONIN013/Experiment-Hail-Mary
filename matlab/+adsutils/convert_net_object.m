function x = convert_net_object(obj)
if isa(obj, "System.Boolean")
    x = logical(obj);
elseif isa(obj, "System.Byte") || isa(obj, "System.UInt16") || ...
        isa(obj, "System.UInt32") || isa(obj, "System.UInt64") || ...
        isa(obj, "System.SByte") || isa(obj, "System.Int16") || ...
        isa(obj, "System.Int32") || isa(obj, "System.Int64") || ...
        isa(obj, "System.Single") || isa(obj, "System.Double")
    x = double(obj);
else
    x = obj;
end
end
