function [Tports, Tsymbols] = discover_ports_and_symbols(amsNetId, ports, varargin)
if nargin < 1
    amsNetId = "";
end
if nargin < 2 || isempty(ports)
    ports = [851 351];
end

p = inputParser;
p.addParameter("ads_assembly", "TwinCAT.Ads", @(x) ischar(x) || isstring(x));
p.addParameter("connect_timeout_ms", 500, @(x) isnumeric(x) && isscalar(x) && x > 0);
p.addParameter("top_level_only", true, @(x) islogical(x) || isnumeric(x));
p.addParameter("force_reload", true, @(x) islogical(x) || isnumeric(x));
p.parse(varargin{:});
cfg = p.Results;

Tports = adsutils.list_ports( ...
    amsNetId, ...
    ports, ...
    "ads_assembly", cfg.ads_assembly, ...
    "connect_timeout_ms", cfg.connect_timeout_ms);

rows = cell(height(Tports), 1);
for k = 1:height(Tports)
    amsIdK = Tports.AmsNetId(k);
    portK = Tports.Port(k);

    if Tports.Connectable(k)
        rows{k} = adsutils.list_symbols_for_port( ...
            amsIdK, ...
            portK, ...
            "ads_assembly", cfg.ads_assembly, ...
            "top_level_only", logical(cfg.top_level_only), ...
            "force_reload", logical(cfg.force_reload));
    else
        rows{k} = table( ...
            amsIdK, ...
            portK, ...
            string(""), ...
            string(""), ...
            int32(0), ...
            "symbol_loader_failed", ...
            "Port unavailable (" + Tports.Status(k) + "): " + Tports.ErrorMessage(k), ...
            'VariableNames', {'AmsNetId', 'Port', 'Name', 'Type', 'SizeBytes', 'Status', 'ErrorMessage'});
    end
end

if isempty(rows)
    Tsymbols = table( ...
        strings(0, 1), ...
        int32(zeros(0, 1)), ...
        strings(0, 1), ...
        strings(0, 1), ...
        int32(zeros(0, 1)), ...
        strings(0, 1), ...
        strings(0, 1), ...
        'VariableNames', {'AmsNetId', 'Port', 'Name', 'Type', 'SizeBytes', 'Status', 'ErrorMessage'});
else
    Tsymbols = vertcat(rows{:});
end
end
