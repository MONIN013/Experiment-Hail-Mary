%% ADS transport API end-to-end check against the idle VM runtime
%
% Scalar/struct/array APIs are exercised on live ADS ports. Write checks
% write the already-observed value back while the experiment state is IDLE.

run_ads_transport_e2e_result = run_ads_transport_e2e_main();

function ads_transport_e2e = run_ads_transport_e2e_main()

tool_file = mfilename("fullpath");
matlab_root = fileparts(fileparts(tool_file));
addpath(matlab_root, fullfile(matlab_root, "experiment"));
clear tool_file matlab_root;

cfg = experiment.ExperimentConfig.defaults();
conn = experiment.ConnectionManager.create(cfg);
cleanup = onCleanup(@() conn.session.close());
symbols = experiment.RuntimeSymbols.from_defaults();
controller_symbols = experiment.RuntimeSymbols.from_controller_prefix( ...
  cfg.env.controller_prefix);
t = twincat_ads.AdsTransport.net_types();
controller_coefficient_n = experiment.ControllerConfig.MAX_SOS_SECTIONS * ...
  experiment.ControllerConfig.ADS_COEFFICIENTS_PER_SECTION;

idle_map = struct( ...
  "experiment_active", {{symbols.experimentActive, t.bool}}, ...
  "mode_state", {{symbols.modeState, t.i16}}, ...
  "logger_file_released", {{symbols.loggerFileReleased, t.bool}});
idle = conn.ctrl.read_struct(idle_map);
if logical(idle.experiment_active) || int16(idle.mode_state) ~= int16(0)
  error("experiment:ads_transport_e2e:notIdle", ...
    "Live ADS write checks require experimentActive=0 and modeState=IDLE.");
end

table_len = double(conn.seq.read_scalar(symbols.tableLen, t.u32));
if table_len < 0 || table_len > cfg.env.table_max_n
  error("experiment:ads_transport_e2e:invalidTableLength", ...
    "Expected 0..%d table samples, got %g.", cfg.env.table_max_n, table_len);
end
% A freshly activated idle PLC has tableLen=0. Probe the first physical array
% element without publishing a logical table length or changing its value.
probe_length = max(1, table_len);
reference_before = conn.seq.read_array(symbols.refTable, t.double, probe_length);
slice_start = min(2, probe_length - 1);
slice_count = min(4, probe_length - slice_start);
reference_slice = conn.seq.read_array_slice( ...
  symbols.refTable, t.double, slice_start, slice_count);
if ~isequal(reference_slice, reference_before(slice_start + (1:slice_count)))
  error("experiment:ads_transport_e2e:sliceMismatch", ...
    "read_array_slice does not match read_array for refTable.");
end

controller_before = struct( ...
  "coefficients", conn.module.read_array( ...
    controller_symbols.controllerParams.coefficients, t.double, controller_coefficient_n), ...
  "section_count", conn.module.read_scalar( ...
    controller_symbols.controllerParams.sectionCount, t.u32), ...
  "apply_revision", conn.module.read_scalar( ...
    controller_symbols.controllerParams.applyRevision, t.u32), ...
  "applied_revision", conn.module.read_scalar( ...
    controller_symbols.controllerParams.appliedRevision, t.u32), ...
  "processed_revision", conn.module.read_scalar( ...
    controller_symbols.controllerParams.processedRevision, t.u32), ...
  "parameter_error_code", conn.module.read_scalar( ...
    controller_symbols.controllerParams.parameterErrorCode, t.u32));

% Reversible write E2E: write the exact current payload while IDLE.
conn.seq.write_array(symbols.refTable, reference_before, t.double);
conn.module.write_array(controller_symbols.controllerParams.coefficients, ...
  controller_before.coefficients, t.double);
conn.module.write_scalar(controller_symbols.controllerParams.sectionCount, ...
  controller_before.section_count, t.u32);
conn.module.write_scalar(controller_symbols.controllerParams.applyRevision, ...
  controller_before.apply_revision, t.u32);

reference_after = conn.seq.read_array(symbols.refTable, t.double, probe_length);
controller_after = struct( ...
  "coefficients", conn.module.read_array( ...
    controller_symbols.controllerParams.coefficients, t.double, controller_coefficient_n), ...
  "section_count", conn.module.read_scalar( ...
    controller_symbols.controllerParams.sectionCount, t.u32), ...
  "apply_revision", conn.module.read_scalar( ...
    controller_symbols.controllerParams.applyRevision, t.u32), ...
  "applied_revision", conn.module.read_scalar( ...
    controller_symbols.controllerParams.appliedRevision, t.u32), ...
  "processed_revision", conn.module.read_scalar( ...
    controller_symbols.controllerParams.processedRevision, t.u32), ...
  "parameter_error_code", conn.module.read_scalar( ...
    controller_symbols.controllerParams.parameterErrorCode, t.u32));
reference_equal = isequaln(reference_after, reference_before);
controller_equal = isequaln(controller_after, controller_before);
if ~reference_equal || ~controller_equal
  error("experiment:ads_transport_e2e:writeMismatch", ...
    "ADS same-value write/readback mismatch (referenceEqual=%d, controllerEqual=%d, " + ...
    "referenceBefore=%s, referenceAfter=%s).", ...
    reference_equal, controller_equal, mat2str(reference_before), mat2str(reference_after));
end

module_state = conn.module.read_client().ReadState();
ads_transport_e2e = struct( ...
  "pass", true, ...
  "table_length", table_len, ...
  "probe_length", probe_length, ...
  "slice_start_zero_based", slice_start, ...
  "slice_count", slice_count, ...
  "idle", idle, ...
  "controller", controller_after, ...
  "module_ads_state", string(module_state.AdsState));
fprintf("ADS transport E2E PASS: table=%d, probed=%d, slice=[%d..%d], " + ...
  "sosSections=%d, revision=%u, module=%s\n", ...
  table_len, probe_length, slice_start, slice_start + slice_count - 1, ...
  uint32(controller_after.section_count), uint32(controller_after.apply_revision), ...
  ads_transport_e2e.module_ads_state);
end
