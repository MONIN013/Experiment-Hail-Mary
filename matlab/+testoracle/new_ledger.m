function ledger = new_ledger(manifest)
% new_ledger  Create a mutable execution ledger linked to a frozen manifest.
if ~isstruct(manifest) || ~isfield(manifest, "canonical_digest") || ...
    ~isfield(manifest, "entries")
  error("testoracle:ledger:invalidManifest", "A frozen manifest is required.");
end
records = repmat(struct( ...
  "name", "", "status", "pending", "pass", false, ...
  "started_at_utc", "", "finished_at_utc", "", ...
  "layers", struct(), "result_digest", "", "detail", ""), ...
  numel(manifest.entries), 1);
for index = 1:numel(records)
  records(index).name = manifest.entries(index).name;
end
ledger = struct( ...
  "format", "ExperimentHailMary.testoracle.ledger", ...
  "version", uint32(1), ...
  "manifest_digest", string(manifest.canonical_digest), ...
  "created_at_utc", utc_now(), ...
  "records", records, ...
  "final_state", struct(), ...
  "complete", false);
end

function value = utc_now()
value = string(datetime("now", "TimeZone", "UTC", ...
  "Format", "yyyy-MM-dd'T'HH:mm:ss.SSSXXX"));
end
