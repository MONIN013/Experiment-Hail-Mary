function evidence = live_freshness_evidence( ...
    before_file_sha256, before_report, after_file_sha256, after_report, options)
%LIVE_FRESHNESS_EVIDENCE Prove that a rich Live Script was freshly saved.
arguments
  before_file_sha256 {mustBeTextScalar}
  before_report (1, 1) struct
  after_file_sha256 {mustBeTextScalar}
  after_report (1, 1) struct
  options.before_datenum (1, 1) double = NaN
  options.after_datenum (1, 1) double = NaN
  options.source_exists (1, 1) logical = true
  options.backup_exists (1, 1) logical = true
end

if ~isfield(before_report, "output_json") || ...
    ~isfield(after_report, "output_json")
  error("testoracle:live:missingOutputJson", ...
    "Both Live Script inspection reports must contain output_json.");
end

before_file_sha256 = string(before_file_sha256);
after_file_sha256 = string(after_file_sha256);
before_output_digest = testoracle.canonical_digest(before_report.output_json);
after_output_digest = testoracle.canonical_digest(after_report.output_json);
file_changed = before_file_sha256 ~= after_file_sha256;
output_changed = before_output_digest ~= after_output_digest;
timestamp_not_older = isnan(options.before_datenum) || ...
  isnan(options.after_datenum) || ...
  options.after_datenum >= options.before_datenum;

evidence = struct( ...
  "before_file_sha256", before_file_sha256, ...
  "after_file_sha256", after_file_sha256, ...
  "file_sha256_changed", logical(file_changed), ...
  "before_output_json_digest", before_output_digest, ...
  "after_output_json_digest", after_output_digest, ...
  "output_json_digest_changed", logical(output_changed), ...
  "source_exists", options.source_exists, ...
  "backup_exists", options.backup_exists, ...
  "before_datenum", options.before_datenum, ...
  "after_datenum", options.after_datenum, ...
  "source_timestamp_not_older", logical(timestamp_not_older), ...
  "pass", logical(file_changed && output_changed));
end
