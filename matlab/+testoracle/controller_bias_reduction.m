function report = controller_bias_reduction( ...
    controller_names, design_methods, absolute_mean_bias, contract)
%CONTROLLER_BIAS_REDUCTION Score the frozen like-for-like integral pair.
arguments
  controller_names (:, 1) string
  design_methods (:, 1) string
  absolute_mean_bias (:, 1) double
  contract (1, 1) struct
end
required = ["integral_controller", "integral_design_method", ...
  "baseline_controller", "baseline_design_method", "metric", ...
  "excluded_pair", "exclusion_reason"];
if any(~isfield(contract, required)) || ...
    numel(controller_names) ~= numel(design_methods) || ...
    numel(controller_names) ~= numel(absolute_mean_bias) || ...
    any(~isfinite(absolute_mean_bias)) || any(absolute_mean_bias < 0)
  error("testoracle:controller:invalidBiasContract", ...
    "Controller bias evidence does not match the frozen comparison contract.");
end
integral = find(controller_names == string(contract.integral_controller));
baseline = find(controller_names == string(contract.baseline_controller));
unique_pair = isscalar(integral) && isscalar(baseline);
if unique_pair
  methods_match = design_methods(integral) == ...
      string(contract.integral_design_method) && ...
    design_methods(baseline) == string(contract.baseline_design_method);
  reduced = absolute_mean_bias(integral) < absolute_mean_bias(baseline);
  integral_bias = absolute_mean_bias(integral);
  baseline_bias = absolute_mean_bias(baseline);
else
  methods_match = false;
  reduced = false;
  integral_bias = NaN;
  baseline_bias = NaN;
end
report = struct( ...
  "pass", logical(unique_pair && methods_match && reduced), ...
  "unique_pair", logical(unique_pair), ...
  "design_methods_match", logical(methods_match), ...
  "integral_bias", integral_bias, "baseline_bias", baseline_bias, ...
  "metric", string(contract.metric), ...
  "excluded_pair", string(contract.excluded_pair), ...
  "exclusion_reason", string(contract.exclusion_reason));
end
