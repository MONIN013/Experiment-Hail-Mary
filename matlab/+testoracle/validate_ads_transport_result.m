function report = validate_ads_transport_result(actual, expected)
%VALIDATE_ADS_TRANSPORT_RESULT Apply frozen safe-IDLE transport invariants.
valid = isstruct(actual) && isscalar(actual) && ...
  all(isfield(actual, ["pass", "table_length", "idle", ...
    "controller", "module_ads_state"])) && ...
  islogical(actual.pass) && isscalar(actual.pass) && actual.pass && ...
  isstruct(actual.idle) && isscalar(actual.idle) && ...
  all(isfield(actual.idle, ["experiment_active", "mode_state", ...
    "logger_file_released"])) && ...
  islogical(actual.idle.experiment_active) && ...
  isscalar(actual.idle.experiment_active) && ...
  isnumeric(actual.idle.mode_state) && isscalar(actual.idle.mode_state) && ...
  isfinite(double(actual.idle.mode_state)) && ...
  islogical(actual.idle.logger_file_released) && ...
  isscalar(actual.idle.logger_file_released) && ...
  isstruct(actual.controller) && isscalar(actual.controller) && ...
  all(isfield(actual.controller, ["section_count", "apply_revision", ...
    "applied_revision", "processed_revision", "parameter_error_code"])) && ...
  isnumeric(actual.table_length) && isscalar(actual.table_length) && ...
  isfinite(double(actual.table_length)) && ...
  all(cellfun(@(value) isnumeric(value) && isscalar(value) && ...
    isfinite(double(value)), {actual.controller.section_count, ...
      actual.controller.apply_revision, actual.controller.applied_revision, ...
      actual.controller.processed_revision, ...
      actual.controller.parameter_error_code})) && ...
  (ischar(actual.module_ads_state) || ...
    (isstring(actual.module_ads_state) && isscalar(actual.module_ads_state)));
if ~valid
  report = failed_report(actual, expected);
  return;
end

idle_match = isequal(logical(actual.idle.experiment_active), ...
    logical(expected.experiment_active)) && ...
  isequal(int16(actual.idle.mode_state), int16(expected.mode_state));
table_match = isnumeric(actual.table_length) && ...
  isscalar(actual.table_length) && isfinite(double(actual.table_length)) && ...
  double(actual.table_length) == double(expected.table_length);
section_count = double(actual.controller.section_count);
section_match = isscalar(section_count) && isfinite(section_count) && ...
  section_count >= 0 && fix(section_count) == section_count && ...
  section_count <= double(expected.controller_max_sos_sections);
revisions = double([actual.controller.apply_revision, ...
  actual.controller.applied_revision, actual.controller.processed_revision]);
revision_match = numel(revisions) == 3 && all(isfinite(revisions)) && ...
  all(revisions == revisions(1));
parameter_match = isequal(uint32(actual.controller.parameter_error_code), ...
  uint32(expected.parameter_error_code));
report = struct( ...
  "pass", logical(valid && idle_match && table_match && section_match && ...
    revision_match && parameter_match), ...
  "valid", logical(valid), "idle_match", logical(idle_match), ...
  "table_length_match", logical(table_match), ...
  "controller_section_count_valid", logical(section_match), ...
  "controller_revisions_match", logical(revision_match), ...
  "parameter_error_match", logical(parameter_match), ...
  "logger_file_released_observed", ...
    logical(actual.idle.logger_file_released), ...
  "module_ads_state_observed", string(actual.module_ads_state), ...
  "expected", expected, "actual", actual);
end

function report = failed_report(actual, expected)
report = struct( ...
  "pass", false, "valid", false, "idle_match", false, ...
  "table_length_match", false, ...
  "controller_section_count_valid", false, ...
  "controller_revisions_match", false, ...
  "parameter_error_match", false, ...
  "logger_file_released_observed", false, ...
  "module_ads_state_observed", "", ...
  "expected", expected, "actual", actual);
end
