function report = validate_restart_proof(value)
% validate_restart_proof  Authenticate one completed zero-state VM restart.
required = ["restarted", "elapsed_s", "state_before", "state_after", ...
  "plc_ready", "observable_state"];
if ~isstruct(value) || ~isscalar(value) || any(~isfield(value, required))
  error("testoracle:restart:invalidProof", ...
    "Restart proof is missing required lifecycle evidence.");
end
observable = value.observable_state;
observable_fields = ["motor_position_count", "load_position_count", ...
  "motor_velocity_count", "load_velocity_count"];
if ~isstruct(observable) || ~isscalar(observable) || ...
    any(~isfield(observable, observable_fields))
  error("testoracle:restart:invalidProof", ...
    "Restart proof is missing zero observable-state evidence.");
end

observable_values = zeros(size(observable_fields));
observable_valid = true;
for index = 1:numel(observable_fields)
  item = observable.(char(observable_fields(index)));
  valid = isnumeric(item) && isreal(item) && isscalar(item) && ...
    isfinite(double(item));
  observable_valid = observable_valid && valid;
  if valid, observable_values(index) = double(item); end
end
elapsed_valid = isnumeric(value.elapsed_s) && isreal(value.elapsed_s) && ...
  isscalar(value.elapsed_s) && isfinite(double(value.elapsed_s)) && ...
  double(value.elapsed_s) >= 0;
checks = struct( ...
  "restart_reported", islogical(value.restarted) && ...
    isscalar(value.restarted) && value.restarted, ...
  "elapsed_time_valid", elapsed_valid, ...
  "state_before_run", is_run_state(value.state_before), ...
  "state_after_run", is_run_state(value.state_after), ...
  "plc_ready", islogical(value.plc_ready) && ...
    isscalar(value.plc_ready) && value.plc_ready, ...
  "observable_state_valid", observable_valid, ...
  "observable_state_zero", observable_valid && all(observable_values == 0));
pass = all(structfun(@logical, checks));
if ~pass
  names = string(fieldnames(checks));
  failed = names(~structfun(@logical, checks));
  error("testoracle:restart:invalidProof", ...
    "Restart lifecycle evidence failed: %s.", strjoin(failed, ", "));
end

report = struct( ...
  "pass", true, ...
  "restart_count", double(logical(value.restarted)), ...
  "checks", checks, ...
  "elapsed_s", double(value.elapsed_s), ...
  "state_before", string(value.state_before), ...
  "state_after", string(value.state_after), ...
  "observable_state", observable);
end

function pass = is_run_state(value)
is_text_scalar = (ischar(value) && (isrow(value) || isempty(value))) || ...
  (isstring(value) && isscalar(value));
pass = is_text_scalar && ...
  strcmpi(strtrim(string(value)), "Run");
pass = logical(pass);
end
