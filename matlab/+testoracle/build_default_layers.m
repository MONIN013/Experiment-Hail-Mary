function source = tracking_artifact_source(scenario, prediction, kind)
[signals, metrics] = experiment.exp02.signals_from_logger_bin( ...
  struct("raw", prediction.raw), ...
  "expected_sample_count", prediction.sample_count);
metrics.tracking_error_rms = rms(signals.error);
metrics.tracking_error_peak = max(abs(signals.error));
metrics.final_error = signals.error(end);
metrics.integral_absolute_error = trapz(signals.time_s, abs(signals.error));
metrics.max_abs_current_cmd = max(abs(signals.current_cmd));
reference = repmat(double(scenario.trajectory.p(:)), ...
  double(scenario.cfg.repeat_count), 1);
source = struct( ...
  "t", signals.time_s, "r", reference, "y", signals.position_act, ...
  "e", signals.error, "u", signals.control_input, ...
  "Kd", scenario.Kd, "stability", scenario.stability);
if string(kind) == "exp02"
  source.feedback_metrics = metrics;
else
  feedforward = repmat(double(scenario.feedforward(:)), ...
    double(scenario.cfg.repeat_count), 1);
  metrics.max_abs_feedforward = max(abs(feedforward));
  source.f = feedforward;
  source.feedforward_metrics = metrics;
  source.feedforward_gains = scenario.feedforward_gains;
end
end

function source = ilc_artifact_source(scenario, prediction)
trial_count = double(scenario.trial_count);
reference = double(scenario.trajectory.p(:));
max_abs_input = max(abs(prediction.control_input), [], 1);
max_abs_feedforward = max(abs(prediction.feedforward), [], 1);
max_abs_total_input = max(abs(prediction.current_cmd), [], 1);
max_abs_error = max(abs(prediction.error), [], 1);
error_increased = false(1, trial_count);
convergence_peak = repmat( ...
  scenario.learning_filters.max_convergence_gain, 1, trial_count);
trial_summary = table( ...
  (1:trial_count)', prediction.error_norm(:), max_abs_error(:), ...
  max_abs_input(:), max_abs_feedforward(:), max_abs_total_input(:), ...
  error_increased(:), convergence_peak(:), convergence_peak(:) < 1, ...
  VariableNames=["trial", "errorNorm", "maxAbsError", ...
    "maxAbsInputA", "maxAbsFeedforwardA", "maxAbsTotalInputA", ...
    "errorIncreased", "convergencePeak", "convergenceSatisfied"]);
history = struct( ...
  "t", double(scenario.trajectory.t(:)), ...
  "r", repmat(reference, 1, trial_count), ...
  "y", prediction.position, "e", prediction.error, ...
  "eNorm", prediction.error_norm, "f", prediction.feedforward, ...
  "ffApplied", applied_feedforward(prediction), ...
  "u", prediction.control_input, "maxAbsInput", max_abs_input, ...
  "maxAbsFeedforward", max_abs_feedforward, ...
  "maxAbsTotalInput", max_abs_total_input, ...
  "maxAbsError", max_abs_error, "errorIncreased", error_increased, ...
  "convergencePeak", convergence_peak, ...
  "trialLoggerPaths", compose("trial%02d_logger.bin", 1:trial_count), ...
  "trialLoggerRecordCount", repmat(numel(reference), 1, trial_count), ...
  "maxSensitivity", scenario.stability.max_sensitivity, ...
  "sensitivityLimitExceeded", scenario.stability.limit_exceeded, ...
  "completedTrials", trial_count, "stopReason", "completed", ...
  "bestErrorNorm", prediction.best_error_norm, ...
  "bestTrial", prediction.best_trial, "trialSummary", trial_summary);
source = struct( ...
  "t", double(scenario.trajectory.t(:)), "history", history, ...
