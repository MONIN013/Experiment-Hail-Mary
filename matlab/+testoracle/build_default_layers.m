function layers = build_default_layers(varargin)
% build_default_layers  Precompute all four layers before any VM experiment.
%
% This function can be expensive: the SI and exp01 predictions each contain
% 800,000 samples and all eleven logger signals by design.
p = inputParser;
p.addParameter("plant", virtualMotor.PlantConfig(), ...
  @(x) isa(x, "virtualMotor.PlantConfig") || isstruct(x));
p.parse(varargin{:});
plant_cfg = virtualMotor.PlantConfig.from_struct(p.Results.plant);
registry = testoracle.entry_registry();
outcomes = testoracle.expected_outcomes();
common_gate = outcomes(1).gate.common;
layers = generic_layers(registry, outcomes);
default_cfg = experiment.ExperimentConfig.defaults();
runtime_symbols = experiment.RuntimeSymbols.from_defaults();
vm_symbols = virtualMotor.Symbols.from_defaults();
environment = default_cfg.env;
discovery_index = find(string({layers.name}) == ...
  "tools.run_ads_discovery_demo", 1);
layers(discovery_index).exact.discovery = struct( ...
  "required_ports", unique(int32([environment.control_port, ...
    environment.seq_port, environment.module_port]), "stable"), ...
  "required_symbols", [ ...
    struct("port", double(environment.control_port), ...
      "name", string(runtime_symbols.experimentActive)); ...
    struct("port", double(environment.seq_port), ...
      "name", string(runtime_symbols.tableLen)); ...
    struct("port", double(environment.module_port), ...
      "name", string(vm_symbols.requiredProbes{1, 1}))]);
verify_index = find(string({layers.name}) == ...
  "tools.run_verify_virtual_motor", 1);
layers(verify_index).exact.verification = struct( ...
  "probe_count", size(vm_symbols.requiredProbes, 1), ...
  "module_port", double(environment.module_port));
transport_index = find(string({layers.name}) == ...
  "tools.run_ads_transport_e2e", 1);
layers(transport_index).exact.transport = struct( ...
  "table_length", 0, "experiment_active", false, ...
  "mode_state", int16(0), ...
  "controller_max_sos_sections", common_gate.controller_max_sos_sections, ...
  "parameter_error_code", uint32(0));
configure_index = find(string({layers.name}) == ...
  "tools.run_configure_virtual_motor", 1);
layers(configure_index).exact.requested = struct( ...
  "plant", plant_cfg.to_struct(), ...
  "taskDtNs", uint64(default_cfg.env.task_dt_ns()));

exp01_scenario = experiment.scenario.exp01("save_results", false);
exp01_prediction = virtualMotor.predict_logger(exp01_scenario.cfg, plant_cfg);
assert_safe(exp01_prediction, "exp01", common_gate);
exp01_analysis = experiment.workflow.run_exp01(exp01_scenario, ...
  "collector", @(~) fake_collection(exp01_prediction));
plant_data = exp01_analysis.plant;
trajectory = experiment.exp0n.load_trajectory( ...
  "expected_sample_time_s", exp01_scenario.Ts, ...
  "table_max_n", exp01_scenario.cfg.env.table_max_n);

exp02_scenario = experiment.scenario.exp02( ...
  plant_data, trajectory, "save_results", false, ...
  "Smax", common_gate.sensitivity_peak_max);
exp02_prediction = virtualMotor.predict_logger(exp02_scenario.cfg, plant_cfg);
assert_safe(exp02_prediction, "exp02", common_gate);
exp03_scenario = experiment.scenario.exp03( ...
  plant_data, trajectory, "save_results", false, "Kd", exp02_scenario.Kd, ...
  "Smax", common_gate.sensitivity_peak_max);
exp03_prediction = virtualMotor.predict_logger(exp03_scenario.cfg, plant_cfg);
assert_safe(exp03_prediction, "exp03", common_gate);
exp04_scenario = experiment.scenario.exp04( ...
  plant_data, trajectory, "save_results", false, "Kd", exp02_scenario.Kd, ...
  "Smax", common_gate.sensitivity_peak_max);
exp04_prediction = testoracle.predict_ilc_campaign(exp04_scenario, plant_cfg);

position_gate = outcomes(string({outcomes.name}) == ...
  "tools.run_position_command_demo").gate.experiment;
position_cfg = position_config();
position_prediction = virtualMotor.predict_logger(position_cfg, plant_cfg);
assert_safe(position_prediction, "position demo", common_gate);
si_gate = outcomes(string({outcomes.name}) == ...
  "tools.run_si_demo").gate.experiment;
[si_cfg, si_balance] = si_config(si_gate);
si_prediction = virtualMotor.predict_logger(si_cfg, plant_cfg);
assert_safe(si_prediction, "SI demo", common_gate);
[si_purpose, si_analysis_contract] = si_outcome( ...
  si_prediction, si_cfg, plant_cfg, si_gate);
baseline_cfg = baseline_prediction_config();
baseline_prediction = virtualMotor.predict_logger(baseline_cfg, plant_cfg);
assert_safe(baseline_prediction, "prediction E2E", common_gate);

set_logger_entry("experiment.exp01", exp01_scenario.cfg, exp01_prediction, ...
  exp01_outcome(exp01_scenario, exp01_analysis, plant_cfg), ...
  testoracle.artifact_projection("experiment.exp01", ...
    exp01_artifact_source(exp01_scenario, exp01_prediction, exp01_analysis)), ...
  ["chirp_result.mat", "plant.mat"], ...
  artifact_tolerance("experiment.exp01", exp01_prediction));
set_logger_entry("experiment.exp02", exp02_scenario.cfg, exp02_prediction, ...
  tracking_outcome(exp02_prediction, exp02_scenario, trajectory), ...
  testoracle.artifact_projection("experiment.exp02", ...
    tracking_artifact_source(exp02_scenario, exp02_prediction, "exp02")), ...
  "feedback_result.mat", ...
  artifact_tolerance("experiment.exp02", exp02_prediction));
set_logger_entry("experiment.exp03", exp03_scenario.cfg, exp03_prediction, ...
  feedforward_outcome(exp03_prediction, exp02_prediction, exp03_scenario), ...
  testoracle.artifact_projection("experiment.exp03", ...
    tracking_artifact_source(exp03_scenario, exp03_prediction, "exp03")), ...
  "feedforward_result.mat", ...
  artifact_tolerance("experiment.exp03", exp03_prediction));
set_ilc_entry(exp04_scenario, exp04_prediction);
set_logger_entry("tools.run_position_command_demo", position_cfg, ...
  position_prediction, position_outcome( ...
    position_prediction, position_cfg, position_gate), ...
  testoracle.artifact_projection("tools.run_position_command_demo", ...
    struct("raw", position_prediction.raw)), ...
  "runner-confirmed logger bin", raw_artifact_tolerance(position_prediction));
set_logger_entry("tools.run_si_demo", si_cfg, si_prediction, ...
  si_purpose, ...
  testoracle.artifact_projection("tools.run_si_demo", ...
    struct("raw", si_prediction.raw)), ...
  "runner-confirmed logger bin", raw_artifact_tolerance(si_prediction));
si_index = find_entry("tools.run_si_demo");
layers(si_index).exact.input_balance = si_balance;
layers(si_index).independent.response.si_analysis = si_analysis_contract;
set_logger_entry("tools.run_virtual_motor_prediction_e2e", baseline_cfg, ...
  baseline_prediction, struct("pass", true, "sample_count", baseline_prediction.sample_count), ...
  testoracle.artifact_projection("tools.run_virtual_motor_prediction_e2e", ...
    struct("raw", baseline_prediction.raw)), ...
  "runner-confirmed logger bin", raw_artifact_tolerance(baseline_prediction));

catalog = experiment.exp02.controller_catalog(plant_data, ...
  "Smax", common_gate.sensitivity_peak_max);
designs = [catalog.design];
if any(~logical([designs.gate_ok])) || ...
    any([designs.sos_section_count] > common_gate.controller_max_sos_sections)
  failed = string({catalog(~logical([designs.gate_ok])).name});
  error("testoracle:manifest:controllerGateFailed", ...
    "Controller designs failed the common pre-execution gate: %s.", ...
    strjoin(failed, ", "));
end
controller_exact = repmat(struct("name", "", "family", "", ...
  "controller", struct(), "design", struct(), "config", struct(), ...
  "prediction", struct(), "raw_contract", struct()), ...
  numel(catalog), 1);
controller_independent = repmat(struct("name", "", "response", struct()), numel(catalog), 1);
controller_metrics = repmat(struct( ...
  "name", "", "metrics", struct(), "ranges", struct()), numel(catalog), 1);
for index = 1:numel(catalog)
  cfg = exp02_scenario.cfg;
  cfg.controller = catalog(index).controller_cfg;
  cfg = cfg.normalize();
  prediction = virtualMotor.predict_logger(cfg, plant_cfg);
  assert_safe(prediction, "controller " + catalog(index).name, common_gate);
  independent = testoracle.independent_lsim(cfg, plant_cfg, "frequency_hz", 200);
  controller_exact(index) = struct( ...
    "name", catalog(index).name, ...
    "family", catalog(index).family, ...
    "controller", catalog(index).controller_cfg.to_struct(), ...
    "design", catalog(index).design, ...
    "config", cfg.to_struct(), ...
    "prediction", prediction, ...
    "raw_contract", raw_contract(prediction, common_gate));
  controller_independent(index) = struct( ...
    "name", catalog(index).name, "response", serializable_lsim(independent));
  signals = experiment.exp02.signals_from_logger_bin( ...
    struct("raw", prediction.raw), "expected_sample_count", prediction.sample_count);
  metrics_row = experiment.exp02.controller_benchmark_metrics(catalog(index), signals);
  metrics = table_row_struct(metrics_row);
  controller_metrics(index) = struct( ...
    "name", catalog(index).name, "metrics", metrics, ...
    "ranges", metric_ranges(metrics, prediction.encoder_quantum_load_rad, ...
      prediction.sample_count));
end
index = find_entry("tools.run_controller_benchmark");
layers(index).exact = struct("ready", true, "controllers", controller_exact, ...
  "plant", plant_cfg.to_struct(), "restart_each_controller", true);
layers(index).independent = struct("ready", true, ...
  "controllers", controller_independent, ...
  "nrmse_max", common_gate.lsim_nrmse_max, ...
  "lag_samples", common_gate.lsim_lag_samples);
layers(index).outcome.gate.experiment.predicted_metrics = controller_metrics;
layers(index).outcome.gate.experiment.rank_pairs = ...
  separated_rank_pairs(controller_metrics, ...
    layers(index).outcome.gate.experiment.rank_uncertainty_multiplier);
layers(index).outcome.predicted = controller_outcome( ...
  controller_exact, controller_metrics, layers(index).outcome.gate.experiment);
benchmark_expected = testoracle.artifact_projection( ...
  "tools.run_controller_benchmark", ...
  controller_artifact_source(catalog, controller_metrics));
layers(index).artifact = artifact_description(benchmark_expected, ...
  "controller_benchmark_summary.mat", ...
  "tools.run_controller_benchmark", benchmark_artifact_tolerance(controller_metrics));
assert_preexecution_layers(layers);

  function set_logger_entry(name, cfg, prediction, purpose_expected, ...
      artifact_expected, artifact_paths, artifact_tolerances)
    item = find_entry(name);
    independent = testoracle.independent_lsim(cfg, plant_cfg, "frequency_hz", [1; 200; 500]);
    serialized = serializable_lsim(independent);
    if string(name) == "experiment.exp01"
      serialized.exp01_workflow_frf = ...
        testoracle.exp01_independent_workflow_frf( ...
          independent, exp01_scenario, ...
          "frequency_band_hz", [ ...
            layers(item).outcome.gate.experiment.frequency_band_min_hz, ...
            layers(item).outcome.gate.experiment.frequency_band_max_hz]);
    end
    exact_layer = struct( ...
      "ready", true, "prediction", prediction, ...
      "config", cfg.to_struct(), ...
      "plant", plant_cfg.to_struct(), ...
      "command_tables", command_tables(cfg), ...
      "raw_contract", raw_contract(prediction, common_gate));
    if string(name) == "experiment.exp01"
      exact_layer.analysis = exp01_analysis_contract( ...
        exp01_scenario, layers(item).outcome.gate.experiment);
    elseif string(name) == "experiment.exp03"
      exact_layer.feedforward = feedforward_contract(exp03_scenario);
    end
    layers(item).exact = exact_layer;
    layers(item).independent = struct( ...
      "ready", true, "response", serialized, ...
      "nrmse_max", common_gate.lsim_nrmse_max, ...
      "lag_samples", common_gate.lsim_lag_samples);
    layers(item).outcome.predicted = purpose_expected;
    if isfield(purpose_expected, "predicted_ranges") && ...
        isfield(layers(item).outcome.gate, "experiment")
      layers(item).outcome.gate.experiment.predicted_ranges = ...
        purpose_expected.predicted_ranges;
    end
    required_fields = strings(0, 1);
    if isfield(layers(item).outcome.gate, "artifact_required_fields")
      required_fields = layers(item).outcome.gate.artifact_required_fields;
    end
    layers(item).artifact = artifact_description( ...
      artifact_expected, artifact_paths, name, artifact_tolerances, ...
      required_fields);
  end

  function set_ilc_entry(scenario, prediction)
    item = find_entry("experiment.exp04");
    independent = cell(1, scenario.trial_count);
    for trial = 1:scenario.trial_count
      cfg = scenario.cfg;
      cfg.ff_profile = prediction.feedforward(:, trial);
      independent{trial} = serializable_lsim( ...
        testoracle.independent_lsim( ...
          cfg, plant_cfg, "frequency_hz", [1; 200; 500]));
    end
    purpose = struct( ...
      "completed_trials", scenario.trial_count, ...
      "best_trial", prediction.best_trial, ...
      "error_norm", prediction.error_norm, ...
      "convergence_factor", prediction.convergence_factor, ...
      "max_feedforward_A", prediction.max_feedforward_A, ...
      "max_total_input_A", prediction.max_total_input_A, ...
      "max_final_velocity_count", max(abs([[prediction.endpoints.motor_velocity_count], ...
        [prediction.endpoints.load_velocity_count]])), ...
      "max_final_position_delta_count", ...
        max([prediction.endpoints.motor_load_position_delta_count]), ...
      "restart_before_campaign", 1, "restart_between_trials", 0);
    layers(item).exact = struct("ready", true, "campaign", prediction, ...
      "config", scenario.cfg.to_struct(), "plant", plant_cfg.to_struct(), ...
      "raw_contract", raw_contract(prediction.predictions{1}, common_gate));
    layers(item).independent = struct("ready", true, ...
      "trials", {independent}, ...
      "nrmse_max", common_gate.lsim_nrmse_max, ...
      "lag_samples", common_gate.lsim_lag_samples);
    layers(item).outcome.predicted = purpose;
    expected_artifact = testoracle.artifact_projection( ...
      "experiment.exp04", ilc_artifact_source(scenario, prediction));
    layers(item).artifact = artifact_description(expected_artifact, ...
      "exp04_runs/<timestamp>/ilc_result.mat", "experiment.exp04", ...
      ilc_artifact_tolerance(prediction), ...
      layers(item).outcome.gate.artifact_required_fields);
  end

  function index = find_entry(name)
    index = find(string({layers.name}) == string(name), 1);
    if isempty(index), error("testoracle:manifest:unknownEntry", "%s", name); end
  end
end

function assert_preexecution_layers(layers)
for index = 1:numel(layers)
  name = string(layers(index).name);
  exact = layers(index).exact;
  independent = layers(index).independent;
  if isfield(exact, "prediction") && isfield(independent, "response")
    assert_lsim(name, exact.prediction.raw, independent.response, ...
      independent.nrmse_max, independent.lag_samples);
  elseif name == "experiment.exp04"
    for trial = 1:numel(exact.campaign.predictions)
      assert_lsim(name + " trial " + trial, ...
        exact.campaign.predictions{trial}.raw, independent.trials{trial}, ...
        independent.nrmse_max, independent.lag_samples);
    end
  elseif name == "tools.run_controller_benchmark"
    for controller = 1:numel(exact.controllers)
      assert_lsim(name + " " + exact.controllers(controller).name, ...
        exact.controllers(controller).prediction.raw, ...
        independent.controllers(controller).response, ...
        independent.nrmse_max, independent.lag_samples);
    end
  end
  if isfield(layers(index).outcome, "predicted")
    actual = layers(index).outcome.predicted;
  else
    actual = struct("pass", true);
  end
  report = testoracle.evaluate_outcome( ...
    name, actual, layers(index).outcome.gate);
  if ~report.pass
    error("testoracle:manifest:predictedOutcomeFailed", ...
      "%s predicted outcome failed before freeze: %s.", ...
      name, strjoin(report.failures, "; "));
  end
  artifact = layers(index).artifact;
  if ~isfield(artifact, "contract")
    error("testoracle:manifest:artifactContractMissing", ...
      "%s has no frozen artifact contract.", name);
  end
  artifact_report = testoracle.verify_artifact( ...
    artifact.contract.expected_value, artifact.contract, ...
    "units", artifact.contract.units);
  if ~artifact_report.pass
    error("testoracle:manifest:artifactContractInconsistent", ...
      "%s artifact contract does not verify its own frozen value.", name);
  end
end
end

function assert_lsim(label, raw, independent, nrmse_max, lag_samples)
report = testoracle.compare_lsim(raw, independent, ...
  "nrmse_limit", nrmse_max, "required_lag_samples", lag_samples);
frequency_response = independent.frequency_response;
finite_frequency_response = all(isfinite(real(frequency_response)), "all") && ...
  all(isfinite(imag(frequency_response)), "all");
if ~report.pass || ~finite_frequency_response
  error("testoracle:manifest:independentPredictionFailed", ...
    "%s independent lsim/freqresp pre-gate failed " + ...
    "(NRMSE=%g, comparisonLag=%g, diagnosticBestLag=%g, finiteFRF=%d).", ...
    label, report.nrmse, report.comparison_lag_samples, ...
    report.diagnostic_best_lag_samples, finite_frequency_response);
end
end

function layers = generic_layers(registry, outcomes)
layers = repmat(struct("name", "", "exact", struct(), ...
  "independent", struct(), "outcome", struct(), "artifact", struct()), ...
  numel(registry), 1);
for index = 1:numel(registry)
  layers(index) = struct( ...
    "name", registry(index).name, ...
    "exact", struct("ready", true, "logger_applicable", false), ...
    "independent", struct("ready", true, ...
      "method", "independent ADS/readback contract"), ...
    "outcome", struct("ready", true, "gate", outcomes(index).gate), ...
    "artifact", artifact_description("no new artifact", "none", ...
      "none", struct()));
end
end

function value = serializable_lsim(value)
value = rmfield(value, "system");
end

function value = raw_contract(prediction, common)
value = struct( ...
  "signals", ["motor_position", "motor_velocity", "motor_current_act", ...
    "load_position", "load_velocity", "current_cmd", "error", ...
    "ref_value", "ff_value", "dist_value", "control_input"], ...
  "signal_count", double(common.raw_signal_count), ...
  "seq_exact", true, "timestamp_exact", true, "table_exact", true, ...
  "position_velocity_encoder_quanta", ...
    double(common.position_velocity_encoder_quanta), ...
  "current_feedback_driver_quanta", ...
    double(common.current_feedback_driver_quanta), ...
  "control_current_tolerance_A", ...
    double(common.control_current_tolerance_A), ...
  "motor_encoder_quantum_rad", prediction.encoder_quantum_motor_rad, ...
  "load_encoder_quantum_rad", prediction.encoder_quantum_load_rad, ...
  "current_quantum_A", prediction.driver_current_quantum_A);
end

function value = command_tables(cfg)
value = struct("ref_profile", cfg.ref_profile, ...
  "ff_profile", cfg.ff_profile, "dist_profile", cfg.dist_profile);
end

function value = artifact_description( ...
    expected, paths, projection, tolerance, required_fields)
if nargin < 5 || isempty(required_fields)
  required_fields = strings(0, 1);
end
if isempty(required_fields) && isstruct(expected) && isscalar(expected)
  required_fields = string(fieldnames(expected));
end
units = testoracle.artifact_unit_map(projection, expected);
contract = testoracle.artifact_contract(expected, ...
  "required_fields", required_fields, ...
  "absolute_tolerance", tolerance, "units", units);
value = struct( ...
  "ready", true, "paths", string(paths), ...
  "projection", string(projection), "contract", contract, ...
  "schema", contract.schema, ...
  "canonical_value_digest", contract.canonical_value_digest, ...
  "units", units);
end

function assert_safe(prediction, label, common)
if prediction.fault.motor || prediction.fault.load || prediction.position_saturated
  error("testoracle:manifest:unsafePrediction", ...
    "%s prediction is not fault/saturation free.", label);
end
maximum_input = max(abs(prediction.raw.current_cmd));
if maximum_input > common.predicted_max_input_A
  error("testoracle:manifest:inputGateFailed", ...
    "%s predicts %.6g A, above the frozen %.6g A common gate.", ...
    label, maximum_input, common.predicted_max_input_A);
end
end

