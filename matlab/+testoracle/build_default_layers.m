function pairs = separated_rank_pairs(metrics, multiplier)
template = struct( ...
  "metric", "", "better", "", "worse", "", ...
  "predicted_difference", 0, "combined_uncertainty", 0);
metric_names = ["trackingErrorL2", "trackingErrorRms", ...
  "trackingErrorPeak", "IAE", "overshootRad", "settlingTimeS", ...
  "maxControlInputA", "maxCurrentCmdA", "controllerGain200Hz"];
capacity = numel(metric_names)*numel(metrics)*(numel(metrics)-1)/2;
pairs = repmat(template, capacity, 1);
pair_count = 0;
for metric = metric_names
  for left = 1:numel(metrics)-1
    for right = left+1:numel(metrics)
      lhs = metrics(left).metrics.(char(metric));
      rhs = metrics(right).metrics.(char(metric));
      if ~(isnumeric(lhs) && isscalar(lhs) && isfinite(lhs) && ...
          isnumeric(rhs) && isscalar(rhs) && isfinite(rhs) && ...
          isfield(metrics(left).ranges, metric) && ...
          isfield(metrics(right).ranges, metric))
        continue;
      end
      lhs_bounds = metrics(left).ranges.(char(metric));
      rhs_bounds = metrics(right).ranges.(char(metric));
      uncertainty = abs(diff(lhs_bounds))/2 + abs(diff(rhs_bounds))/2;
      difference = abs(double(lhs)-double(rhs));
      if difference <= double(multiplier)*uncertainty
        continue;
      end
      if lhs < rhs
        better = metrics(left).name; worse = metrics(right).name;
      else
        better = metrics(right).name; worse = metrics(left).name;
      end
      pair_count = pair_count + 1;
      pairs(pair_count) = struct( ...
        "metric", metric, "better", better, "worse", worse, ...
        "predicted_difference", difference, ...
        "combined_uncertainty", uncertainty);
    end
  end
end
pairs = pairs(1:pair_count);
end

