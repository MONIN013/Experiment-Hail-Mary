function report = validate_virtual_motor_verification(actual, expected)
%VALIDATE_VIRTUAL_MOTOR_VERIFICATION Compare probe proof to frozen defaults.
valid = isstruct(actual) && isscalar(actual) && ...
  all(isfield(actual, ["passed", "probe_count", "module_port"])) && ...
  islogical(actual.passed) && isscalar(actual.passed) && actual.passed;
probe_match = valid && isnumeric(actual.probe_count) && ...
  isscalar(actual.probe_count) && isfinite(double(actual.probe_count)) && ...
  double(actual.probe_count) == double(expected.probe_count);
port_match = valid && isnumeric(actual.module_port) && ...
  isscalar(actual.module_port) && isfinite(double(actual.module_port)) && ...
  double(actual.module_port) == double(expected.module_port);
report = struct("pass", logical(valid && probe_match && port_match), ...
  "valid", logical(valid), "probe_count_match", logical(probe_match), ...
  "module_port_match", logical(port_match), ...
  "expected", expected, "actual", actual);
end
