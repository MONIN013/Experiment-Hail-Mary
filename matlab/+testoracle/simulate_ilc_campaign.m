function plan = simulate_ilc_campaign(scenario, plant_cfg)
% simulate_ilc_campaign  Run the exact VM ILC recurrence without outcome gates.
%
% This diagnostic primitive intentionally keeps the same quantized runtime
% model and learning update as the frozen oracle. Experiment-purpose gates
% are owned by the pre-freeze evaluate_outcome pass.
if ~isstruct(scenario) || ~isfield(scenario, "name") || scenario.name ~= "exp04"
  error("testoracle:ilc:invalidScenario", "An exp04 scenario is required.");
end
plant_cfg = virtualMotor.PlantConfig.from_struct(plant_cfg);
n = numel(scenario.trajectory.p);
if ~isfield(scenario, "learning_sample_count")
  error("testoracle:ilc:missingLearningSampleCount", ...
    "exp04 scenario must declare the active learning_sample_count.");
end
learning_n = double(scenario.learning_sample_count);
if ~(isscalar(learning_n) && isfinite(learning_n) && ...
    learning_n >= 1 && fix(learning_n) == learning_n && learning_n <= n)
  error("testoracle:ilc:invalidLearningSampleCount", ...
    "learning_sample_count must be an integer within the campaign trajectory.");
end

trials = double(scenario.trial_count);
feedforward = zeros(n, trials);
error_signal = zeros(n, trials);
position = zeros(n, trials);
control = zeros(n, trials);
current = zeros(n, trials);
error_norm = zeros(1, trials);
predictions = cell(1, trials);
initial_states = cell(1, trials);
plant_state = struct();
endpoints = repmat(struct( ...
  "motor_velocity_count", 0, "load_velocity_count", 0, ...
  "motor_load_position_delta_count", 0), trials, 1);

for trial = 1:trials
  cfg = scenario.cfg;
  cfg.ff_profile = feedforward(:, trial);
  cfg = cfg.normalize();
  initial_states{trial} = plant_state;
  prediction = virtualMotor.predict_logger( ...
    cfg, plant_cfg, "initial_state", plant_state);
  plant_state = prediction.final_state;
  if prediction.fault.motor || prediction.fault.load || prediction.position_saturated
    error("testoracle:ilc:unsafePrediction", ...
      "Predicted ILC trial %d faults or saturates.", trial);
  end
  predictions{trial} = prediction;
  error_signal(:, trial) = prediction.raw.error;
  position(:, trial) = prediction.raw.load_position;
  control(:, trial) = prediction.raw.control_input;
  current(:, trial) = prediction.raw.current_cmd;
  error_norm(trial) = norm(prediction.raw.error);
  motor_velocity_count = round(prediction.raw.motor_velocity(end) / ...
    prediction.encoder_quantum_motor_rad);
  load_velocity_count = round(prediction.raw.load_velocity(end) / ...
    prediction.encoder_quantum_load_rad);
  motor_count = round(prediction.raw.motor_position(end) / ...
    prediction.encoder_quantum_motor_rad);
  load_count = round(prediction.raw.load_position(end) / ...
    prediction.encoder_quantum_load_rad);
  endpoints(trial) = struct( ...
    "motor_velocity_count", motor_velocity_count, ...
    "load_velocity_count", load_velocity_count, ...
    "motor_load_position_delta_count", abs(motor_count-load_count));
  if trial < trials
    [next, status] = experiment.exp04.learning_update( ...
      feedforward(1:learning_n, trial), error_signal(1:learning_n, trial), ...
      scenario.learning_filters, "alpha", scenario.alpha, ...
      "Npad", scenario.Npad, ...
      "transient_samples", scenario.transient_samples, ...
      "max_input", scenario.max_input_A);
    if ~status.ok
      error("testoracle:ilc:inputLimit", ...
        "Predicted trial %d feedforward exceeds %.6g A.", trial+1, status.limit);
    end
    feedforward(:, trial+1) = [next; zeros(n-learning_n, 1)];
  end
end

[best_norm, best_trial] = min(error_norm);
plan = struct( ...
  "predictions", {predictions}, ...
  "initial_states", {initial_states}, ...
  "inter_trial_state_carried", true, ...
  "feedforward", feedforward, "error", error_signal, ...
  "position", position, "control_input", control, ...
  "current_cmd", current, "error_norm", error_norm, ...
  "best_error_norm", best_norm, "best_trial", best_trial, ...
  "max_feedforward_A", max(abs(feedforward), [], "all"), ...
  "max_total_input_A", max(abs(current), [], "all"), ...
  "convergence_factor", scenario.learning_filters.max_convergence_gain, ...
  "learning_error_quantum_rad", scenario.learning_error_quantum_rad, ...
  "endpoints", endpoints);
end
