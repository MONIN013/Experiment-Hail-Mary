function state = restore_and_read_final_state()
% restore_and_read_final_state  Force safe IDLE then return final ADS proof.
cfg = experiment.ExperimentConfig.defaults();
conn = experiment.ConnectionManager.create(cfg);
cleanup = onCleanup(@() conn.session.close());
symbols = experiment.RuntimeSymbols.from_defaults();
controller_symbols = experiment.RuntimeSymbols.from_controller_prefix( ...
  cfg.env.controller_prefix);
t = symbols.types;
control = experiment.ModeManagerControl.resolve_symbols( ...
  conn.ctrl, symbols, "testoracle:restore:missingSymbol");

experiment.ModeManagerControl.write_mode_flags(conn.ctrl, control, uint32(0));
conn.seq.write_scalar(symbols.tableLen, uint32(0), t.u32);
heartbeat = experiment.ModeManagerControl.heartbeat_disabled();
[acked, reset_diag, heartbeat] = ...
  experiment.ModeManagerControl.request_reset_and_wait_ack( ...
    conn.ctrl, control, cfg.reset_timeout_s, heartbeat);
if ~acked
  error("testoracle:restore:resetTimeout", ...
    "Final reset was not acknowledged (before=%g after=%g).", ...
    reset_diag.counter_before, reset_diag.counter_after);
end
conn.ctrl.write_scalar(control.resetReqSymbol, false, t.bool);
[idle, idle_diag] = experiment.ModeManagerControl.wait_for_reset_idle( ...
  conn.seq, conn.ctrl, symbols, control, cfg.reset_timeout_s, heartbeat);
if ~idle
  error("testoracle:restore:idleTimeout", ...
    "Final reset did not reach IDLE (idx=%g mode=%g active=%d).", ...
    idle_diag.idx, idle_diag.mode_state, idle_diag.experiment_active);
end

p = controller_symbols.controllerParams;
vm_prefix = "VirtualMotorCore_Obj1 (Module1).Outputs.";
state = struct( ...
  "modeFlags", conn.ctrl.read_scalar(symbols.modeFlags, t.u16), ...
  "modeState", conn.ctrl.read_scalar(symbols.modeState, t.i16), ...
  "experimentActive", conn.ctrl.read_scalar(symbols.experimentActive, t.bool), ...
  "resetReq", conn.ctrl.read_scalar(symbols.modeResetReq, t.bool), ...
  "idx", conn.seq.read_scalar(symbols.idx, t.u32), ...
  "tableLen", conn.seq.read_scalar(symbols.tableLen, t.u32), ...
  "loggerErrorCode", conn.ctrl.read_scalar(symbols.loggerErrorCode, t.u32), ...
  "apply_revision", conn.module.read_scalar(p.applyRevision, t.u32), ...
  "applied_revision", conn.module.read_scalar(p.appliedRevision, t.u32), ...
  "processed_revision", conn.module.read_scalar(p.processedRevision, t.u32), ...
  "parameter_error_code", conn.module.read_scalar(p.parameterErrorCode, t.u32), ...
  "motor_status", conn.module.read_scalar(vm_prefix + "motor.statusWord", t.u16), ...
  "load_status", conn.module.read_scalar(vm_prefix + "load.statusWord", t.u16));
report = testoracle.verify_final_state(state);
if ~report.pass
  error("testoracle:restore:dirtyState", ...
    "Final reset completed but the required clean-state readback failed.");
end
end
