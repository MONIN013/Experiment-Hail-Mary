function projected = artifact_projection(entry_name, source)
% artifact_projection  Remove nondeterministic MAT metadata and LTI objects.
%
% The input is the value loaded from the saved artifact. exp01 uses a
% container with fields chirp and plant because it writes two MAT files.
% Logger-only tools use a container with field raw (or logger_bin.raw).
% The returned value is safe to freeze in a canonical manifest and retains
% every deterministic numeric result needed by the artifact gate.

entry_name = string(entry_name);
if ~(isscalar(entry_name) && isstruct(source) && isscalar(source))
  error("testoracle:artifact:invalidProjectionInput", ...
    "entry_name and a scalar source struct are required.");
end

switch entry_name
  case "experiment.exp01"
    chirp = require_container(source, "chirp");
    plant = require_container(source, "plant");
    projected = struct( ...
      "chirp", select_fields(chirp, ...
        ["input", "loadpos", "motorpos", "Ts", "Tend", "Tcycle"]), ...
      "plant", struct( ...
        "Pd", system_projection(require_field(plant, "Pd")), ...
        "Pd_motor", system_projection(require_field(plant, "Pd_motor")), ...
        "Pd_load", system_projection(require_field(plant, "Pd_load")), ...
        "Pd_vel_load", system_projection(require_field(plant, "Pd_vel_load")), ...
        "Pd_vel_motor", system_projection(require_field(plant, "Pd_vel_motor")), ...
        "Pdn", system_projection(require_field(plant, "Pdn")), ...
        "Jn", require_field(plant, "Jn"), ...
        "Dn", require_field(plant, "Dn"), ...
        "Ndelay", require_field(plant, "Ndelay"), ...
        "Ts", require_field(plant, "Ts")));
  case "experiment.exp02"
    projected = struct( ...
      "t", require_field(source, "t"), ...
      "r", require_field(source, "r"), ...
      "y", require_field(source, "y"), ...
      "e", require_field(source, "e"), ...
      "u", require_field(source, "u"), ...
      "Kd", system_projection(require_field(source, "Kd")), ...
      "feedback_metrics", numeric_struct( ...
        require_field(source, "feedback_metrics"), "feedback_metrics"), ...
      "stability", stability_projection(require_field(source, "stability")));
  case "experiment.exp03"
    projected = struct( ...
      "t", require_field(source, "t"), ...
      "r", require_field(source, "r"), ...
      "y", require_field(source, "y"), ...
      "e", require_field(source, "e"), ...
      "u", require_field(source, "u"), ...
      "f", require_field(source, "f"), ...
      "Kd", system_projection(require_field(source, "Kd")), ...
      "feedforward_metrics", numeric_struct( ...
        require_field(source, "feedforward_metrics"), "feedforward_metrics"), ...
      "stability", stability_projection(require_field(source, "stability")), ...
      "feedforward_gains", numeric_struct( ...
        require_field(source, "feedforward_gains"), "feedforward_gains"));
  case "experiment.exp04"
    projected = struct( ...
      "t", require_field(source, "t"), ...
      "history", history_projection(require_field(source, "history")), ...
      "Kd", system_projection(require_field(source, "Kd")), ...
      "stability", stability_projection(require_field(source, "stability")), ...
      "learning_filters", learning_projection( ...
        require_field(source, "learning_filters")));
  case "tools.run_controller_benchmark"
    benchmark = source;
    if isfield(source, "benchmark")
      benchmark = source.benchmark;
    end
    if ~(isstruct(benchmark) && isscalar(benchmark))
      error("testoracle:artifact:invalidBenchmark", ...
        "benchmark must be a scalar struct.");
    end
    projected = struct( ...
      "design", row_structs(require_field(benchmark, "design_table")), ...
      "results", row_structs(require_field(benchmark, "results_table")));
  case {"tools.run_position_command_demo", "tools.run_si_demo", ...
      "tools.run_virtual_motor_prediction_e2e"}
    if isfield(source, "logger_bin")
      source = source.logger_bin;
    end
    projected = struct("raw", logger_raw(source));
  otherwise
    error("testoracle:artifact:unsupportedProjection", ...
      "No saved-artifact projection is defined for %s.", entry_name);
end
end

function value = require_container(source, name)
value = require_field(source, name);
if ~(isstruct(value) && isscalar(value))
  error("testoracle:artifact:invalidContainer", ...
    "%s must be a scalar struct loaded from its MAT file.", name);
end
end

function value = require_field(source, name)
if ~(isstruct(source) && isscalar(source) && isfield(source, name))
  error("testoracle:artifact:missingSourceField", ...
    "Saved artifact is missing field %s.", name);
end
value = source.(name);
end

function out = select_fields(source, names)
out = struct();
for name = names(:)'
  out.(char(name)) = require_field(source, name);
end
end

function out = system_projection(system)
if ~(isa(system, "lti") && isscalar(system) && ...
    size(system, 1) == 1 && size(system, 2) == 1)
  error("testoracle:artifact:invalidSystem", ...
    "Saved dynamic systems must be scalar SISO LTI values.");
end
if isa(system, "frd")
  response = squeeze(system.ResponseData);
  out = struct( ...
    "kind", "frd", "Ts", double(system.Ts), ...
    "frequency", double(system.Frequency(:)), ...
    "frequency_unit", string(system.FrequencyUnit), ...
    "magnitude_db", 20*log10(abs(double(response(:)))), ...
    "phase_deg", wrap_phase(rad2deg(angle(double(response(:))))));
  return;
end
system = tf(system);
[numerator, denominator] = tfdata(system, "v");
out = struct( ...
  "kind", "tf", "Ts", double(system.Ts), ...
  "numerator", double(numerator(:).'), ...
  "denominator", double(denominator(:).'), ...
  "input_delay", delay_value(system, "InputDelay"), ...
  "output_delay", delay_value(system, "OutputDelay"), ...
  "io_delay", delay_value(system, "IODelay"));
end

function value = delay_value(system, property_name)
if isprop(system, property_name)
  value = double(system.(property_name));
else
  value = 0;
end
end

function value = wrap_phase(value)
value = mod(value + 180, 360) - 180;
value(value == -180) = 180;
end

function out = stability_projection(value)
out = numeric_struct(select_fields(value, ...
  ["ok", "limit_exceeded", "max_sensitivity", "Smax"]), "stability");
end

function out = learning_projection(value)
out = numeric_struct(select_fields(value, ...
  ["Qnum", "Qden", "convergence_frequency_hz", ...
  "max_convergence_gain", "error_quantum_rad"]), "learning_filters");
end

function out = history_projection(value)
required = ["t", "r", "y", "e", "eNorm", "f", "ffApplied", "u", ...
  "maxAbsInput", "maxAbsFeedforward", "maxAbsTotalInput", ...
  "maxAbsError", "errorIncreased", "convergencePeak", ...
  "trialLoggerPaths", "trialLoggerRecordCount", ...
  "maxSensitivity", "sensitivityLimitExceeded", "completedTrials", ...
  "stopReason", "bestErrorNorm", "bestTrial", "trialSummary"];
out = select_fields(value, required);
paths = string(out.trialLoggerPaths(:));
files = strings(size(paths));
for index = 1:numel(paths)
  [~, name, extension] = fileparts(paths(index));
  files(index) = name + extension;
end
out = rmfield(out, "trialLoggerPaths");
out.trialLoggerFiles = reshape(files, 1, []);
out.trialSummary = row_structs(out.trialSummary);
out = canonical_struct(out, "history");
end

function out = numeric_struct(value, label)
if ~(isstruct(value) && isscalar(value))
  error("testoracle:artifact:invalidNumericStruct", ...
    "%s must be a scalar struct.", label);
end
out = canonical_struct(value, label);
names = string(fieldnames(out));
for name = names(:)'
  item = out.(char(name));
  if ~(isnumeric(item) || islogical(item) || isstring(item) || ...
      ischar(item) || istable(item))
    error("testoracle:artifact:invalidNumericStruct", ...
      "%s.%s has unsupported class %s.", label, name, class(item));
  end
end
end

function out = canonical_struct(value, label)
if ~(isstruct(value) && isscalar(value))
  error("testoracle:artifact:invalidStruct", ...
    "%s must be a scalar struct.", label);
end
out = value;
end

function out = row_structs(value)
if istable(value)
  names = string(value.Properties.VariableNames);
  prototype = struct();
  for name = names(:)'
    prototype.(char(name)) = [];
  end
  out = repmat(prototype, height(value), 1);
  for row = 1:height(value)
    item = struct();
    for name = names(:)'
      column = value.(char(name));
      field_value = column(row, :);
      if iscell(field_value), field_value = field_value{1}; end
      item.(char(name)) = field_value;
    end
    out(row) = item;
  end
elseif isstruct(value)
  out = value(:);
else
  error("testoracle:artifact:invalidRows", ...
    "Benchmark rows must be a table or struct array.");
end
end

function raw = logger_raw(source)
if isfield(source, "raw")
  raw = source.raw;
else
  raw = source;
end
required = ["seq", "t_ns", "t_s", "motor_position", ...
  "motor_velocity", "motor_current_act", "load_position", ...
  "load_velocity", "current_cmd", "error", "ref_value", ...
  "ff_value", "dist_value", "control_input"];
raw = select_fields(raw, required);
end
