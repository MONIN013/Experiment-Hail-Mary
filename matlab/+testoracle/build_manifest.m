function manifest = build_manifest(entry_layers, varargin)
% build_manifest  Build a complete pre-execution four-layer manifest.
p = inputParser;
p.addParameter("campaign_id", "", @(x) ischar(x) || (isstring(x) && isscalar(x)));
p.addParameter("created_at_utc", "", @(x) ischar(x) || (isstring(x) && isscalar(x)));
p.parse(varargin{:});

registry = testoracle.entry_registry();
if ~isstruct(entry_layers) || ~isvector(entry_layers)
  error("testoracle:manifest:invalidEntries", ...
    "entry_layers must be a struct vector.");
end
required = ["name", "exact", "independent", "outcome", "artifact"];
if isempty(entry_layers) || any(~isfield(entry_layers, required))
  error("testoracle:manifest:invalidEntries", ...
    "Every entry requires name/exact/independent/outcome/artifact layers.");
end
provided_names = string({entry_layers.name});
required_names = string({registry.name});
if numel(unique(provided_names)) ~= numel(provided_names) || ...
    ~isequal(sort(provided_names), sort(required_names))
  missing = setdiff(required_names, provided_names);
  extra = setdiff(provided_names, required_names);
  error("testoracle:manifest:entrySetMismatch", ...
    "Manifest entry set mismatch (missing=%s, extra=%s).", ...
    strjoin(missing, ","), strjoin(extra, ","));
end

entries = repmat(struct( ...
  "name", "", "exact", struct(), "independent", struct(), ...
  "outcome", struct(), "artifact", struct(), ...
  "layer_digests", struct()), numel(registry), 1);
for index = 1:numel(registry)
  source = entry_layers(provided_names == registry(index).name);
  validate_layer(source.exact, registry(index).name, "exact");
  validate_layer(source.independent, registry(index).name, "independent");
  validate_layer(source.outcome, registry(index).name, "outcome");
  validate_layer(source.artifact, registry(index).name, "artifact");
  digests = struct( ...
    "exact", testoracle.canonical_digest(source.exact), ...
    "independent", testoracle.canonical_digest(source.independent), ...
    "outcome", testoracle.canonical_digest(source.outcome), ...
    "artifact", testoracle.canonical_digest(source.artifact));
  entries(index) = struct( ...
    "name", registry(index).name, ...
    "exact", source.exact, ...
    "independent", source.independent, ...
    "outcome", source.outcome, ...
    "artifact", source.artifact, ...
    "layer_digests", digests);
end

campaign_id = string(p.Results.campaign_id);
if strlength(campaign_id) == 0
  campaign_id = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyyMMdd'T'HHmmss_SSS'Z'"));
end
created_at = string(p.Results.created_at_utc);
if strlength(created_at) == 0
  created_at = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyy-MM-dd'T'HH:mm:ss.SSSXXX"));
end
payload = struct( ...
  "format", "ExperimentHailMary.testoracle.manifest", ...
  "version", uint32(1), ...
  "campaign_id", campaign_id, ...
  "created_at_utc", created_at, ...
  "frozen_before_execution", true, ...
  "registry", registry, ...
  "entries", entries);
manifest = payload;
manifest.canonical_digest = testoracle.canonical_digest(payload);
end

function validate_layer(value, entry_name, layer_name)
if ~isstruct(value) || ~isscalar(value) || isempty(fieldnames(value))
  error("testoracle:manifest:emptyLayer", ...
    "%s.%s must be a nonempty scalar struct.", entry_name, layer_name);
end
if isfield(value, "ready") && ~logical(value.ready)
  error("testoracle:manifest:layerNotReady", ...
    "%s.%s was not generated before freeze.", entry_name, layer_name);
end
end
