function reports = build_layer_reports(entry, expected, capture, context)
% build_layer_reports  Convert captured child evidence into four gate reports.
name = string(entry.name);
if string(capture.name) ~= name
  error("testoracle:reports:captureMismatch", ...
    "Captured entry does not match %s.", name);
end
tool_pass = captured_tool_pass(name, capture, expected.outcome.gate.common);

if isfield(expected.exact, "prediction")
  exact = logger_exact_report( ...
    capture.logger, expected.exact.prediction, ...
    capture.command_tables, expected.exact.command_tables, ...
    expected.exact.raw_contract);
  independent = testoracle.compare_lsim( ...
    capture.logger, expected.independent.response, ...
    "nrmse_limit", expected.independent.nrmse_max, ...
    "required_lag_samples", expected.independent.lag_samples);
  independent = attach_frequency_report( ...
    independent, name, capture, expected, 1);
  exact = attach_runtime_readback( ...
    exact, expected.exact, capture, context, expected.outcome.gate.common);
  if name == "tools.run_virtual_motor_prediction_e2e"
    exact = attach_restart_proof(exact, capture);
  end
elseif name == "experiment.exp04"
  count = numel(expected.exact.campaign.predictions);
  exact_items = cell(1, count);
  independent_items = cell(1, count);
  for index = 1:count
    expected_tables = tables_for_config( ...
      expected.exact.config, expected.exact.campaign.feedforward(:, index));
    exact_items{index} = logger_exact_report( ...
      capture.logger{index}, expected.exact.campaign.predictions{index}, ...
      capture.command_tables{index}, expected_tables, ...
      expected.exact.raw_contract);
    independent_items{index} = testoracle.compare_lsim( ...
      capture.logger{index}, expected.independent.trials{index}, ...
      "nrmse_limit", expected.independent.nrmse_max, ...
      "required_lag_samples", expected.independent.lag_samples);
    independent_items{index} = attach_frequency_report( ...
      independent_items{index}, name, capture, expected, index);
  end
  exact = aggregate_reports(exact_items, "trials");
  independent = aggregate_reports(independent_items, "trials");
  exact = attach_runtime_readback( ...
    exact, expected.exact, capture, context, expected.outcome.gate.common);
elseif name == "tools.run_controller_benchmark"
  count = numel(expected.exact.controllers);
  exact_items = cell(1, count);
  independent_items = cell(1, count);
  controller_items = cell(1, count);
  parameter_items = cell(1, count);
  post_parameter_items = cell(1, count);
  for index = 1:count
    frozen = expected.exact.controllers(index);
    expected_tables = tables_for_config(frozen.config, []);
    exact_items{index} = logger_exact_report( ...
      capture.logger{index}, frozen.prediction, ...
      capture.command_tables{index}, expected_tables, ...
      frozen.raw_contract);
    independent_items{index} = testoracle.compare_lsim( ...
      capture.logger{index}, expected.independent.controllers(index).response, ...
      "nrmse_limit", expected.independent.nrmse_max, ...
      "required_lag_samples", expected.independent.lag_samples);
    independent_items{index} = attach_frequency_report( ...
      independent_items{index}, name, capture, expected, index);
    controller_items{index} = testoracle.compare_controller_readback( ...
      frozen.controller, capture.controller_readback(index), ...
      "eps_factor", expected.outcome.gate.common.parameter_double_eps_factor);
    parameter_items{index} = capture.parameter_reports(index);
    expected_parameter = expected_parameter_readback( ...
      frozen.config, expected.exact.plant);
    post_parameter_items{index} = testoracle.compare_parameter_readback( ...
      expected_parameter, capture.parameter_readbacks(index), ...
      "eps_factor", expected.outcome.gate.common.parameter_double_eps_factor);
  end
  raw_report = aggregate_reports(exact_items, "controllers");
  controller_report = aggregate_reports(controller_items, "controllers");
  parameter_report = aggregate_reports(parameter_items, "controllers");
  post_parameter_report = aggregate_reports( ...
    post_parameter_items, "controllers");
  vm_status = runtime_status_report(capture.vm_status);
  benchmark_provenance = capture.benchmark_provenance;
  provenance_pass = isstruct(benchmark_provenance) && ...
    isscalar(benchmark_provenance) && ...
    isfield(benchmark_provenance, "pass") && ...
    islogical(benchmark_provenance.pass) && ...
    isscalar(benchmark_provenance.pass) && benchmark_provenance.pass;
  exact = struct( ...
    "pass", logical(raw_report.pass && controller_report.pass && ...
      parameter_report.pass && post_parameter_report.pass && vm_status.pass && ...
      provenance_pass), ...
    "raw", raw_report, "controller_readback", controller_report, ...
    "parameter_readback", parameter_report, ...
    "post_parameter_readback", post_parameter_report, "vm_status", vm_status, ...
    "saved_benchmark_provenance", benchmark_provenance);
  independent = aggregate_reports(independent_items, "controllers");
elseif name == "tools.run_configure_virtual_motor"
  value = capture.tool_result;
  requested = testoracle.compare_parameter_readback( ...
    expected.exact.requested, value.requested, ...
    "eps_factor", expected.outcome.gate.common.parameter_double_eps_factor);
  readback = testoracle.compare_parameter_readback( ...
    expected.exact.requested, value.readback, ...
    "eps_factor", expected.outcome.gate.common.parameter_double_eps_factor);
  exact = struct("pass", logical(tool_pass && requested.pass && readback.pass), ...
    "captured_verified", logical(tool_pass), ...
    "requested_against_frozen", requested, ...
    "readback_against_frozen", readback);
  independent = struct("pass", logical(requested.pass && readback.pass), ...
    "method", "frozen requested parameter and independent ADS readback", ...
    "requested_against_frozen", requested, ...
    "readback_against_frozen", readback);
elseif name == "tools.run_ads_discovery_demo"
  contract = expected.exact.discovery;
  exact = testoracle.validate_discovery( ...
    capture.tool_result.ports, capture.tool_result.symbols, ...
    "required_ports", contract.required_ports, ...
    "required_symbols", contract.required_symbols);
  independent = exact;
  independent.method = "frozen exact ADS port set and required symbol probes";
elseif name == "tools.run_verify_virtual_motor"
  exact = testoracle.validate_virtual_motor_verification( ...
    capture.tool_result, expected.exact.verification);
  independent = exact;
  independent.method = "frozen VirtualMotor probe count and module port";
elseif name == "tools.run_ads_transport_e2e"
  exact = testoracle.validate_ads_transport_result( ...
    capture.tool_result, expected.exact.transport);
  independent = exact;
  independent.method = "frozen safe-IDLE ADS transport invariants";
else
  exact = struct("pass", logical(tool_pass), ...
    "captured_tool_result", capture.tool_result);
  independent = struct("pass", logical(tool_pass), ...
    "method", "captured ADS/tool contract");
end

actual = testoracle.actual_outcome(name, capture, expected, context);
outcome = testoracle.evaluate_outcome(name, actual, expected.outcome.gate);
artifact = artifact_report(name, capture, expected.artifact);
reports = struct("exact", exact, "independent", independent, ...
  "outcome", outcome, "artifact", artifact);
end

function report = attach_restart_proof(report, capture)
if ~isfield(capture, "restart_proof") || ...
    ~isstruct(capture.restart_proof) || ~isscalar(capture.restart_proof) || ...
    ~all(isfield(capture.restart_proof, ["pass", "restart_count"]))
  error("testoracle:reports:restartProofMissing", ...
    "Prediction E2E capture has no validated restart proof.");
end
proof = capture.restart_proof;
valid = islogical(proof.pass) && isscalar(proof.pass) && proof.pass && ...
  isnumeric(proof.restart_count) && isscalar(proof.restart_count) && ...
  double(proof.restart_count) == 1;
report.restart_proof = proof;
report.pass = logical(report.pass && valid);
end

function report = attach_frequency_report(report, name, capture, expected, index)
measured = struct("pass", true, "applicable", false);
[config_value, parameter_readback, controller_readback, frozen] = ...
  frequency_evidence(name, capture, expected, index);
advance = 0;
if string(name) == "experiment.exp01"
  gate = expected.outcome.gate.experiment;
  advance = sum(double(struct2array(frozen.sample_delay_contract))) - ...
    double(gate.delay_samples);
end
readback = testoracle.compare_readback_freqresp( ...
  config_value, parameter_readback, controller_readback, frozen, ...
  "feedforward_advance_samples", advance);
readback.applicable = true;
switch string(name)
  case "experiment.exp01"
    gate = expected.outcome.gate.experiment;
    target = frozen.exp01_workflow_frf;
    frequencies = target.frequency_hz(:);
    actual_velocity = squeeze(freqresp( ...
      capture.artifact_source.plant.Pd_vel_load, 2*pi*frequencies));
    actual_position = squeeze(freqresp( ...
      capture.artifact_source.plant.Pd_load, 2*pi*frequencies));
    velocity = testoracle.compare_freqresp( ...
      actual_velocity, target.velocity_response, ...
      "magnitude_tolerance_db", gate.magnitude_error_max_db, ...
      "phase_tolerance_deg", gate.phase_error_max_deg, ...
      "magnitude_p95_tolerance_db", gate.magnitude_error_p95_db, ...
      "phase_p95_tolerance_deg", gate.phase_error_p95_deg);
    position = testoracle.compare_freqresp( ...
      actual_position, target.position_response, ...
      "magnitude_tolerance_db", gate.magnitude_error_max_db, ...
      "phase_tolerance_deg", gate.phase_error_max_deg, ...
      "magnitude_p95_tolerance_db", gate.magnitude_error_p95_db, ...
      "phase_p95_tolerance_deg", gate.phase_error_p95_deg);
    measured = struct("pass", logical(velocity.pass && position.pass), ...
      "applicable", true, "sample_delay_from_ff_value", gate.delay_samples, ...
      "velocity", velocity, "position", position);
  case "tools.run_si_demo"
    gate = expected.outcome.gate.experiment;
    frequencies = frozen.frequency_hz(:);
    analysis = capture.tool_result.frf;
    actual = interp1(double(analysis.freq_hz(:)), ...
      double(analysis.frf(:)), frequencies, "linear", NaN);
    cfg = experiment.ExperimentConfig.from_struct(expected.exact.config);
    Ts = 1/double(cfg.env.task_rate_hz);
    delay_contract = frozen.sample_delay_contract;
    feedforward_advance = sum(double(struct2array(delay_contract))) - ...
      double(gate.delay_samples);
    target = squeeze(frozen.frequency_response(1, 2, :)) .* ...
      exp(1i*2*pi*frequencies*Ts*feedforward_advance) .* ...
      (1-exp(-1i*2*pi*frequencies*Ts))/Ts;
    measured = testoracle.compare_freqresp(actual, target, ...
      "magnitude_tolerance_db", gate.magnitude_error_max_db, ...
      "phase_tolerance_deg", gate.phase_error_max_deg, ...
      "magnitude_p95_tolerance_db", gate.magnitude_error_p95_db, ...
      "phase_p95_tolerance_deg", gate.phase_error_p95_deg);
    measured.applicable = true;
end
frequency = struct("pass", logical(readback.pass && measured.pass), ...
  "applicable", true, "readback_model", readback, "measured", measured);
report.frequency_response = frequency;
report.pass = logical(report.pass && frequency.pass);
end

function [config_value, parameter, controller, frozen] = ...
    frequency_evidence(name, capture, expected, index)
if string(name) == "tools.run_controller_benchmark"
  config_value = expected.exact.controllers(index).config;
  frozen = expected.independent.controllers(index).response;
  parameter = capture.parameter_readbacks(index);
  controller = capture.controller_readback(index);
elseif string(name) == "experiment.exp04"
  config_value = expected.exact.config;
  frozen = expected.independent.trials{index};
  parameter = capture.parameter_readbacks;
  controller = capture.controller_readback;
else
  config_value = expected.exact.config;
  frozen = expected.independent.response;
  parameter = capture.parameter_readbacks;
  controller = capture.controller_readback;
end
if isempty(parameter) || isempty(controller)
  error("testoracle:reports:readbackFrequencyEvidenceMissing", ...
    "%s has no applied VM/controller readback for freqresp.", name);
end
end

function report = logger_exact_report( ...
    actual, prediction, actual_tables, expected_tables, contract)
report = testoracle.compare_raw_logger(actual, prediction, ...
  "actual_tables", actual_tables, "expected_tables", expected_tables, ...
  "require_table_match", true, "contract", contract);
end

function report = attach_runtime_readback(report, exact, capture, context, common)
pre_parameter = struct("pass", true, "applicable", false);
if isfield(context, "preparation") && ...
    isfield(context.preparation, "configuration") && ...
    isfield(context.preparation.configuration, "parameter_report")
  pre_parameter = context.preparation.configuration.parameter_report;
  pre_parameter.applicable = true;
elseif isfield(capture.tool_result, "configuration")
  configuration = capture.tool_result.configuration;
  pre_parameter = testoracle.compare_parameter_readback( ...
    configuration.requested, configuration.readback, ...
    "eps_factor", common.parameter_double_eps_factor);
  pre_parameter.applicable = true;
end
post_parameter = struct("pass", true, "applicable", false);
if isfield(exact, "plant") && isfield(exact, "config") && ...
    ~isempty(capture.parameter_readbacks)
  expected_parameter = expected_parameter_readback(exact.config, exact.plant);
  post_parameter = testoracle.compare_parameter_readback( ...
    expected_parameter, capture.parameter_readbacks, ...
    "eps_factor", common.parameter_double_eps_factor);
  post_parameter.applicable = true;
end
parameter = struct("pass", logical(pre_parameter.pass && post_parameter.pass), ...
  "applicable", logical(pre_parameter.applicable || post_parameter.applicable), ...
  "pre_application", pre_parameter, "post_run", post_parameter);
controller = struct("pass", true, "applicable", false);
if isfield(exact, "config") && ~isempty(capture.controller_readback)
  cfg = experiment.ExperimentConfig.from_struct(exact.config);
  controller = testoracle.compare_controller_readback( ...
    cfg.controller, capture.controller_readback, ...
    "eps_factor", common.parameter_double_eps_factor);
  controller.applicable = true;
end

live = struct("pass", true, "applicable", false);
if isfield(capture, "live_report") && ~isempty(fieldnames(capture.live_report))
  live_report = capture.live_report;
  evidence = capture.live_evidence;
  live = struct( ...
    "pass", logical(isfield(live_report, "after") && ...
      isfield(live_report.after, "valid") && ...
      islogical(live_report.after.valid) && live_report.after.valid && ...
      isempty(live_report.after.issues) && ...
      double(live_report.target_execution_time_s) > 0 && ...
      isfile(live_report.backup_path) && evidence.source_exists && ...
      evidence.backup_exists && evidence.file_sha256_changed && ...
      evidence.output_json_digest_changed), ...
    "applicable", true, "report", live_report, "evidence", evidence);
end
vm_status = runtime_status_report(capture.vm_status);
raw_pass = report.pass;
report.raw_pass = raw_pass;
report.parameter_readback = parameter;
report.controller_readback = controller;
report.live_refresh = live;
report.vm_status = vm_status;
report.pass = logical(raw_pass && parameter.pass && controller.pass && ...
  live.pass && vm_status.pass);
end

function value = expected_parameter_readback(config_value, plant_value)
cfg = experiment.ExperimentConfig.from_struct(config_value);
plant = virtualMotor.PlantConfig.from_struct(plant_value);
value = struct("plant", plant.to_struct(), ...
  "taskDtNs", uint64(cfg.env.task_dt_ns()));
end

function report = runtime_status_report(status)
applicable = isstruct(status) && ~isempty(status);
if applicable
  motor_ready = all(arrayfun(@(x) ...
    uint16(x.motor_status) == uint16(hex2dec("0060")), status));
  load_ready = all(arrayfun(@(x) ...
    uint16(x.load_status) == uint16(hex2dec("0060")), status));
else
  motor_ready = false;
  load_ready = false;
end
report = struct( ...
  "pass", logical(applicable && motor_ready && load_ready), ...
  "applicable", applicable, "motor_ready", motor_ready, ...
  "load_ready", load_ready, "readback", status);
end

function tables = tables_for_config(config_value, feedforward)
cfg = experiment.ExperimentConfig.from_struct(config_value);
if ~isempty(feedforward), cfg.ff_profile = double(feedforward(:)); end
tables = struct( ...
  "ref_profile", cfg.ref_profile(:), "ff_profile", cfg.ff_profile(:), ...
  "dist_profile", cfg.dist_profile(:));
end

function report = aggregate_reports(items, field_name)
passes = cellfun(@(x) isstruct(x) && isscalar(x) && ...
  isfield(x, "pass") && islogical(x.pass) && isscalar(x.pass) && x.pass, items);
report = struct("pass", logical(all(passes)), field_name, {items}, ...
  "count", numel(items), "pass_count", nnz(passes));
end

function report = artifact_report(name, capture, expected)
if ~isfield(expected, "contract")
  error("testoracle:reports:artifactContractMissing", ...
    "%s has no frozen artifact contract.", name);
end
if string(expected.projection) == "none"
  actual = "no new artifact";
elseif any(name == ["tools.run_position_command_demo", "tools.run_si_demo", ...
    "tools.run_virtual_motor_prediction_e2e"])
  actual = testoracle.artifact_projection(name, struct("raw", capture.logger.raw));
else
  if isempty(capture.artifact_source)
    error("testoracle:reports:artifactUncaptured", ...
      "%s did not capture its saved artifact.", name);
  end
  actual = testoracle.artifact_projection(name, capture.artifact_source);
end
actual_units = testoracle.artifact_unit_map(name, actual);
report = testoracle.verify_artifact( ...
  actual, expected.contract, "units", actual_units);
end

function pass = captured_tool_pass(name, capture, common)
value = capture.tool_result;
switch name
  case {"tools.run_exp01_exp04_preflight", "tools.run_verify_xar"}
    pass = isstruct(value) && isfield(value, "passed") && ...
      islogical(value.passed) && isscalar(value.passed) && value.passed;
  case "tools.run_ads_discovery_demo"
    pass = isstruct(value) && all(isfield(value, ["ports", "symbols"])) && ...
      testoracle.validate_discovery(value.ports, value.symbols).pass;
  case "tools.run_verify_virtual_motor"
    pass = isstruct(value) && isfield(value, "passed") && ...
      islogical(value.passed) && isscalar(value.passed) && value.passed;
  case "tools.run_ads_transport_e2e"
    pass = isstruct(value) && isfield(value, "pass") && ...
      islogical(value.pass) && isscalar(value.pass) && value.pass;
  case "tools.run_configure_virtual_motor"
    pass = isstruct(value) && isfield(value, "verified") && ...
      islogical(value.verified) && isscalar(value.verified) && value.verified && ...
      testoracle.compare_parameter_readback(value.requested, value.readback, ...
        "eps_factor", common.parameter_double_eps_factor).pass;
  case "tools.run_virtual_motor_prediction_e2e"
    pass = isstruct(value) && all(isfield(value, ...
      ["logger_bin", "configuration", "restart"]));
  case "tools.run_check_logger_bin"
    pass = isstruct(value) && all(isfield(value, ...
      ["pass", "expected_count", "checked_count", "checks"])) && ...
      islogical(value.pass) && isscalar(value.pass) && value.pass && ...
      double(value.expected_count) == 30 && ...
      double(value.checked_count) == double(value.expected_count) && ...
      numel(capture.logger_proof) == double(value.expected_count) && ...
      all([capture.logger_proof.record_count] > 0);
  otherwise
    pass = true;
end
pass = islogical(pass) && isscalar(pass) && pass;
end
