function report = verify_final_state(state)
% verify_final_state  Enforce the final clean VirtualMotor/Controller state.
required = ["modeFlags", "modeState", "experimentActive", "resetReq", ...
  "idx", "tableLen", "loggerErrorCode", "apply_revision", ...
  "applied_revision", "processed_revision", "parameter_error_code", ...
  "motor_status", "load_status"];
if ~isstruct(state) || ~isscalar(state) || any(~isfield(state, required))
  error("testoracle:finalState:invalid", ...
    "Final state readback is missing required fields.");
end
checks = struct( ...
  "mode_flags_zero", uint16(state.modeFlags) == 0, ...
  "mode_idle", int16(state.modeState) == 0, ...
  "experiment_inactive", ~logical(state.experimentActive), ...
  "reset_request_clear", ~logical(state.resetReq), ...
  "index_zero", uint32(state.idx) == 0, ...
  "table_length_zero", uint32(state.tableLen) == 0, ...
  "logger_error_zero", uint32(state.loggerErrorCode) == 0, ...
  "controller_revision_match", ...
    uint32(state.apply_revision) == uint32(state.applied_revision) && ...
    uint32(state.apply_revision) == uint32(state.processed_revision), ...
  "controller_parameter_error_zero", uint32(state.parameter_error_code) == 0, ...
  "motor_status_ready", uint16(state.motor_status) == uint16(hex2dec("0060")), ...
  "load_status_ready", uint16(state.load_status) == uint16(hex2dec("0060")));
report = struct("pass", all(structfun(@logical, checks)), "checks", checks);
end
