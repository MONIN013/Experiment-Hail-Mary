function proof = prepare_vm_entry(registry_entry, expected_entry, ~)
% prepare_vm_entry  Apply the restart/configure policy immediately pre-entry.
policy = string(registry_entry.restart_policy);
proof = struct("policy", policy, "restart_count", 0, ...
  "restart", struct(), "configuration", struct());
if ~any(policy == ["before_entry", "campaign_once"])
  return;
end
if ~isfield(expected_entry.exact, "config") || ...
    ~isfield(expected_entry.exact, "plant")
  error("testoracle:orchestrator:missingPreparation", ...
    "%s has no frozen config/plant for restart preparation.", registry_entry.name);
end
cfg = experiment.ExperimentConfig.from_struct(expected_entry.exact.config);
plant = virtualMotor.PlantConfig.from_struct(expected_entry.exact.plant);
restart = virtualMotor.restart_runtime(cfg.env);
conn = experiment.ConnectionManager.create(cfg);
cleanup = onCleanup(@() conn.session.close());
configuration = virtualMotor.configure(conn, plant, ...
  "taskDtNs", cfg.env.task_dt_ns(), ...
  "timeout_s", cfg.reset_timeout_s, "validateSymbols", true);
parameter_report = testoracle.compare_parameter_readback( ...
  configuration.requested, configuration.readback, ...
  "eps_factor", expected_entry.outcome.gate.common.parameter_double_eps_factor);
if ~parameter_report.pass
  error("testoracle:orchestrator:parameterMismatch", ...
    "%s VM parameter readback did not match the frozen request.", registry_entry.name);
end
proof.restart_count = 1;
proof.restart = restart;
proof.configuration = struct( ...
  "verified", configuration.verified, ...
  "parameter_report", parameter_report, ...
  "requested", configuration.requested, ...
  "readback", configuration.readback);
end
