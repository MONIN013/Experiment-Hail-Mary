function value = read_controller_readback(conn, cfg)
% read_controller_readback  Capture padded SOS and revision state over ADS.
if ~isstruct(conn) || ~isfield(conn, "module") || ...
    ~isa(conn.module, "twincat_ads.IAdsTransport")
  error("testoracle:controller:invalidConnection", ...
    "A live module transport is required.");
end
cfg = experiment.ExperimentConfig.from_varargin(cfg);
symbols = experiment.RuntimeSymbols.from_controller_prefix( ...
  cfg.env.controller_prefix).controllerParams;
t = twincat_ads.AdsTransport.net_types();
count = experiment.ControllerConfig.MAX_SOS_SECTIONS * ...
  experiment.ControllerConfig.ADS_COEFFICIENTS_PER_SECTION;
value = struct( ...
  "coefficients", conn.module.read_array(symbols.coefficients, t.double, count), ...
  "section_count", conn.module.read_scalar(symbols.sectionCount, t.u32), ...
  "apply_revision", conn.module.read_scalar(symbols.applyRevision, t.u32), ...
  "applied_revision", conn.module.read_scalar(symbols.appliedRevision, t.u32), ...
  "processed_revision", conn.module.read_scalar(symbols.processedRevision, t.u32), ...
  "parameter_error_code", conn.module.read_scalar(symbols.parameterErrorCode, t.u32));
end
