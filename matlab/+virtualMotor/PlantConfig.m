classdef PlantConfig
  properties
    motor = struct( ...
      "inertia", 7.1e-6, ...
      "damping", 7.1e-5, ...
      "ratedTorque", 0.32, ...
      "tauLimit", 1.11, ...
      "velLimit", 2*pi*6500/60, ...
      "maxPermille", 1000.0, ...
      "encoderResolution", uint32(8388608))
    load = struct( ...
      "inertia", 7.1e-6, ...
      "damping", 3.55e-5, ...
      "ratedTorque", 0.32, ...
      "tauLimit", 1.11, ...
      "velLimit", 2*pi*6500/60, ...
      "encoderResolution", uint32(8388608))
    coupling = struct( ...
      "stiffness", 5.6059352998187553, ...
      "damping", 0.0004194811568097506)
  end

  methods (Static)
    function out = from_struct(s)
      out = virtualMotor.PlantConfig();
      if nargin < 1 || isempty(s)
        out = out.normalize();
        return;
      end
      if isa(s, "virtualMotor.PlantConfig")
        if ~isscalar(s)
          error("virtualMotor:plant:invalid", "PlantConfig must be scalar.");
        end
        out = s.normalize();
        return;
      end
      if ~isstruct(s) || ~isscalar(s)
        error("virtualMotor:plant:invalid", ...
          "PlantConfig.from_struct accepts only a scalar struct or PlantConfig.");
      end

      required_fields = ["motor", "load", "coupling"];
      actual_fields = string(fieldnames(s));
      if ~isempty(setdiff(actual_fields, required_fields))
        error("virtualMotor:plant:invalid", ...
          "PlantConfig accepts only motor/load/coupling fields.");
      end

      for k = 1:numel(required_fields)
        key = char(required_fields(k));
        if ~isfield(s, key)
          error("virtualMotor:plant:invalid", ...
            "PlantConfig requires '%s'.", key);
        end
      end

      out.motor = normalize_axis_struct(s.motor, "motor");
      out.load = normalize_axis_struct(s.load, "load");
      out.coupling = normalize_coupling_struct(s.coupling);
      out = out.normalize();
    end
  end

  methods
    function out = normalize(obj)
      out = obj;
      out.motor = normalize_axis_struct(out.motor, "motor");
      out.load = normalize_axis_struct(out.load, "load");
      out.coupling = normalize_coupling_struct(out.coupling);
    end

    function s = to_struct(obj)
      out = obj.normalize();
      s = struct( ...
        "motor", out.motor, ...
        "load", out.load, ...
        "coupling", out.coupling);
    end
  end
end

function axis = normalize_axis_struct(axis, label)
if nargin < 2
  label = "axis";
end
if strcmp(label, "motor")
  defaults = struct( ...
    "inertia", 7.1e-6, ...
    "damping", 7.1e-5, ...
    "ratedTorque", 0.32, ...
    "tauLimit", 1.11, ...
    "velLimit", 2*pi*6500/60, ...
    "maxPermille", 1000.0, ...
    "encoderResolution", uint32(8388608));
else
  defaults = struct( ...
    "inertia", 7.1e-6, ...
    "damping", 3.55e-5, ...
    "ratedTorque", 0.32, ...
    "tauLimit", 1.11, ...
    "velLimit", 2*pi*6500/60, ...
    "encoderResolution", uint32(8388608));
end
if ~isstruct(axis) || ~isscalar(axis)
  error("virtualMotor:plant:invalid", ...
    "%s must be a scalar struct.", label);
end
actual_fields = string(fieldnames(axis));
expected_fields = string(fieldnames(defaults));
unknown = setdiff(actual_fields, expected_fields);
if ~isempty(unknown)
  error("virtualMotor:plant:invalid", ...
    "%s accepts only %s.", label, strjoin(expected_fields, ", "));
end
missing = setdiff(expected_fields, actual_fields);
if ~isempty(missing)
  error("virtualMotor:plant:invalid", ...
    "%s is missing %s.", label, strjoin(missing, ", "));
end
if strcmp(label, "motor")
  validate_positive(axis.inertia, label + ".inertia");
  validate_nonnegative(axis.damping, label + ".damping");
  validate_positive(axis.ratedTorque, label + ".ratedTorque");
  validate_positive(axis.tauLimit, label + ".tauLimit");
  validate_positive(axis.velLimit, label + ".velLimit");
  validate_nonnegative(axis.maxPermille, label + ".maxPermille");
  validate_encoder_resolution(axis.encoderResolution, label + ".encoderResolution");
  axis = struct( ...
    "inertia", double(axis.inertia), ...
    "damping", double(axis.damping), ...
    "ratedTorque", double(axis.ratedTorque), ...
    "tauLimit", double(axis.tauLimit), ...
    "velLimit", double(axis.velLimit), ...
    "maxPermille", double(axis.maxPermille), ...
    "encoderResolution", uint32(axis.encoderResolution));
else
  validate_positive(axis.inertia, label + ".inertia");
  validate_nonnegative(axis.damping, label + ".damping");
  validate_positive(axis.ratedTorque, label + ".ratedTorque");
  validate_positive(axis.tauLimit, label + ".tauLimit");
  validate_positive(axis.velLimit, label + ".velLimit");
  validate_encoder_resolution(axis.encoderResolution, label + ".encoderResolution");
  axis = struct( ...
    "inertia", double(axis.inertia), ...
    "damping", double(axis.damping), ...
    "ratedTorque", double(axis.ratedTorque), ...
    "tauLimit", double(axis.tauLimit), ...
    "velLimit", double(axis.velLimit), ...
    "encoderResolution", uint32(axis.encoderResolution));
end
end

function coupling = normalize_coupling_struct(coupling)
if ~isstruct(coupling) || ~isscalar(coupling)
  error("virtualMotor:plant:invalid", ...
    "coupling must be a scalar struct.");
end
expected_fields = ["stiffness", "damping"];
actual_fields = string(fieldnames(coupling));
unknown = setdiff(actual_fields, expected_fields);
if ~isempty(unknown)
  error("virtualMotor:plant:invalid", ...
    "coupling accepts only stiffness and damping.");
end
missing = setdiff(expected_fields, actual_fields);
if ~isempty(missing)
  error("virtualMotor:plant:invalid", ...
    "coupling is missing %s.", strjoin(missing, ", "));
end
validate_nonnegative(coupling.stiffness, "coupling.stiffness");
validate_nonnegative(coupling.damping, "coupling.damping");
coupling = struct( ...
  "stiffness", double(coupling.stiffness), ...
  "damping", double(coupling.damping));
end

function validate_positive(value, label)
if ~(isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(double(value)) && double(value) > 0)
  error("virtualMotor:plant:invalid", "%s must be a positive scalar.", label);
end
end

function validate_nonnegative(value, label)
if ~(isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(double(value)) && double(value) >= 0)
  error("virtualMotor:plant:invalid", "%s must be a nonnegative scalar.", label);
end
end

function validate_encoder_resolution(value, label)
if ~(isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(double(value)) && double(value) >= 1 && ...
    floor(double(value)) == double(value) && double(value) <= double(intmax("uint32")))
  error("virtualMotor:plant:invalid", ...
    "%s must be a positive integer representable as uint32.", label);
end
end
