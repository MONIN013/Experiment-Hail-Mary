function out = readParams(conn)
% readParams  Read the active VirtualMotor plant parameter set.

if ~isstruct(conn) || ~isfield(conn, "module") || ...
    ~isa(conn.module, "twincat_ads.IAdsTransport")
  error("virtualMotor:readParams:invalidConnection", ...
    "Connection must contain a module transport.");
end

transport = conn.module;
symbols = virtualMotor.Symbols.from_defaults();
t = symbols.types;
vm = symbols.vmParams;
plant = struct( ...
  "motor", struct( ...
    "inertia", double(transport.read_scalar(vm.motor.inertia, t.double)), ...
    "damping", double(transport.read_scalar(vm.motor.damping, t.double)), ...
    "ratedTorque", double(transport.read_scalar(vm.motor.ratedTorque, t.double)), ...
    "tauLimit", double(transport.read_scalar(vm.motor.tauLimit, t.double)), ...
    "velLimit", double(transport.read_scalar(vm.motor.velLimit, t.double)), ...
    "maxPermille", double(transport.read_scalar(vm.motor.maxPermille, t.double)), ...
    "encoderResolution", uint32(transport.read_scalar(vm.motor.encoderResolution, t.u32))), ...
  "load", struct( ...
    "inertia", double(transport.read_scalar(vm.load.inertia, t.double)), ...
    "damping", double(transport.read_scalar(vm.load.damping, t.double)), ...
    "ratedTorque", double(transport.read_scalar(vm.load.ratedTorque, t.double)), ...
    "tauLimit", double(transport.read_scalar(vm.load.tauLimit, t.double)), ...
    "velLimit", double(transport.read_scalar(vm.load.velLimit, t.double)), ...
    "encoderResolution", uint32(transport.read_scalar(vm.load.encoderResolution, t.u32))), ...
  "coupling", struct( ...
    "stiffness", double(transport.read_scalar(vm.coupling.stiffness, t.double)), ...
    "damping", double(transport.read_scalar(vm.coupling.damping, t.double))));

out = struct( ...
  "plant", virtualMotor.PlantConfig.from_struct(plant).to_struct(), ...
  "taskDtNs", uint64(transport.read_scalar(vm.taskDtNs, t.u64)));
end
