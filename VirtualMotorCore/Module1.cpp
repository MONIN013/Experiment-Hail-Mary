double CModule1::ClampSymmetric(double value, double limit)
{
	double lim = limit;
	if (lim < 0.0)
	{
		lim = -lim;
	}
	if (value > lim)
	{
		return lim;
	}
	if (value < -lim)
	{
		return -lim;
	}
	return value;
}

void CModule1::StepVirtualMotor(double currentIn)
{
	if (m_VirtualMotorParameter.M <= 0.0 || m_VirtualMotorParameter.task_dt_ns == 0)
	{
		return;
	}

	const double kVelocityZeroThreshold = 1e-6;
	const double dtS = static_cast<double>(m_VirtualMotorParameter.task_dt_ns) * 1e-9;
	const double dNonNeg = (m_VirtualMotorParameter.D < 0.0) ? 0.0 : m_VirtualMotorParameter.D;
	const double ktAbs = (m_VirtualMotorParameter.Kt < 0.0) ? -m_VirtualMotorParameter.Kt : m_VirtualMotorParameter.Kt;
	const double tauCmdRequest = ktAbs * currentIn;
	const double tauLimitAbs = (m_VirtualMotorParameter.tau_limit < 0.0) ? -m_VirtualMotorParameter.tau_limit : m_VirtualMotorParameter.tau_limit;
	if (tauLimitAbs > 0.0 && (tauCmdRequest > tauLimitAbs || tauCmdRequest < -tauLimitAbs))
	{
		m_internalFault = true;
		m_driveState = EDriveState::FAULT;
	}

	const double appliedCurrent = m_internalFault ? 0.0 : currentIn;
	const double tauCmd = ktAbs * appliedCurrent;
	const double tauSat = ClampSymmetric(tauCmd, m_VirtualMotorParameter.tau_limit);

	const double vNextUnclamped = m_velocity + (dtS / m_VirtualMotorParameter.M) * (tauSat - dNonNeg * m_velocity);
	const double velLimitAbs = (m_VirtualMotorParameter.vel_limit < 0.0) ? -m_VirtualMotorParameter.vel_limit : m_VirtualMotorParameter.vel_limit;
	if (velLimitAbs > 0.0 && (vNextUnclamped > velLimitAbs || vNextUnclamped < -velLimitAbs))
	{
		m_internalFault = true;
		m_driveState = EDriveState::FAULT;
	}

	double vNext = vNextUnclamped;
	vNext = ClampSymmetric(vNext, m_VirtualMotorParameter.vel_limit);
	if (vNext < kVelocityZeroThreshold && vNext > -kVelocityZeroThreshold)
	{
		vNext = 0.0;
	}
	const double xNext = m_position + dtS * vNext;

	m_velocity = vNext;
	m_position = xNext;
}

void CModule1::ResetState()
{
	m_position = 0.0;
	m_velocity = 0.0;
	m_driveState = EDriveState::SWITCH_ON_DISABLED;
	m_faultResetBitWasSet = false;
	m_internalFault = false;
	m_Outputs.statusword = ComposeStatusWord();
}

void CModule1::UpdateDriveState(USHORT controlWord)
{
	const bool disableVoltage = (controlWord & 0x0002) == 0;
	const bool faultResetBitSet = (controlWord & 0x0080) != 0;
	const bool faultResetPulse = faultResetBitSet && !m_faultResetBitWasSet;
	const bool isShutdown = (controlWord & 0x008F) == 0x0006;
	const bool isSwitchOn = (controlWord & 0x008F) == 0x0007;
	const bool isEnableOp = (controlWord & 0x008F) == 0x000F;

	m_faultResetBitWasSet = faultResetBitSet;

	// Fault is latched and can only be cleared by FaultReset pulse.
	if (m_driveState == EDriveState::FAULT || m_internalFault)
	{
		m_driveState = EDriveState::FAULT;
		m_internalFault = true;
		if (faultResetPulse)
		{
			m_internalFault = false;
			m_driveState = EDriveState::SWITCH_ON_DISABLED;
		}
		return;
	}

	if (disableVoltage)
	{
		m_driveState = EDriveState::SWITCH_ON_DISABLED;
		return;
	}

	switch (m_driveState)
	{
	case EDriveState::SWITCH_ON_DISABLED:
		if (isShutdown)
		{
			m_driveState = EDriveState::READY_TO_SWITCH_ON;
		}
		break;
	case EDriveState::READY_TO_SWITCH_ON:
		if (isSwitchOn)
		{
			m_driveState = EDriveState::SWITCHED_ON;
		}
		break;
	case EDriveState::SWITCHED_ON:
		if (isEnableOp)
		{
			m_driveState = EDriveState::OPERATION_ENABLED;
		}
		break;
	case EDriveState::OPERATION_ENABLED:
		break;
	case EDriveState::FAULT:
		break;
	}
}

USHORT CModule1::ComposeStatusWord() const
{
	switch (m_driveState)
	{
	case EDriveState::SWITCH_ON_DISABLED:
		return static_cast<USHORT>((1u << 6) | (1u << 5));
	case EDriveState::READY_TO_SWITCH_ON:
		return static_cast<USHORT>((1u << 5) | (1u << 0));
	case EDriveState::SWITCHED_ON:
		return static_cast<USHORT>((1u << 5) | (1u << 1) | (1u << 0));
	case EDriveState::OPERATION_ENABLED:
		return static_cast<USHORT>((1u << 5) | (1u << 2) | (1u << 1) | (1u << 0));
	case EDriveState::FAULT:
		return static_cast<USHORT>((1u << 5) | (1u << 3));
	}
	return 0;
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CModule1::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID; 
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CModule1::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if ( m_spCyclicCaller )
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller	= NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}

