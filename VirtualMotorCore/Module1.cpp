double CModule1::ClampSymmetric(double value, double limit)
{
	double lim = limit;
	if (lim < 0.0)
	{
		lim = -lim;
	}
	if (value > lim)
	{
		return lim;
	}
	if (value < -lim)
	{
		return -lim;
	}
	return value;
}

namespace
{
double ApplyOptionalSymmetricLimit(double value, double limit)
{
	const double limitAbs = std::fabs(limit);
	if (limitAbs <= 0.0)
	{
		return value;
	}
	if (value > limitAbs)
	{
		return limitAbs;
	}
	if (value < -limitAbs)
	{
		return -limitAbs;
	}
	return value;
}
}

LONG CModule1::SaturatingRoundToDint(double value)
{
	const double rounded = (value >= 0.0) ? std::floor(value + 0.5) : std::ceil(value - 0.5);
	if (rounded > kLongMaxAsDouble)
	{
		return std::numeric_limits<LONG>::max();
	}
	if (rounded < kLongMinAsDouble)
	{
		return std::numeric_limits<LONG>::min();
	}
	return static_cast<LONG>(rounded);
}

