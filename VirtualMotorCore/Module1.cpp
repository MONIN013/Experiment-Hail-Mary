///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CModule1::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	HRESULT hr = S_OK;
	(void)ipTask;
	(void)ipCaller;
	(void)context;

	UpdateDriveState(m_Inputs.controlword);
	if (m_driveState == EDriveState::OPERATION_ENABLED)
	{
		StepVirtualMotor(m_Inputs.VirtualMotorInputs.current_in);
	}
	m_Outputs.VirtualMotorOutputs.position_out = m_position;
	m_Outputs.VirtualMotorOutputs.velocity_out = m_velocity;
	m_Outputs.statusword = ComposeStatusWord();

	return hr;
}
