///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CModule1::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	HRESULT hr = S_OK;
	(void)ipTask;
	(void)ipCaller;
	(void)context;

	UpdateDriveState(kMotorAxis, m_Inputs.motor.controlWord);
	UpdateDriveState(kLoadAxis, m_Inputs.load.controlWord);

	EvaluateMotorCommandFaults(static_cast<double>(m_Inputs.motor.targetTorque));
	IntegratePlant(static_cast<double>(m_Inputs.motor.targetTorque));
	UpdateOutputs();

	return hr;
}
