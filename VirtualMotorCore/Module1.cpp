void CModule1::EvaluateMotorCommandFaults(double targetTorquePermille)
{
	DriveRuntimeState& motorDrive = DriveState(kMotorAxis);
	if (motorDrive.driveState != EDriveState::OPERATION_ENABLED || motorDrive.internalFault)
	{
		return;
	}

	const ST_VirtualMotorMotorParams& motorParams = MotorParams();
	const double maxPerm = NonNegativeOrZero(motorParams.maxPermille);
	if (maxPerm > 0.0 && std::fabs(targetTorquePermille) > maxPerm)
	{
		motorDrive.internalFault = true;
		motorDrive.driveState = EDriveState::FAULT;
		return;
	}

	const double tauRequestNm =
		(targetTorquePermille / 1000.0) * EffectiveRatedTorque(motorParams);
	const double tauLimitAbs = std::fabs(motorParams.tauLimit);
	if (tauLimitAbs > 0.0 && std::fabs(tauRequestNm) > tauLimitAbs)
	{
		motorDrive.internalFault = true;
		motorDrive.driveState = EDriveState::FAULT;
	}
}

void CModule1::IntegratePlant(double targetTorquePermille)
{
	const double dtS = static_cast<double>(m_PlantParameter.taskDtNs) * 1e-9;
	const double jm = NonNegativeOrZero(m_PlantParameter.motor.inertia);
	const double jl = NonNegativeOrZero(m_PlantParameter.load.inertia);
	if (dtS <= 0.0 || jm <= 0.0 || jl <= 0.0)
	{
		m_PlantState.lastMotorTorqueNm = 0.0;
		m_PlantState.lastShaftTorqueNm = 0.0;
		return;
	}

	const double bm = NonNegativeOrZero(m_PlantParameter.motor.damping);
	const double bl = NonNegativeOrZero(m_PlantParameter.load.damping);
	const double ks = NonNegativeOrZero(m_PlantParameter.coupling.stiffness);
	const double ds = NonNegativeOrZero(m_PlantParameter.coupling.damping);

	double tauMotorNm = 0.0;
	if (DriveState(kMotorAxis).driveState == EDriveState::OPERATION_ENABLED &&
		!DriveState(kMotorAxis).internalFault)
	{
		const double tauRequestNm =
			(targetTorquePermille / 1000.0) * EffectiveRatedTorque(MotorParams());
		tauMotorNm = ApplyOptionalSymmetricLimit(tauRequestNm, MotorParams().tauLimit);
	}

	const double thetaDelta = m_PlantState.thetaMotor - m_PlantState.thetaLoad;
	const double omegaDelta = m_PlantState.omegaMotor - m_PlantState.omegaLoad;
	const double tauShaftNm = ks * thetaDelta + ds * omegaDelta;

	const double omegaMotorNextUnclamped = m_PlantState.omegaMotor +
		dtS * ((tauMotorNm - tauShaftNm - bm * m_PlantState.omegaMotor) / jm);
	const double omegaLoadNextUnclamped = m_PlantState.omegaLoad +
		dtS * ((tauShaftNm - bl * m_PlantState.omegaLoad) / jl);

	const double motorVelLimitAbs = std::fabs(MotorParams().velLimit);
	if (motorVelLimitAbs > 0.0 && std::fabs(omegaMotorNextUnclamped) > motorVelLimitAbs)
	{
		DriveState(kMotorAxis).internalFault = true;
		DriveState(kMotorAxis).driveState = EDriveState::FAULT;
	}

	const double loadVelLimitAbs = std::fabs(LoadParams().velLimit);
	if (loadVelLimitAbs > 0.0 && std::fabs(omegaLoadNextUnclamped) > loadVelLimitAbs)
	{
		DriveState(kLoadAxis).internalFault = true;
		DriveState(kLoadAxis).driveState = EDriveState::FAULT;
	}

	double omegaMotorNext = ApplyOptionalSymmetricLimit(omegaMotorNextUnclamped, MotorParams().velLimit);
	double omegaLoadNext = ApplyOptionalSymmetricLimit(omegaLoadNextUnclamped, LoadParams().velLimit);
	if (std::fabs(omegaMotorNext) < 1e-9)
	{
		omegaMotorNext = 0.0;
	}
	if (std::fabs(omegaLoadNext) < 1e-9)
	{
		omegaLoadNext = 0.0;
	}

	m_PlantState.thetaMotor += dtS * omegaMotorNext;
	m_PlantState.thetaLoad += dtS * omegaLoadNext;
	m_PlantState.omegaMotor = omegaMotorNext;
	m_PlantState.omegaLoad = omegaLoadNext;

	const double tauShaftNextNm =
		ks * (m_PlantState.thetaMotor - m_PlantState.thetaLoad) +
		ds * (m_PlantState.omegaMotor - m_PlantState.omegaLoad);
	const double loadTauLimitAbs = std::fabs(LoadParams().tauLimit);
	if (loadTauLimitAbs > 0.0 && std::fabs(tauShaftNextNm) > loadTauLimitAbs)
	{
		DriveState(kLoadAxis).internalFault = true;
		DriveState(kLoadAxis).driveState = EDriveState::FAULT;
	}

	m_PlantState.lastMotorTorqueNm = tauMotorNm;
	m_PlantState.lastShaftTorqueNm = tauShaftNextNm;
}

void CModule1::UpdateOutputs()
{
	const ST_VirtualMotorMotorParams& motorParams = MotorParams();
	const ST_VirtualMotorLoadParams& loadParams = LoadParams();
	const double motorScale = static_cast<double>(EffectiveEncoderResolution(motorParams)) / kTwoPi;
	const double loadScale = static_cast<double>(EffectiveEncoderResolution(loadParams)) / kTwoPi;

	m_Outputs.motor.positionActualValue = SaturatingRoundToDint(m_PlantState.thetaMotor * motorScale);
	m_Outputs.motor.velocityActualValue = SaturatingRoundToDint(m_PlantState.omegaMotor * motorScale);
	m_Outputs.motor.torqueActualValue = SaturatingRoundToInt(
		(m_PlantState.lastMotorTorqueNm / EffectiveRatedTorque(motorParams)) * 1000.0);
	m_Outputs.motor.statusWord = ComposeStatusWord(kMotorAxis);

	m_Outputs.load.positionActualValue = SaturatingRoundToDint(m_PlantState.thetaLoad * loadScale);
	m_Outputs.load.velocityActualValue = SaturatingRoundToDint(m_PlantState.omegaLoad * loadScale);
	m_Outputs.load.torqueActualValue = SaturatingRoundToInt(
		(m_PlantState.lastShaftTorqueNm / EffectiveRatedTorque(loadParams)) * 1000.0);
	m_Outputs.load.statusWord = ComposeStatusWord(kLoadAxis);
}

void CModule1::ResetRuntimeState()
{
	for (int i = 0; i < kAxisCount; ++i)
	{
		m_Drive[i].driveState = EDriveState::SWITCH_ON_DISABLED;
		m_Drive[i].faultResetBitWasSet = false;
		m_Drive[i].internalFault = false;
	}

	m_PlantState.thetaMotor = 0.0;
	m_PlantState.omegaMotor = 0.0;
	m_PlantState.thetaLoad = 0.0;
	m_PlantState.omegaLoad = 0.0;
	m_PlantState.lastMotorTorqueNm = 0.0;
	m_PlantState.lastShaftTorqueNm = 0.0;
	memset(&m_Outputs, 0, sizeof(m_Outputs));
	UpdateOutputs();
}

void CModule1::UpdateDriveState(int axisIndex, USHORT controlWord)
{
	DriveRuntimeState& axis = DriveState(axisIndex);
	const bool disableVoltage = (controlWord & 0x0002) == 0;
	const bool faultResetBitSet = (controlWord & 0x0080) != 0;
	const bool faultResetPulse = faultResetBitSet && !axis.faultResetBitWasSet;
	const bool isShutdown = (controlWord & 0x008F) == 0x0006;
	const bool isSwitchOn = (controlWord & 0x008F) == 0x0007;
	const bool isEnableOp = (controlWord & 0x008F) == 0x000F;

	axis.faultResetBitWasSet = faultResetBitSet;

	if (axis.driveState == EDriveState::FAULT || axis.internalFault)
	{
		axis.driveState = EDriveState::FAULT;
		axis.internalFault = true;
		if (faultResetPulse)
		{
			axis.internalFault = false;
			axis.driveState = EDriveState::SWITCH_ON_DISABLED;
		}
		return;
	}

	if (disableVoltage)
	{
		axis.driveState = EDriveState::SWITCH_ON_DISABLED;
		return;
	}

	switch (axis.driveState)
	{
	case EDriveState::SWITCH_ON_DISABLED:
		if (isShutdown)
		{
			axis.driveState = EDriveState::READY_TO_SWITCH_ON;
		}
		break;
	case EDriveState::READY_TO_SWITCH_ON:
		if (isSwitchOn)
		{
			axis.driveState = EDriveState::SWITCHED_ON;
		}
		break;
	case EDriveState::SWITCHED_ON:
		if (isEnableOp)
		{
			axis.driveState = EDriveState::OPERATION_ENABLED;
		}
		break;
	case EDriveState::OPERATION_ENABLED:
		break;
	case EDriveState::FAULT:
		break;
	}
}

USHORT CModule1::ComposeStatusWord(int axisIndex) const
{
	switch (DriveState(axisIndex).driveState)
	{
	case EDriveState::SWITCH_ON_DISABLED:
		return static_cast<USHORT>((1u << 6) | (1u << 5));
	case EDriveState::READY_TO_SWITCH_ON:
		return static_cast<USHORT>((1u << 5) | (1u << 0));
	case EDriveState::SWITCHED_ON:
		return static_cast<USHORT>((1u << 5) | (1u << 1) | (1u << 0));
	case EDriveState::OPERATION_ENABLED:
		return static_cast<USHORT>((1u << 5) | (1u << 2) | (1u << 1) | (1u << 0));
	case EDriveState::FAULT:
		return static_cast<USHORT>((1u << 5) | (1u << 3));
	}
	return 0;
}

HRESULT CModule1::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if (m_spCyclicCaller.HasOID())
	{
		if (SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)))
		{
			if (FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))))
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID;
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

VOID CModule1::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if (m_spCyclicCaller)
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller = NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}
