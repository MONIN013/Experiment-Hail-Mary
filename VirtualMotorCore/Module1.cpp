void CModule1::StepVirtualMotor(int axisIndex, SHORT targetTorquePermille)
{
	AxisRuntimeState& axis = m_Axis[axisIndex];
	const ST_VirtualMotorParams& params = AxisParams(axisIndex);

	if (params.mass <= 0.0 || params.taskDtNs == 0)
	{
		axis.lastAppliedTorqueNm = 0.0;
		return;
	}

	const double kVelocityZeroThreshold = 1e-6;
	const double dtS = static_cast<double>(params.taskDtNs) * 1e-9;
	const double dNonNeg = (params.damping < 0.0) ? 0.0 : params.damping;
	const double ratedTorque = EffectiveRatedTorque(params);
	const double tauCmdRequest = (static_cast<double>(targetTorquePermille) / 1000.0) * ratedTorque;
	const double tauLimitAbs = (params.tauLimit < 0.0) ? -params.tauLimit : params.tauLimit;
	if (tauLimitAbs > 0.0 && (tauCmdRequest > tauLimitAbs || tauCmdRequest < -tauLimitAbs))
	{
		axis.internalFault = true;
		axis.driveState = EDriveState::FAULT;
	}

	const double appliedTargetTorquePermille = axis.internalFault ? 0.0 : static_cast<double>(targetTorquePermille);
	const double tauCmd = (appliedTargetTorquePermille / 1000.0) * ratedTorque;
	const double tauSat = ClampSymmetric(tauCmd, params.tauLimit);

	const double vNextUnclamped = axis.velocity + (dtS / params.mass) * (tauSat - dNonNeg * axis.velocity);
	const double velLimitAbs = (params.velLimit < 0.0) ? -params.velLimit : params.velLimit;
	if (velLimitAbs > 0.0 && (vNextUnclamped > velLimitAbs || vNextUnclamped < -velLimitAbs))
	{
		axis.internalFault = true;
		axis.driveState = EDriveState::FAULT;
	}

	double vNext = ClampSymmetric(vNextUnclamped, params.velLimit);
	if (vNext < kVelocityZeroThreshold && vNext > -kVelocityZeroThreshold)
	{
		vNext = 0.0;
	}
	const double xNext = axis.position + dtS * vNext;

	axis.velocity = vNext;
	axis.position = xNext;
	axis.lastAppliedTorqueNm = tauSat;
}

void CModule1::ResetRuntimeState()
{
	for (int i = 0; i < kAxisCount; ++i)
	{
		m_Axis[i].position = 0.0;
		m_Axis[i].velocity = 0.0;
		m_Axis[i].lastAppliedTorqueNm = 0.0;
		m_Axis[i].driveState = EDriveState::SWITCH_ON_DISABLED;
		m_Axis[i].faultResetBitWasSet = false;
		m_Axis[i].internalFault = false;
	}

	m_Outputs.statusWord1 = ComposeStatusWord(0);
	m_Outputs.statusWord2 = ComposeStatusWord(1);
	m_Outputs.VirtualMotor1Outputs.positionActualValue = 0;
	m_Outputs.VirtualMotor1Outputs.velocityActualValue = 0;
	m_Outputs.VirtualMotor1Outputs.torqueActualValue = 0;
	m_Outputs.VirtualMotor2Outputs.positionActualValue = 0;
	m_Outputs.VirtualMotor2Outputs.velocityActualValue = 0;
	m_Outputs.VirtualMotor2Outputs.torqueActualValue = 0;
}

void CModule1::UpdateDriveState(int axisIndex, USHORT controlWord)
{
	AxisRuntimeState& axis = m_Axis[axisIndex];
	const bool disableVoltage = (controlWord & 0x0002) == 0;
	const bool faultResetBitSet = (controlWord & 0x0080) != 0;
	const bool faultResetPulse = faultResetBitSet && !axis.faultResetBitWasSet;
	const bool isShutdown = (controlWord & 0x008F) == 0x0006;
	const bool isSwitchOn = (controlWord & 0x008F) == 0x0007;
	const bool isEnableOp = (controlWord & 0x008F) == 0x000F;

	axis.faultResetBitWasSet = faultResetBitSet;

	// Fault is latched and can only be cleared by FaultReset pulse.
	if (axis.driveState == EDriveState::FAULT || axis.internalFault)
	{
		axis.driveState = EDriveState::FAULT;
		axis.internalFault = true;
		if (faultResetPulse)
		{
			axis.internalFault = false;
			axis.driveState = EDriveState::SWITCH_ON_DISABLED;
		}
		return;
	}

	if (disableVoltage)
	{
		axis.driveState = EDriveState::SWITCH_ON_DISABLED;
		return;
	}

	switch (axis.driveState)
	{
	case EDriveState::SWITCH_ON_DISABLED:
		if (isShutdown)
		{
			axis.driveState = EDriveState::READY_TO_SWITCH_ON;
		}
		break;
	case EDriveState::READY_TO_SWITCH_ON:
		if (isSwitchOn)
		{
			axis.driveState = EDriveState::SWITCHED_ON;
		}
		break;
	case EDriveState::SWITCHED_ON:
		if (isEnableOp)
		{
			axis.driveState = EDriveState::OPERATION_ENABLED;
		}
		break;
	case EDriveState::OPERATION_ENABLED:
		break;
	case EDriveState::FAULT:
		break;
	}
}

USHORT CModule1::ComposeStatusWord(int axisIndex) const
{
	switch (m_Axis[axisIndex].driveState)
	{
	case EDriveState::SWITCH_ON_DISABLED:
		return static_cast<USHORT>((1u << 6) | (1u << 5));
	case EDriveState::READY_TO_SWITCH_ON:
		return static_cast<USHORT>((1u << 5) | (1u << 0));
	case EDriveState::SWITCHED_ON:
		return static_cast<USHORT>((1u << 5) | (1u << 1) | (1u << 0));
	case EDriveState::OPERATION_ENABLED:
		return static_cast<USHORT>((1u << 5) | (1u << 2) | (1u << 1) | (1u << 0));
	case EDriveState::FAULT:
		return static_cast<USHORT>((1u << 5) | (1u << 3));
	}
	return 0;
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CModule1::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID; 
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CModule1::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if ( m_spCyclicCaller )
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller	= NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}

