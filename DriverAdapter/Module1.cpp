///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CModule1::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	HRESULT hr = S_OK;
	(void)ipTask;
	(void)ipCaller;
	(void)context;

	const driveradapter::Parameters parameters = {
		MakeAxisParameters(m_MotorParams),
		MakeAxisParameters(m_LoadParams),
		{ m_SafetyLimits.maxPositionRad, m_SafetyLimits.maxVelocityRadS, m_SafetyLimits.maxTwistRad },
		m_SafetyResetRevision
	};
	CopyOutputs(m_algorithm.Step(parameters, MakeInputs(m_Inputs)), m_Outputs);
	return hr;
}
///</AutoGeneratedContent>

void CModule1::ResetRuntimeState()
{
	m_algorithm.Reset();
	memset(&m_Outputs, 0, sizeof(m_Outputs));
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CModule1::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if (m_spCyclicCaller.HasOID())
	{
		if (SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)))
		{
			if (FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))))
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID;
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CModule1::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if (m_spCyclicCaller)
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller = NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}
