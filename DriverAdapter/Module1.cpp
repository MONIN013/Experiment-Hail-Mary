driveradapter::AxisParameters MakeAxisParameters(const ST_DriverChannelParams& source)
{
	return {
		static_cast<std::uint32_t>(source.encoderResolution),
		source.ratedCurrentA,
		source.maxCurrentA,
		static_cast<std::int32_t>(source.positionSign),
		static_cast<std::int32_t>(source.velocitySign),
		static_cast<std::int32_t>(source.currentSign),
		(source.enableRelativePosition != false)
	};
}

driveradapter::Inputs MakeInputs(const Module1Inputs& source)
{
	return {
		{
			static_cast<std::int32_t>(source.motorRaw.positionActualValue),
			static_cast<std::int32_t>(source.motorRaw.velocityActualValue),
			static_cast<std::int16_t>(source.motorRaw.torqueActualValue),
			static_cast<std::uint16_t>(source.motorRaw.statusWord)
		},
		{
			static_cast<std::int32_t>(source.loadRaw.positionActualValue),
			static_cast<std::int32_t>(source.loadRaw.velocityActualValue),
			static_cast<std::int16_t>(source.loadRaw.torqueActualValue),
			static_cast<std::uint16_t>(source.loadRaw.statusWord)
		},
		source.controlInput,
		source.distValue,
		static_cast<std::uint16_t>(source.motorControlWordIn),
		static_cast<std::uint16_t>(source.loadControlWordIn),
		(source.enableCurrentOutput != false),
		(source.playbackDone != false),
		(source.resetReq != false)
	};
}

void CopyOutputs(const driveradapter::Outputs& source, Module1Outputs& destination)
{
	destination.motor.positionAbs = source.motor.positionAbs;
	destination.motor.positionRel = source.motor.positionRel;
	destination.motor.velocityAct = source.motor.velocityAct;
	destination.motor.currentAct = source.motor.currentAct;
	destination.load.positionAbs = source.load.positionAbs;
	destination.load.positionRel = source.load.positionRel;
	destination.load.velocityAct = source.load.velocityAct;
	destination.load.currentAct = source.load.currentAct;
	destination.currentCmd = source.currentCmd;
	destination.targetTorque = static_cast<SHORT>(source.targetTorque);
	destination.motorControlWordOut = static_cast<USHORT>(source.motorControlWordOut);
	destination.loadControlWordOut = static_cast<USHORT>(source.loadControlWordOut);
	destination.motorStatusWordOut = static_cast<USHORT>(source.motorStatusWordOut);
	destination.loadStatusWordOut = static_cast<USHORT>(source.loadStatusWordOut);
	destination.safetyTrip = source.safetyTrip;
	destination.safetyCode = source.safetyCode;
}
