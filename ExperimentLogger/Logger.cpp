///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CLogger::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	HRESULT hr = S_OK;

	(void)ipTask;
	(void)ipCaller;
	(void)context;

	const bool loggingNow = IsLoggingRequested();
	const bool rising = (!m_prevLogging && loggingNow);
	const bool falling = (m_prevLogging && !loggingNow);

	if (rising)
	{
		ResetStatus();
		hr = StartLoggingRun();
		if (FAILED(hr))
		{
			m_runFaulted = true;
		}
	}

	if (loggingNow && m_isFileOpen && !m_runFaulted)
	{
		hr = AppendCurrentInputsAsRecord();
		if (FAILED(hr))
		{
			m_runFaulted = true;
			CloseFileHandle();
		}
		else if (m_bufferCount >= kBufferRecords)
		{
			hr = FlushBuffer();
			if (FAILED(hr))
			{
				m_runFaulted = true;
				CloseFileHandle();
			}
		}
	}

	if (falling)
	{
		(void)StopLoggingRun();
	}

	m_Outputs.LogStatus.file_size_kb = static_cast<ULONG>(m_bytesWritten / 1024ULL);
	m_prevLogging = loggingNow;

	return hr;
}
///</AutoGeneratedContent>

void CLogger::ResetRuntimeState()
{
	(void)StopLoggingRun();
	m_prevLogging = false;
	m_runFaulted = false;
	m_bufferCount = 0;
	m_seqCounter = 0;
	m_bytesWritten = 0;
	memset(m_latchedPath, 0, sizeof(m_latchedPath));
}

void CLogger::ResetStatus()
{
	m_Outputs.LogStatus.records_written = 0;
	m_Outputs.LogStatus.file_size_kb = 0;
	m_Outputs.LogStatus.error_code = 0;
}

void CLogger::SetErrorCode(ULONG code)
{
	m_Outputs.LogStatus.error_code = code;
	m_runFaulted = true;
}

bool CLogger::IsLoggingRequested() const
{
	return m_LogControl.logging;
}

double CLogger::SanitizeFinite(double v) const
{
	return std::isfinite(v) ? v : 0.0;
}

HRESULT CLogger::StartLoggingRun()
{
	CloseFileHandle();
	m_bufferCount = 0;
	m_seqCounter = 0;
	m_bytesWritten = 0;
	m_runFaulted = false;
	memset(m_latchedPath, 0, sizeof(m_latchedPath));
	memset(m_buffer, 0, sizeof(m_buffer));

	const CHAR* srcPath = reinterpret_cast<const CHAR*>(m_LogControl.file_path);
	if (srcPath == NULL || srcPath[0] == '\0')
	{
		SetErrorCode(1);
		return E_FAIL;
	}

	std::strncpy(m_latchedPath, srcPath, sizeof(m_latchedPath) - 1);
	m_latchedPath[sizeof(m_latchedPath) - 1] = '\0';

	m_hFile = CreateFileA(
		m_latchedPath,
		GENERIC_WRITE,
		FILE_SHARE_READ,
		NULL,
		CREATE_ALWAYS,
		FILE_ATTRIBUTE_NORMAL,
		NULL);

	if (m_hFile == INVALID_HANDLE_VALUE)
	{
		m_isFileOpen = false;
		SetErrorCode(2);
		return E_FAIL;
	}

	m_isFileOpen = true;
	return S_OK;
}

HRESULT CLogger::AppendCurrentInputsAsRecord()
{
	if (!m_isFileOpen)
	{
		SetErrorCode(3);
		return E_FAIL;
	}
	if (m_bufferCount >= kBufferRecords)
	{
		SetErrorCode(3);
		return E_FAIL;
	}

	LogRecordDisk record = {};
	++m_seqCounter;
	record.seq = static_cast<ULONG>(m_seqCounter);
	record.reserved = 0;
	record.t_ns = m_seqCounter * kTaskDtNs;
	record.motor_position = SanitizeFinite(m_Inputs.motor_position);
	record.motor_velocity = SanitizeFinite(m_Inputs.motor_velocity);
	record.motor_torque_act = SanitizeFinite(m_Inputs.motor_torque_act);
	record.load_position = SanitizeFinite(m_Inputs.load_position);
	record.load_velocity = SanitizeFinite(m_Inputs.load_velocity);
	record.torque_cmd = SanitizeFinite(m_Inputs.torque_cmd);
	record.error = SanitizeFinite(m_Inputs.error);
	record.ref_value = SanitizeFinite(m_Inputs.ref_value);
	record.ff_value = SanitizeFinite(m_Inputs.ff_value);
	record.control_input = SanitizeFinite(m_Inputs.control_input);

	m_buffer[m_bufferCount] = record;
	++m_bufferCount;
	++m_Outputs.LogStatus.records_written;

	return S_OK;
}

HRESULT CLogger::FlushBuffer()
{
	if (!m_isFileOpen)
	{
		return (m_bufferCount == 0) ? S_OK : E_FAIL;
	}
	if (m_bufferCount == 0)
	{
		return S_OK;
	}

	const DWORD bytesToWrite = static_cast<DWORD>(m_bufferCount * sizeof(LogRecordDisk));
	DWORD bytesWritten = 0;
	const BOOL ok = WriteFile(
		m_hFile,
		reinterpret_cast<const void*>(m_buffer),
		bytesToWrite,
		&bytesWritten,
		NULL);

	if (!ok)
	{
		SetErrorCode(3);
		return E_FAIL;
	}
	if (bytesWritten != bytesToWrite)
	{
		SetErrorCode(4);
		return E_FAIL;
	}

	m_bytesWritten += static_cast<ULONGLONG>(bytesWritten);
	m_bufferCount = 0;
	return S_OK;
}

HRESULT CLogger::StopLoggingRun()
{
	HRESULT hr = S_OK;

	if (!m_isFileOpen)
	{
		m_bufferCount = 0;
		return S_OK;
	}

	if (FAILED(FlushBuffer()))
	{
		hr = E_FAIL;
	}

	if (m_hFile != INVALID_HANDLE_VALUE)
	{
		if (!FlushFileBuffers(m_hFile))
		{
			SetErrorCode(5);
			hr = E_FAIL;
		}
	}

	CloseFileHandle();
	m_bufferCount = 0;
	m_Outputs.LogStatus.file_size_kb = static_cast<ULONG>(m_bytesWritten / 1024ULL);

	return hr;
}

void CLogger::CloseFileHandle()
{
	if (m_hFile != INVALID_HANDLE_VALUE)
	{
		if (!CloseHandle(m_hFile))
		{
			SetErrorCode(6);
		}
	}
	m_hFile = INVALID_HANDLE_VALUE;
	m_isFileOpen = false;
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CLogger::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID; 
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CLogger::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if ( m_spCyclicCaller )
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller	= NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}

