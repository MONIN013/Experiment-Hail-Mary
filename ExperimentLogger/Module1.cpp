///////////////////////////////////////////////////////////////////////////////
// State transition from PREOP to SAFEOP
//
// Initialize input parameters 
// Allocate memory
HRESULT CModule1::SetObjStatePS(PTComInitDataHdr pInitData)
{
	m_Trace.Log(tlVerbose, FENTERA_STR());
	HRESULT hr = S_OK;
	IMPLEMENT_ITCOMOBJECT_EVALUATE_INITDATA(pInitData);

	ResetRuntimeState();
	UpdateStatusOutputs();

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// State transition from SAFEOP to OP
//
// Register with other TwinCAT objects
HRESULT CModule1::SetObjStateSO()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());
	HRESULT hr = S_OK;

	UpdateStatusOutputs();


	// If following call is successful the CycleUpdate method will be called, 
	// possibly even before method has been left.
	hr = FAILED(hr) ? hr : AddModuleToCaller(); 

	// Cleanup if transition failed at some stage
	if ( FAILED(hr) )
	{
		RemoveModuleFromCaller(); 
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// State transition from OP to SAFEOP
HRESULT CModule1::SetObjStateOS()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;

	RemoveModuleFromCaller(); 
	CloseLogFile(true);
	UpdateStatusOutputs();
	if (m_fileFsmState != EFileFsmState::IDLE)
	{
		AbortSession(true);
		m_fileFsmState = EFileFsmState::IDLE;
	}
	m_spFileAccessAsync = NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// State transition from SAFEOP to PREOP
HRESULT CModule1::SetObjStateSP()
{
	HRESULT hr = S_OK;
	m_Trace.Log(tlVerbose, FENTERA_STR());

	CloseLogFile(false);
	ResetRuntimeState();
	UpdateStatusOutputs();
	m_spFileAccessAsync = NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CModule1::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	HRESULT hr = S_OK;
	(void)ipCaller;
	(void)context;

	m_bootDiagStage = 1;
	const bool isAsyncState = (m_fileFsmState == EFileFsmState::OPEN_WAIT)
		|| (m_fileFsmState == EFileFsmState::WRITE_WAIT)
		|| (m_fileFsmState == EFileFsmState::CLOSE_WAIT);
	const bool canSampleTaskCycle = (ipTask != NULL)
		&& !isAsyncState
		&& (m_cycleCounter >= kTimestampInitSkipCycles);
	if (canSampleTaskCycle)
	{
		UpdateTimestampStepFromTask(ipTask);
	}
	if (m_cycleCounter < 0xFFFFFFFFUL)
	{
		++m_cycleCounter;
	}
	if (m_cycleCounter >= kTimestampInitSkipCycles && m_bootDiagStage < 4)
	{
		m_bootDiagStage = 0;
	}

	const bool resetEdge = (m_Inputs.resetReq != false) && !m_prevResetReq;
	m_prevResetReq = (m_Inputs.resetReq != false);
	if (resetEdge)
	{
		CloseLogFile(true);
		ResetRuntimeState();
	}

	const bool loggingCmd = (m_Inputs.loggingReq != false) || (m_LogControl.logging != false);
	bool risingEdge = loggingCmd && !m_prevLoggingCommand;
	bool fallingEdge = !loggingCmd && m_prevLoggingCommand;
	if (resetEdge)
	{
		risingEdge = false;
		fallingEdge = false;
	}

	if (risingEdge)
	{
		CloseLogFile(true);
		ResetRuntimeState();
		if (!StartAsyncOpen())
		{
			m_fileFsmState = EFileFsmState::ERROR;
			m_sessionFailed = true;
		}
	}
	m_bootDiagStage = 2;

	switch (m_fileFsmState)
	{
	case EFileFsmState::OPEN_WAIT:
		if (PollAsyncOp())
		{
			m_fileFsmState = EFileFsmState::ACTIVE;
			m_isLoggingActive = true;
			ClearError();
			if (!loggingCmd)
			{
				CloseLogFile(true);
			}
		}
		break;
	case EFileFsmState::WRITE_WAIT:
		if (PollAsyncOp())
		{
			if (m_lastWriteBytes != m_pendingWriteBytes)
			{
				SetError(kErrAsyncWriteShort);
				AbortSession(true);
				m_fileFsmState = EFileFsmState::ERROR;
				break;
			}
			m_bytesWritten += static_cast<ULONGLONG>(m_lastWriteBytes);
			m_bufferCount = 0;
			m_pendingWriteBytes = 0;
			m_lastWriteBytes = 0;
			if (m_isLoggingActive)
			{
				m_fileFsmState = EFileFsmState::ACTIVE;
			}
			else
			{
				m_fileFsmState = EFileFsmState::ACTIVE;
				CloseLogFile(false);
			}
		}
		break;
	case EFileFsmState::CLOSE_WAIT:
		if (PollAsyncOp())
		{
			m_fileHandle = 0;
			m_fileFsmState = EFileFsmState::IDLE;
			m_isLoggingActive = false;
		}
		break;
	case EFileFsmState::IDLE:
	case EFileFsmState::ACTIVE:
	case EFileFsmState::ERROR:
	default:
		break;
	}
	m_bootDiagStage = 3;

	if (loggingCmd && m_fileFsmState == EFileFsmState::ACTIVE && !m_sessionFailed)
	{
		if (!AppendCurrentInputsAsRecord())
		{
			m_fileFsmState = EFileFsmState::ERROR;
		}
		else if (m_bufferCount >= kBufferRecords)
		{
			if (!StartAsyncWrite())
			{
				m_fileFsmState = EFileFsmState::ERROR;
			}
		}
	}

	if (fallingEdge)
	{
		CloseLogFile(true);
	}

	m_prevLoggingCommand = loggingCmd;
	if (m_bootDiagStage != 0)
	{
		m_bootDiagStage = 4;
	}
	UpdateStatusOutputs();

	return hr;
}
