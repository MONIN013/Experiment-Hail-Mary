///////////////////////////////////////////////////////////////////////////////
// State transition from PREOP to SAFEOP
// MARK: PREOP to SAFEOP
// Initialize input parameters 
// Allocate memory
HRESULT CModule1::SetObjStatePS(PTComInitDataHdr pInitData)
{
	m_Trace.Log(tlVerbose, FENTERA_STR());
	HRESULT hr = S_OK;
	IMPLEMENT_ITCOMOBJECT_EVALUATE_INITDATA(pInitData);

	ResetRuntimeState();

	// Create file access async object during PREOP→SAFEOP transition
	// (following TC1300 S20-FileIOWrite pattern: create + configure + SAFEOP here,
	//  OP transition deferred to SetObjStateSO)
	hr = FAILED(hr) ? hr : m_spSrv->TcCreateInstance(
		CID_TcFileAccessAsync,
		IID_ITcFileAccessAsync,
		(PPVOID)&m_spFileAccessAsync);
	if (SUCCEEDED(hr) && m_spFileAccessAsync)
	{
		hr = InitializeFileAccessAsyncObject();
		if (SUCCEEDED(hr))
		{
			m_fileAccessAsyncInitialized = true;
		}
		else
		{
			m_spFileAccessAsync = NULL;
			m_fileAccessAsyncInitialized = false;
		}
	}

	UpdateStatusOutputs();

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// State transition from SAFEOP to OP
// MARK: SAFEOP to OP
// Register with other TwinCAT objects
HRESULT CModule1::SetObjStateSO()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());
	HRESULT hr = S_OK;

	// Transition file access async object to OP
	// (following TC1300 S20-FileIOWrite pattern: OP transition in SAFEOP→OP)
	if (m_spFileAccessAsync)
	{
		hr = TransitionFileAccessAsyncToState(TCOM_STATE_OP);
	}

	UpdateStatusOutputs();

	// If following call is successful the CycleUpdate method will be called, 
	// possibly even before method has been left.
	hr = FAILED(hr) ? hr : AddModuleToCaller(); 

	// Cleanup if transition failed at some stage
	if ( FAILED(hr) )
	{
		RemoveModuleFromCaller(); 
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// State transition from OP to SAFEOP
// MARK: OP to SAFEOP
HRESULT CModule1::SetObjStateOS()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;

	RemoveModuleFromCaller();
	// This logger must stop any active session when leaving OP so that open
	// file handles are not kept across runtime state changes. m_sessionFailed
	// is left set here and is cleared explicitly by ResetRuntimeState() before
	// the next session starts.
	AbortSession(true);
	m_fileFsmState = EFileFsmState::IDLE;
	m_lastAsyncHr = S_OK;
	m_reopenRequested = false;

	UpdateStatusOutputs();

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// State transition from SAFEOP to PREOP
// MARK: SAFEOP to PREOP
HRESULT CModule1::SetObjStateSP()
{
	HRESULT hr = S_OK;
	m_Trace.Log(tlVerbose, FENTERA_STR());

	// Drop the COM pointer without forcing SAFEOP->PREOP. TC1300 keeps this
	// transition simple, and ResetRuntimeState() still clears our session data.
	m_spFileAccessAsync = NULL;
	m_fileAccessAsyncInitialized = false;
	ResetRuntimeState();
	UpdateStatusOutputs();

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CModule1::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	HRESULT hr = S_OK;
	(void)ipCaller;
	(void)context;

	const bool isAsyncState = (m_fileFsmState == EFileFsmState::OPEN_WAIT)
		|| (m_fileFsmState == EFileFsmState::WRITE_WAIT)
		|| (m_fileFsmState == EFileFsmState::CLOSE_WAIT);
	const bool canSampleTaskCycle = (ipTask != NULL)
		&& !isAsyncState
		&& (m_cycleCounter >= kTimestampInitSkipCycles);
	if (canSampleTaskCycle)
	{
		UpdateTimestampStepFromTask(ipTask);
	}
	if (m_cycleCounter < 0xFFFFFFFFUL)
	{
		++m_cycleCounter;
	}

	const bool resetCmd = (m_Inputs.control.resetReq != false);
	const bool preArmCmd = (m_Inputs.control.preArmReq != false);
	const bool loggingCmd = (m_Inputs.control.loggingReq != false);
	const bool playbackDone = (m_Inputs.control.playbackDone != false);
	const bool resetEdge = resetCmd && !m_prevResetReq;
	bool preArmRisingEdge = preArmCmd && !m_prevPreArmReq;
	bool preArmFallingEdge = !preArmCmd && m_prevPreArmReq;
	bool loggingRisingEdge = loggingCmd && !m_prevLoggingCommand;
	bool loggingFallingEdge = !loggingCmd && m_prevLoggingCommand;

	if (resetEdge)
	{
		m_resetPending = true;
		CloseLogFile(true);
		if (m_fileFsmState != EFileFsmState::OPEN_WAIT
			&& m_fileFsmState != EFileFsmState::WRITE_WAIT
			&& m_fileFsmState != EFileFsmState::CLOSE_WAIT)
		{
			ResetRuntimeState();
		}
	}

	if (resetEdge || m_resetPending)
	{
		preArmRisingEdge = false;
		preArmFallingEdge = false;
		loggingRisingEdge = false;
		loggingFallingEdge = false;
	}

	switch (m_fileFsmState)
	{
	case EFileFsmState::OPEN_WAIT:
		switch (PollAsyncOp())
		{
		case EAsyncPollResult::Completed:
			m_fileFsmState = EFileFsmState::ACTIVE;
			if (!ValidateOpenedFileHandle(kErrOpenCompletedWithoutHandle))
			{
				if (m_resetPending)
				{
					ResetRuntimeState();
				}
				break;
			}
			if (!m_sessionFailed)
			{
				ClearError();
			}
			if (m_closeRequested || m_resetPending || (!preArmCmd && !loggingCmd))
			{
				CloseLogFile(m_closeFlushRequested || m_resetPending || (!preArmCmd && !loggingCmd));
			}
			break;
		case EAsyncPollResult::Failed:
			AbortSession(true);
			m_fileFsmState = EFileFsmState::ERROR;
			if (m_resetPending)
			{
				ResetRuntimeState();
			}
			break;
		case EAsyncPollResult::Pending:
		default:
			break;
		}
		break;
	case EFileFsmState::WRITE_WAIT:
		switch (PollAsyncOp())
		{
		case EAsyncPollResult::Completed:
			if (m_lastWriteBytes != m_pendingWriteBytes)
			{
				SetError(kErrAsyncWriteShort);
				AbortSession(true);
				m_fileFsmState = EFileFsmState::ERROR;
				break;
			}
			m_bytesWritten += static_cast<ULONGLONG>(m_lastWriteBytes);
			if (m_pendingWriteBufferIndex < 2UL)
			{
				m_bufferCounts[m_pendingWriteBufferIndex] = 0;
			}
			m_pendingWriteBufferIndex = 0;
			m_pendingWriteRecords = 0;
			m_pendingWriteBytes = 0;
			m_lastWriteBytes = 0;
			m_fileFsmState = EFileFsmState::ACTIVE;
			if (m_closeRequested || !m_isLoggingActive)
			{
				CloseLogFile(m_closeFlushRequested);
			}
			else
			{
				m_closeFlushRequested = false;
			}
			break;
		case EAsyncPollResult::Failed:
			AbortSession(true);
			m_fileFsmState = EFileFsmState::ERROR;
			if (m_resetPending)
			{
				ResetRuntimeState();
			}
			break;
		case EAsyncPollResult::Pending:
		default:
			break;
		}
		break;
	case EFileFsmState::CLOSE_WAIT:
		switch (PollAsyncOp())
		{
		case EAsyncPollResult::Completed:
			m_fileHandle = 0;
			m_fileFsmState = EFileFsmState::IDLE;
			m_isLoggingActive = false;
			m_closeRequested = false;
			m_closeFlushRequested = false;
			m_fileReleased = (m_errorCode == 0);
			if (m_resetPending)
			{
				ResetRuntimeState();
			}
			break;
		case EAsyncPollResult::Failed:
			AbortSession(true);
			m_fileFsmState = EFileFsmState::ERROR;
			if (m_resetPending)
			{
				ResetRuntimeState();
			}
			break;
		case EAsyncPollResult::Pending:
		default:
			break;
		}
		break;
	case EFileFsmState::IDLE:
	case EFileFsmState::ACTIVE:
	case EFileFsmState::ERROR:
	default:
		break;
	}

	// Handle deferred reopen: when a preArmRisingEdge occurred during a pending
	// async operation, the reopen is deferred until the operation completes.
	if (m_reopenRequested && !m_resetPending)
	{
		const bool canReopen = (m_fileFsmState == EFileFsmState::IDLE)
			|| (m_fileFsmState == EFileFsmState::ERROR);
		if (canReopen)
		{
			m_reopenRequested = false;
			ResetRuntimeState();
			if (!StartAsyncOpen())
			{
				m_fileFsmState = EFileFsmState::ERROR;
				m_sessionFailed = true;
			}
		}
	}

	if (preArmRisingEdge)
	{
		const bool isPending = (m_fileFsmState == EFileFsmState::OPEN_WAIT)
			|| (m_fileFsmState == EFileFsmState::WRITE_WAIT)
			|| (m_fileFsmState == EFileFsmState::CLOSE_WAIT);
		if (isPending)
		{
			// Cannot start a new file open while an async operation is in progress.
			// Request close and defer the reopen until the operation completes.
			m_closeRequested = true;
			m_closeFlushRequested = false;
			m_reopenRequested = true;
		}
		else
		{
			CloseLogFile(true);
			ResetRuntimeState();
			if (!StartAsyncOpen())
			{
				m_fileFsmState = EFileFsmState::ERROR;
				m_sessionFailed = true;
			}
		}
	}

	if (loggingRisingEdge)
	{
		if (!IsLoggerReady())
		{
			SetError(kErrLoggingNotPreArmed);
			m_sessionFailed = true;
		}
		else
		{
			m_isLoggingActive = true;
		}
	}

	const bool allowAppend = loggingCmd && !loggingRisingEdge && !playbackDone && !m_resetPending;
	if (allowAppend && !m_sessionFailed)
	{
		if (!AppendCurrentInputsAsRecord())
		{
			m_fileFsmState = EFileFsmState::ERROR;
		}
	}

	if (loggingFallingEdge)
	{
		CloseLogFile(true);
	}
	else if (preArmFallingEdge && !loggingCmd)
	{
		CloseLogFile(true);
	}

	m_prevResetReq = resetCmd;
	m_prevPreArmReq = m_resetPending ? false : preArmCmd;
	m_prevLoggingCommand = m_resetPending ? false : loggingCmd;
	UpdateStatusOutputs();

	return hr;
}
