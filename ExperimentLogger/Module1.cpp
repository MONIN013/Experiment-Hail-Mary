void CModule1::ResetRuntimeState()
{
	m_activeBufferIndex = 0;
	m_bufferCounts[0] = 0;
	m_bufferCounts[1] = 0;
	m_pendingWriteBufferIndex = 0;
	m_pendingWriteRecords = 0;
	m_seq = 0;
	m_recordsWritten = 0;
	m_bytesWritten = 0;
	m_errorCode = 0;
	m_isLoggingActive = false;
	m_sessionFailed = false;
	m_resetPending = false;
	m_closeRequested = false;
	m_closeFlushRequested = false;
	m_fileReleased = false;
	m_reopenRequested = false;
	m_pendingWriteBytes = 0;
	m_lastWriteBytes = 0;
	m_lastAsyncHr = S_OK;
	m_fileHandle = 0;
	m_fileFsmState = EFileFsmState::IDLE;
	m_timestampStepNsRuntime = kDefaultTimestampStepNs;
	m_cycleCounter = 0;
}

void CModule1::UpdateTimestampStepFromTask(ITcTask* ipTask)
{
	if (ipTask == NULL)
	{
		return;
	}

	ULONG cycleTimeNs = 0;
	if (SUCCEEDED(ipTask->GetCycleTime(&cycleTimeNs)) && cycleTimeNs != 0)
	{
		m_timestampStepNsRuntime = static_cast<ULONGLONG>(cycleTimeNs);
	}
}

HRESULT CModule1::EnsureFileAccessAsync()
{
	if (m_spFileAccessAsync && m_fileAccessAsyncInitialized)
	{
		return S_OK;
	}

	// File access async object must be created during module lifecycle
	// transitions (SetObjStatePS/SO).  If it is missing here, the module
	// was not initialised correctly.
	SetError(static_cast<HRESULT>(kErrAsyncCreateFailed));
	return E_FAIL;
}

HRESULT CModule1::InitializeFileAccessAsyncObject()
{
	if (!m_spFileAccessAsync)
	{
		return E_POINTER;
	}

	ITComObjectPtr spFileAccessObj = m_spFileAccessAsync;
	if (!spFileAccessObj)
	{
		return E_NOINTERFACE;
	}

	if (!m_spCyclicCaller.HasOID())
	{
		return ADS_E_INVALIDOBJID;
	}

	OTCID taskOid = m_spCyclicCaller.GetOID();
	HRESULT hr = spFileAccessObj->TcSetObjPara(
		PID_TcFileAccessAsyncAdsProvider,
		sizeof(taskOid),
		&taskOid);
	if (FAILED(hr))
	{
		return hr;
	}

	ULONG segmentSize = kFileAccessSegmentSize;
	hr = spFileAccessObj->TcSetObjPara(
		PID_TcFileAccessAsyncSegmentSize,
		sizeof(segmentSize),
		&segmentSize);
	if (FAILED(hr))
	{
		return hr;
	}

	ULONG timeoutMs = kFileAccessTimeoutMs;
	hr = spFileAccessObj->TcSetObjPara(
		PID_TcFileAccessAsyncTimeoutMs,
		sizeof(timeoutMs),
		&timeoutMs);
	if (FAILED(hr))
	{
		return hr;
	}

	hr = TransitionFileAccessAsyncToState(TCOM_STATE_SAFEOP);
	if (FAILED(hr))
	{
		return hr;
	}

	// OP transition is performed separately in SetObjStateSO()
	return S_OK;
}

HRESULT CModule1::TransitionFileAccessAsyncToState(TCOM_STATE state)
{
	if (!m_spFileAccessAsync)
	{
		return E_POINTER;
	}

	ITComObjectPtr spFileAccessObj = m_spFileAccessAsync;
	if (!spFileAccessObj)
	{
		return E_NOINTERFACE;
	}

	return spFileAccessObj->TcSetObjState(state, m_spSrv, NULL);
}

void CModule1::ReleaseFileAccessAsyncObject(bool transitionToPreOp)
{
	if (!m_spFileAccessAsync)
	{
		m_fileAccessAsyncInitialized = false;
		return;
	}

	const bool isPending = (m_fileFsmState == EFileFsmState::OPEN_WAIT)
		|| (m_fileFsmState == EFileFsmState::WRITE_WAIT)
		|| (m_fileFsmState == EFileFsmState::CLOSE_WAIT);
	if (!isPending)
	{
		(void)TransitionFileAccessAsyncToState(TCOM_STATE_SAFEOP);
		if (transitionToPreOp)
		{
			(void)TransitionFileAccessAsyncToState(TCOM_STATE_PREOP);
		}
	}

	m_spFileAccessAsync = NULL;
	m_fileAccessAsyncInitialized = false;
}

void CModule1::AbortSession(bool keepError)
{
	m_isLoggingActive = false;
	m_sessionFailed = true;
	m_closeRequested = false;
	m_closeFlushRequested = false;
	m_fileReleased = false;
	if (!keepError)
	{
		ClearError();
	}
	const bool isPending = (m_fileFsmState == EFileFsmState::OPEN_WAIT
		|| m_fileFsmState == EFileFsmState::WRITE_WAIT
		|| m_fileFsmState == EFileFsmState::CLOSE_WAIT);
	if (!isPending && m_spFileAccessAsync && IsFileHandleValid(m_fileHandle))
	{
		(void)m_spFileAccessAsync->FileClose(m_fileHandle);
	}
	m_fileHandle = 0;
	m_pendingWriteBufferIndex = 0;
	m_pendingWriteRecords = 0;
	m_pendingWriteBytes = 0;
	m_lastWriteBytes = 0;
	m_bufferCounts[0] = 0;
	m_bufferCounts[1] = 0;
}

void CModule1::TeardownSession(bool transitionToPreOp, bool keepError, EFileFsmState finalState)
{
	AbortSession(keepError);
	ReleaseFileAccessAsyncObject(transitionToPreOp);
	m_fileFsmState = finalState;
	if (finalState == EFileFsmState::IDLE)
	{
		m_lastAsyncHr = S_OK;
	}
}

void CModule1::CloseLogFile(bool flushRemaining)
{
	if (m_fileFsmState == EFileFsmState::OPEN_WAIT || m_fileFsmState == EFileFsmState::WRITE_WAIT || m_fileFsmState == EFileFsmState::CLOSE_WAIT)
	{
		m_closeRequested = true;
		m_closeFlushRequested = m_closeFlushRequested || flushRemaining;
		m_isLoggingActive = false;
		return;
	}

	const bool shouldFlush = flushRemaining || m_closeFlushRequested;
	m_closeRequested = false;
	m_closeFlushRequested = false;

	if (!IsFileHandleValid(m_fileHandle))
	{
		m_fileHandle = 0;
		m_isLoggingActive = false;
		if (shouldFlush)
		{
			m_bufferCounts[0] = 0;
			m_bufferCounts[1] = 0;
			m_pendingWriteBufferIndex = 0;
			m_pendingWriteRecords = 0;
			m_pendingWriteBytes = 0;
			m_lastWriteBytes = 0;
		}
		m_fileFsmState = EFileFsmState::IDLE;
		m_fileReleased = (m_errorCode == 0);
		return;
	}

	if (shouldFlush && HasBufferedRecords())
	{
		while (HasBufferedRecords())
		{
			if (!FlushBuffer())
			{
				AbortSession(true);
				m_fileFsmState = EFileFsmState::ERROR;
				m_isLoggingActive = false;
				return;
			}
			if (m_fileFsmState == EFileFsmState::WRITE_WAIT)
			{
				m_closeRequested = true;
				m_closeFlushRequested = shouldFlush;
				m_isLoggingActive = false;
				return;
			}
		}
	}

	if (!StartAsyncClose())
	{
		AbortSession(true);
		m_fileFsmState = EFileFsmState::ERROR;
		return;
	}
	m_isLoggingActive = false;
}

bool CModule1::FlushBuffer()
{
	const ULONG idx = CurrentBufferIndex();
	if (m_bufferCounts[idx] == 0)
	{
		return true;
	}
	if (m_fileFsmState != EFileFsmState::ACTIVE || HasPendingWrite())
	{
		SetError(kErrBufferFlushPending);
		m_sessionFailed = true;
		return false;
	}
	return StartAsyncWrite();
}

bool CModule1::AppendCurrentInputsAsRecord()
{
	ULONG idx = CurrentBufferIndex();
	if (m_bufferCounts[idx] >= kBufferRecords)
	{
		if (!FlushBuffer())
		{
			return false;
		}
		idx = CurrentBufferIndex();
		if (m_bufferCounts[idx] >= kBufferRecords)
		{
			SetError(kErrBufferFlushPending);
			m_sessionFailed = true;
			return false;
		}
	}

	LogRecord& rec = m_logBuffers[idx][m_bufferCounts[idx]];
	rec.seq = m_seq;
	rec.reservedPad0 = 0;
	rec.tNs = static_cast<ULONGLONG>(m_seq) * m_timestampStepNsRuntime;
	rec.motorPosition = m_Inputs.record.motor.position;
	rec.motorVelocity = m_Inputs.record.motor.velocity;
	rec.motorCurrentAct = m_Inputs.record.motor.currentAct;
	rec.loadPosition = m_Inputs.record.load.position;
	rec.loadVelocity = m_Inputs.record.load.velocity;
	rec.currentCmd = m_Inputs.record.currentCmd;
	rec.error = m_Inputs.record.error;
	rec.refValue = m_Inputs.record.refValue;
	rec.ffValue = m_Inputs.record.ffValue;
	rec.controlInput = m_Inputs.record.controlInput;

	++m_bufferCounts[idx];
	++m_seq;
	++m_recordsWritten;

	if (m_bufferCounts[idx] >= kBufferRecords)
	{
		return FlushBuffer();
	}
	return true;
}

bool CModule1::HasPendingWrite() const
{
	return m_pendingWriteRecords > 0;
}

bool CModule1::HasBufferedRecords() const
{
	return (m_bufferCounts[0] > 0) || (m_bufferCounts[1] > 0);
}

ULONG CModule1::CurrentBufferIndex() const
{
	return m_activeBufferIndex & 0x1UL;
}

ULONG CModule1::InactiveBufferIndex() const
{
	return CurrentBufferIndex() ^ 0x1UL;
}

void CModule1::UpdateStatusOutputs()
{
	m_Outputs.status.recordsWritten = m_recordsWritten;
	m_Outputs.status.fileSizeKb = static_cast<ULONG>(m_bytesWritten / 1024ULL);
	m_Outputs.status.errorCode = m_errorCode;
	m_Outputs.status.loggerReady = IsLoggerReady();
	m_Outputs.status.fileReleased = m_fileReleased;
}

void CModule1::ResolveFilePath(char* dst, size_t dstSize) const
{
	if (dst == NULL || dstSize == 0)
	{
		return;
	}

	const char* src = kDefaultLogPath;
	const size_t customCap = sizeof(m_LogControl.filePath);
	size_t customLen = 0;
	while (customLen < customCap && m_LogControl.filePath[customLen] != '\0')
	{
		++customLen;
	}
	if (customLen > 0)
	{
		src = m_LogControl.filePath;
	}

	size_t len = 0;
	const size_t srcCap = (src == m_LogControl.filePath) ? customLen : std::strlen(src);
	while (len + 1 < dstSize && len < srcCap && src[len] != '\0')
	{
		dst[len] = src[len];
		++len;
	}
	dst[len] = '\0';
	dst[dstSize - 1] = '\0';
}

bool CModule1::ValidateFilePath(const char* filePath)
{
	if (filePath == NULL || filePath[0] == '\0')
	{
		SetError(kErrInvalidPath);
		return false;
	}
	return true;
}

void CModule1::SetError(HRESULT errorCode)
{
	if (errorCode != 0)
	{
		m_errorCode = static_cast<ULONG>(errorCode);
	}
}

void CModule1::ClearError()
{
	m_errorCode = 0;
}

bool CModule1::ValidateOpenedFileHandle(HRESULT failureCode)
{
	if (IsFileHandleValid(m_fileHandle))
	{
		return true;
	}

	SetError(failureCode);
	m_sessionFailed = true;
	ReleaseFileAccessAsyncObject(false);
	m_fileFsmState = EFileFsmState::ERROR;
	return false;
}

bool CModule1::IsLoggerReady() const
{
	return (m_fileFsmState == EFileFsmState::ACTIVE)
		&& IsFileHandleValid(m_fileHandle)
		&& !m_closeRequested
		&& !m_sessionFailed;
}

bool CModule1::StartAsyncOpen()
{
	if (m_fileFsmState == EFileFsmState::OPEN_WAIT || m_fileFsmState == EFileFsmState::WRITE_WAIT || m_fileFsmState == EFileFsmState::CLOSE_WAIT)
	{
		SetError(kErrInvalidFsmState);
		m_sessionFailed = true;
		return false;
	}

	if (FAILED(EnsureFileAccessAsync()) || !m_spFileAccessAsync)
	{
		m_sessionFailed = true;
		return false;
	}

	memset(m_openPathBuffer, 0, sizeof(m_openPathBuffer));
	ResolveFilePath(m_openPathBuffer, sizeof(m_openPathBuffer));
	if (!ValidateFilePath(m_openPathBuffer))
	{
		m_sessionFailed = true;
		return false;
	}

	m_fileHandle = 0;
	m_isLoggingActive = false;
	m_closeRequested = false;
	m_closeFlushRequested = false;
	m_fileReleased = false;
	m_lastAsyncHr = S_OK;
	const HRESULT hr = m_spFileAccessAsync->FileOpen(
		m_openPathBuffer,
		amWriteBinary,
		&m_fileHandle);

	if (FAILED_AND_NOT_PENDING(hr))
	{
		SetError(hr);
		m_sessionFailed = true;
		return false;
	}
	if (FAILED(hr))
	{
		m_fileFsmState = EFileFsmState::OPEN_WAIT;
		return true;
	}

	m_fileFsmState = EFileFsmState::ACTIVE;
	m_isLoggingActive = false;
	m_sessionFailed = false;
	return ValidateOpenedFileHandle(kErrOpenCompletedWithoutHandle);
}

bool CModule1::StartAsyncWrite()
{
	if (m_fileFsmState != EFileFsmState::ACTIVE)
	{
		SetError(kErrInvalidFsmState);
		m_sessionFailed = true;
		return false;
	}

	if (!m_spFileAccessAsync || !IsFileHandleValid(m_fileHandle))
	{
		SetError(kErrInvalidFileHandle);
		m_sessionFailed = true;
		return false;
	}
	if (HasPendingWrite())
	{
		SetError(kErrBufferFlushPending);
		m_sessionFailed = true;
		return false;
	}

	const ULONG writeIdx = CurrentBufferIndex();
	const ULONG writeCount = m_bufferCounts[writeIdx];
	if (writeCount == 0)
	{
		return true;
	}

	const ULONG nextIdx = InactiveBufferIndex();
	if (m_bufferCounts[nextIdx] != 0)
	{
		SetError(kErrBufferFlushPending);
		m_sessionFailed = true;
		return false;
	}

	m_pendingWriteBufferIndex = writeIdx;
	m_pendingWriteRecords = writeCount;
	m_pendingWriteBytes = static_cast<UINT>(writeCount * sizeof(LogRecord));
	m_lastWriteBytes = 0;
	m_activeBufferIndex = nextIdx;
	HRESULT hr = m_spFileAccessAsync->FileWrite(
		m_fileHandle,
		static_cast<PCVOID>(&m_logBuffers[writeIdx][0]),
		m_pendingWriteBytes,
		reinterpret_cast<PUINT>(&m_lastWriteBytes));

	if (FAILED_AND_NOT_PENDING(hr))
	{
		SetError(hr);
		m_sessionFailed = true;
		m_activeBufferIndex = writeIdx;
		m_pendingWriteBufferIndex = 0;
		m_pendingWriteRecords = 0;
		m_pendingWriteBytes = 0;
		m_lastWriteBytes = 0;
		return false;
	}
	if (FAILED(hr))
	{
		m_fileFsmState = EFileFsmState::WRITE_WAIT;
		m_lastAsyncHr = S_OK;
		return true;
	}
	if (m_lastWriteBytes != m_pendingWriteBytes)
	{
		SetError(kErrAsyncWriteShort);
		m_sessionFailed = true;
		m_activeBufferIndex = writeIdx;
		m_pendingWriteBufferIndex = 0;
		m_pendingWriteRecords = 0;
		m_pendingWriteBytes = 0;
		m_lastWriteBytes = 0;
		return false;
	}

	m_bytesWritten += static_cast<ULONGLONG>(m_lastWriteBytes);
	m_bufferCounts[writeIdx] = 0;
	m_pendingWriteBufferIndex = 0;
	m_pendingWriteRecords = 0;
	m_pendingWriteBytes = 0;
	m_lastWriteBytes = 0;
	m_fileFsmState = EFileFsmState::ACTIVE;
	return true;
}

bool CModule1::StartAsyncClose()
{
	if (m_fileFsmState != EFileFsmState::ACTIVE
		&& m_fileFsmState != EFileFsmState::IDLE
		&& m_fileFsmState != EFileFsmState::ERROR)
	{
		SetError(kErrInvalidFsmState);
		m_sessionFailed = true;
		return false;
	}

	if (!m_spFileAccessAsync || !IsFileHandleValid(m_fileHandle))
	{
		m_fileHandle = 0;
		m_closeRequested = false;
		m_closeFlushRequested = false;
		m_fileFsmState = EFileFsmState::IDLE;
		return true;
	}

	const HRESULT hr = m_spFileAccessAsync->FileClose(m_fileHandle);
	if (FAILED_AND_NOT_PENDING(hr))
	{
		SetError(hr);
		m_sessionFailed = true;
		return false;
	}
	if (FAILED(hr))
	{
		m_fileFsmState = EFileFsmState::CLOSE_WAIT;
		m_lastAsyncHr = S_OK;
		return true;
	}

	m_fileHandle = 0;
	m_closeRequested = false;
	m_closeFlushRequested = false;
	m_fileFsmState = EFileFsmState::IDLE;
	m_fileReleased = (m_errorCode == 0);
	return true;
}

CModule1::EAsyncPollResult CModule1::PollAsyncOp()
{
	const bool isAsyncState = (m_fileFsmState == EFileFsmState::OPEN_WAIT)
		|| (m_fileFsmState == EFileFsmState::WRITE_WAIT)
		|| (m_fileFsmState == EFileFsmState::CLOSE_WAIT);
	if (!isAsyncState)
	{
		SetError(kErrInvalidFsmState);
		m_sessionFailed = true;
		return EAsyncPollResult::Failed;
	}

	if (!m_spFileAccessAsync)
	{
		SetError(kErrAsyncCreateFailed);
		m_sessionFailed = true;
		return EAsyncPollResult::Failed;
	}

	const HRESULT hr = m_spFileAccessAsync->Check();
	if (FAILED_AND_NOT_PENDING(hr))
	{
		m_lastAsyncHr = hr;
		SetError(hr);
		m_sessionFailed = true;
		return EAsyncPollResult::Failed;
	}
	if (SUCCEEDED(hr))
	{
		m_lastAsyncHr = hr;
		return EAsyncPollResult::Completed;
	}
	m_lastAsyncHr = hr;
	return EAsyncPollResult::Pending;
}

///////////////////////////////////////////////////////////////////////////////
HRESULT CModule1::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID; 
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CModule1::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if ( m_spCyclicCaller )
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller	= NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}
